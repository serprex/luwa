-- Tables are hash only for now. tbl.hash holds pairs: key at 2i, value at 2i+1.
-- Open addressing, probing forward. Keys are never removed, setting nil leaves the key
local M = require 'make'
local func = M.func

local alloc = require 'alloc'
local tbl, vals, int, float, R, typeof, types = alloc.tbl, alloc.vals, alloc.int, alloc.float, alloc.R, alloc.typeof, alloc.types

local _obj = require 'obj'
local hash, eq, hashi64 = _obj.hash, _obj.eq, _obj.hashi64

-- Pair index to start probing at, for hash h in a table with cap pairs
local function startpair(f, h, cap)
	f:load(h)
	f:load(cap)
	f:remu()
end

-- Put key & val in arr without checking for room, key isn't in arr yet. Used by rehash
local rawinsert = func(R.vals, V, V, i32, void, function(f, arr, key, val, h)
	local cap, i = f:locals(i32, 2)
	f:load(arr)
	f:arraylen()
	f:i32(1)
	f:shru()
	f:store(cap)
	startpair(f, h, cap)
	f:store(i)
	f:loop(function(loop)
		f:load(arr)
		f:load(i)
		f:i32(1)
		f:shl()
		f:arrayget(vals)
		f:refisnull()
		f:iff(function()
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:shl()
			f:load(key)
			f:arrayset(vals)
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:shl()
			f:i32(1)
			f:add()
			f:load(val)
			f:arrayset(vals)
			f:ret()
		end)
		f:load(i)
		f:i32(1)
		f:add()
		f:tee(i)
		f:load(cap)
		f:eq()
		f:iff(function()
			f:i32(0)
			f:store(i)
		end)
		f:br(loop)
	end)
end)

-- Double the hash part, dropping pairs whose value is nil
local rehash = func(R.tbl, void, function(f, tab)
	local old, new = f:locals(R.vals, 2)
	local i, n, cnt = f:locals(i32, 3)
	local k, v = f:locals(V, 2)
	f:load(tab)
	f:structget(tbl, 'hash')
	f:tee(old)
	f:arraylen()
	f:tee(n)
	f:i32(1)
	f:shl()
	f:arraynewdefault(vals)
	f:store(new)
	f:loop(function(loop)
		f:load(i)
		f:load(n)
		f:ltu()
		f:iff(function()
			f:load(old)
			f:load(i)
			f:arrayget(vals)
			f:store(k)
			f:load(old)
			f:load(i)
			f:i32(1)
			f:add()
			f:arrayget(vals)
			f:tee(v)
			f:refisnull()
			f:load(k)
			f:refisnull()
			f:bor()
			f:eqz()
			f:iff(function()
				f:load(new)
				f:load(k)
				f:load(v)
				f:load(k)
				f:call(hash)
				f:call(rawinsert)
				f:load(cnt)
				f:i32(1)
				f:add()
				f:store(cnt)
			end)
			f:load(i)
			f:i32(2)
			f:add()
			f:store(i)
			f:br(loop)
		end)
	end)
	f:load(tab)
	f:load(new)
	f:refasnonnull()
	f:structset(tbl, 'hash')
	f:load(tab)
	f:load(cnt)
	f:structset(tbl, 'hlen')
end)

local tblset = func(R.tbl, V, V, void, function(f, tab, key, val)
	local arr = f:locals(R.vals)
	local cap, i, n = f:locals(i32, 3)
	local k = f:locals(V)
	f:load(tab)
	f:structget(tbl, 'hash')
	f:tee(arr)
	f:arraylen()
	f:i32(1)
	f:shru()
	f:store(cap)
	f:load(key)
	f:call(hash)
	f:load(cap)
	f:remu()
	f:store(i)
	f:loop(function(loop)
		f:load(arr)
		f:load(i)
		f:i32(1)
		f:shl()
		f:arrayget(vals)
		f:tee(k)
		f:refisnull()
		f:iff(function()
			-- new key. Setting a missing key to nil does nothing
			f:load(val)
			f:refisnull()
			f:iff(function()
				f:ret()
			end)
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:shl()
			f:load(key)
			f:arrayset(vals)
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:shl()
			f:i32(1)
			f:add()
			f:load(val)
			f:arrayset(vals)
			f:load(tab)
			f:load(tab)
			f:structget(tbl, 'hlen')
			f:i32(1)
			f:add()
			f:tee(n)
			f:structset(tbl, 'hlen')
			-- keep at most half full
			f:load(n)
			f:i32(1)
			f:shl()
			f:load(cap)
			f:gtu()
			f:iff(function()
				f:load(tab)
				f:call(rehash)
			end)
			f:ret()
		end)
		f:load(k)
		f:load(key)
		f:call(eq)
		f:iff(function()
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:shl()
			f:i32(1)
			f:add()
			f:load(val)
			f:arrayset(vals)
			f:ret()
		end)
		f:load(i)
		f:i32(1)
		f:add()
		f:tee(i)
		f:load(cap)
		f:eq()
		f:iff(function()
			f:i32(0)
			f:store(i)
		end)
		f:br(loop)
	end)
end)

-- Probe for a key: eqf(f, k) leaves whether k is the key. Leaves the value, nil if missing
local function getter(f, tab, h, eqf)
	local arr = f:locals(R.vals)
	local cap, i = f:locals(i32, 2)
	local k = f:locals(V)
	f:load(tab)
	f:structget(tbl, 'hash')
	f:tee(arr)
	f:arraylen()
	f:i32(1)
	f:shru()
	f:store(cap)
	h()
	f:load(cap)
	f:remu()
	f:store(i)
	f:loop(V, function(loop)
		f:load(arr)
		f:load(i)
		f:i32(1)
		f:shl()
		f:arrayget(vals)
		f:tee(k)
		f:refisnull()
		f:iff(function()
			f:refnull(M.heap.eq)
			f:ret()
		end)
		eqf(k)
		f:iff(function()
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:shl()
			f:i32(1)
			f:add()
			f:arrayget(vals)
			f:ret()
		end)
		f:load(i)
		f:i32(1)
		f:add()
		f:tee(i)
		f:load(cap)
		f:eq()
		f:iff(function()
			f:i32(0)
			f:store(i)
		end)
		f:br(loop)
	end)
end

local tblget = func(R.tbl, V, V, function(f, tab, key)
	getter(f, tab, function()
		f:load(key)
		f:call(hash)
	end, function(k)
		f:load(k)
		f:load(key)
		f:call(eq)
	end)
end)

-- Is v the integer x, as an int or float
local eqi64 = func(V, i64, i32, function(f, v, x)
	f:switch(function()
		f:load(v)
		f:call(typeof)
	end, types.int, function()
		f:load(v)
		f:refcast(M.ref(int))
		f:structget(int, 'val')
		f:load(x)
		f:eq()
		f:ret()
	end, types.float, function()
		f:load(v)
		f:refcast(M.ref(float))
		f:structget(float, 'val')
		f:load(x)
		f:f64converts()
		f:eq()
		f:ret()
	end, -1)
	f:i32(0)
end)

-- t[x] for an integer x, without making an int object
local tblgeti = func(R.tbl, i64, V, function(f, tab, x)
	getter(f, tab, function()
		hashi64(f, x)
	end, function(k)
		f:load(k)
		f:load(x)
		f:call(eqi64)
	end)
end)

-- Length of a table's sequence: a border n where t[n] ~= nil and t[n+1] == nil (or n == 0).
-- Probes integer keys, starting from the last length found
local tbllen = func(R.tbl, i32, function(f, tab)
	local n = f:locals(i32)
	f:load(tab)
	f:structget(tbl, 'len')
	f:store(n)

	-- grow while t[n+1] ~= nil
	f:block(function(done)
		f:loop(function(loop)
			f:load(tab)
			f:load(n)
			f:i32(1)
			f:add()
			f:i64extendu()
			f:call(tblgeti)
			f:refisnull()
			f:brif(done)
			f:load(n)
			f:i32(1)
			f:add()
			f:store(n)
			f:br(loop)
		end)
	end)

	-- shrink while t[n] == nil
	f:block(function(done)
		f:loop(function(loop)
			f:load(n)
			f:eqz()
			f:brif(done)
			f:load(tab)
			f:load(n)
			f:i64extendu()
			f:call(tblgeti)
			f:refisnull()
			f:eqz()
			f:brif(done)
			f:load(n)
			f:i32(1)
			f:sub()
			f:store(n)
			f:br(loop)
		end)
	end)

	f:load(tab)
	f:load(n)
	f:structset(tbl, 'len')
	f:load(n)
end)

-- Pair after key (first pair when key is nil) whose value isn't nil. nil, nil past the last.
-- TODO a key that isn't in the table should raise an error, it starts over for now
local tblnext = func(R.tbl, V, { V, V }, function(f, tab, key)
	local arr = f:locals(R.vals)
	local i, n = f:locals(i32, 2)
	f:load(tab)
	f:structget(tbl, 'hash')
	f:tee(arr)
	f:arraylen()
	f:store(n)
	f:load(key)
	f:refisnull()
	f:eqz()
	f:iff(function()
		-- find key's pair, then start after it
		f:block(function(found)
			f:loop(function(loop)
				f:load(i)
				f:load(n)
				f:geu()
				f:iff(function()
					f:refnull(M.heap.eq)
					f:refnull(M.heap.eq)
					f:ret()
				end)
				f:load(arr)
				f:load(i)
				f:arrayget(vals)
				f:load(key)
				f:call(eq)
				f:brif(found)
				f:load(i)
				f:i32(2)
				f:add()
				f:store(i)
				f:br(loop)
			end)
		end)
		f:load(i)
		f:i32(2)
		f:add()
		f:store(i)
	end)
	f:loop(function(loop)
		f:load(i)
		f:load(n)
		f:ltu()
		f:iff(function()
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:add()
			f:arrayget(vals)
			f:refisnull()
			f:iff(function()
				f:load(i)
				f:i32(2)
				f:add()
				f:store(i)
				f:br(loop)
			end)
			f:load(arr)
			f:load(i)
			f:arrayget(vals)
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:add()
			f:arrayget(vals)
			f:ret()
		end)
	end)
	f:refnull(M.heap.eq)
	f:refnull(M.heap.eq)
end)

return {
	tblget = tblget,
	tblgeti = tblgeti,
	tblset = tblset,
	tbllen = tbllen,
	tblnext = tblnext,
	eqi64 = eqi64,
}
