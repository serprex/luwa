-- A table has an array part & a hash part. Keys 1..asize live in arr[k-1], arr can be longer than asize.
-- Setting nil in the array leaves a hole. Other keys go in hash, which holds pairs: key at 2i, value at 2i+1.
-- Open addressing, probing forward. Keys are never removed, setting nil leaves the key.
-- The hash never has a non nil value for key asize+1: setting that key appends to the array instead,
-- & each append moves the next key over from the hash
local M = require 'make'
local func = M.func

local alloc = require 'alloc'
local tbl, vals, i32s, int, float, R, typeof, types = alloc.tbl, alloc.vals, alloc.i32s, alloc.int, alloc.float, alloc.R, alloc.typeof, alloc.types

local _obj = require 'obj'
local hash, eq, hashi64 = _obj.hash, _obj.eq, _obj.hashi64

-- Pair index to start probing at, for hash h in a table with cap pairs
local function startpair(f, h, cap)
	f:load(h)
	f:load(cap)
	f:remu()
end

-- Array slot for key: k-1 when key is an integer k in 1..2^30 (an int, or a float with that value), else -1.
-- Leaves an i32. fl is a scratch f64 local
local function keyslot(f, key, fl)
	f:block(i32, function(out)
		f:load(key)
		f:block(M.functype({ V }, M.ref(float)), function(isflt)
			f:block(M.functype({ V }, M.ref(M.heap.i31)), function(isi31)
				f:broncast(isi31, V, M.ref(M.heap.i31))
				f:broncast(isflt, V, M.ref(float))
				-- int structs are all outside i31 range, so too big for the array
				f:drop()
				f:i32(-1)
				f:br(out)
			end)
			-- below 1 gives a negative slot, which unsigned compares see as huge
			f:i31gets()
			f:i32(1)
			f:sub()
			f:br(out)
		end)
		f:structget(float, 'val')
		f:tee(fl)
		f:f64(1)
		f:ge()
		f:load(fl)
		f:f64(2^30)
		f:le()
		f:band()
		f:load(fl)
		f:trunc()
		f:load(fl)
		f:eq()
		f:band()
		f:iff(i32, function()
			f:load(fl)
			f:i32truncs()
			f:i32(1)
			f:sub()
		end, function()
			f:i32(-1)
		end)
	end)
end

-- Probe the hash for a key: eqf(k) leaves whether k is the key.
-- found(arr, i) runs for the matching pair i & has to return. Otherwise returns nil
local function getter(f, tab, h, eqf, found)
	local arr = f:locals(R.vals)
	local cap, i = f:locals(i32, 2)
	local k = f:locals(V)
	f:load(tab)
	f:structget(tbl, 'hash')
	f:tee(arr)
	f:arraylen()
	f:i32(1)
	f:shru()
	f:store(cap)
	h()
	f:load(cap)
	f:remu()
	f:store(i)
	f:loop(V, function(loop)
		f:load(arr)
		f:load(i)
		f:i32(1)
		f:shl()
		f:arrayget(vals)
		f:tee(k)
		f:refisnull()
		f:iff(function()
			f:refnull(M.heap.eq)
			f:ret()
		end)
		eqf(k)
		f:iff(function()
			if found then
				found(arr, i)
			else
				f:load(arr)
				f:load(i)
				f:i32(1)
				f:shl()
				f:i32(1)
				f:add()
				f:arrayget(vals)
				f:ret()
			end
		end)
		f:load(i)
		f:i32(1)
		f:add()
		f:tee(i)
		f:load(cap)
		f:eq()
		f:iff(function()
			f:i32(0)
			f:store(i)
		end)
		f:br(loop)
	end)
end

-- Is v the integer x, as an int or float
local eqi64 = func(V, i64, i32, function(f, v, x)
	f:switch(function()
		f:load(v)
		f:call(typeof)
	end, types.int, function()
		f:load(v)
		alloc.intvalst(f)
		f:load(x)
		f:eq()
		f:ret()
	end, types.float, function()
		f:load(v)
		f:refcast(M.ref(float))
		f:structget(float, 'val')
		f:load(x)
		f:f64converts()
		f:eq()
		f:ret()
	end, -1)
	f:i32(0)
end)

-- Hash part's value for integer key x, which is set to nil. Gives the old value
local hashtake = func(R.tbl, i64, V, function(f, tab, x)
	local v = f:locals(V)
	getter(f, tab, function()
		hashi64(f, x)
	end, function(k)
		f:load(k)
		f:load(x)
		f:call(eqi64)
	end, function(arr, i)
		f:load(arr)
		f:load(i)
		f:i32(1)
		f:shl()
		f:i32(1)
		f:add()
		f:tee(i)
		f:arrayget(vals)
		f:store(v)
		f:load(arr)
		f:load(i)
		f:refnull(M.heap.eq)
		f:arrayset(vals)
		f:load(v)
		f:ret()
	end)
end)

-- t[asize+1] = val, val isn't nil. Doubles arr when it's full,
-- then moves keys asize+2, asize+3, .. over from the hash while they're there
local tblappend = func(R.tbl, V, void, function(f, tab, val)
	local arr, new = f:locals(R.vals, 2)
	local n = f:locals(i32)
	local v = f:locals(V)
	f:load(tab)
	f:structget(tbl, 'arr')
	f:store(arr)
	f:load(tab)
	f:structget(tbl, 'asize')
	f:store(n)
	f:load(val)
	f:store(v)
	f:loop(function(loop)
		f:load(n)
		f:load(arr)
		f:arraylen()
		f:eq()
		f:iff(function()
			-- full: new size is max(4, 2n)
			f:i32(4)
			f:load(n)
			f:i32(1)
			f:shl()
			f:load(n)
			f:i32(2)
			f:ltu()
			f:select()
			f:arraynewdefault(vals)
			f:tee(new)
			f:i32(0)
			f:load(arr)
			f:i32(0)
			f:load(n)
			f:arraycopy(vals, vals)
			f:load(new)
			f:store(arr)
			f:load(tab)
			f:load(arr)
			f:refasnonnull()
			f:structset(tbl, 'arr')
		end)
		f:load(arr)
		f:load(n)
		f:load(v)
		f:arrayset(vals)
		f:load(n)
		f:i32(1)
		f:add()
		f:store(n)
		f:load(tab)
		f:structget(tbl, 'hlen')
		f:iff(function()
			f:load(tab)
			f:load(n)
			f:i32(1)
			f:add()
			f:i64extendu()
			f:call(hashtake)
			f:tee(v)
			f:refisnull()
			f:eqz()
			f:brif(loop)
		end)
	end)
	f:load(tab)
	f:load(n)
	f:structset(tbl, 'asize')
end)

-- Put key & val in arr without checking for room, key isn't in arr yet. Used by rehash
local rawinsert = func(R.vals, V, V, i32, void, function(f, arr, key, val, h)
	local cap, i = f:locals(i32, 2)
	f:load(arr)
	f:arraylen()
	f:i32(1)
	f:shru()
	f:store(cap)
	startpair(f, h, cap)
	f:store(i)
	f:loop(function(loop)
		f:load(arr)
		f:load(i)
		f:i32(1)
		f:shl()
		f:arrayget(vals)
		f:refisnull()
		f:iff(function()
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:shl()
			f:load(key)
			f:arrayset(vals)
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:shl()
			f:i32(1)
			f:add()
			f:load(val)
			f:arrayset(vals)
			f:ret()
		end)
		f:load(i)
		f:i32(1)
		f:add()
		f:tee(i)
		f:load(cap)
		f:eq()
		f:iff(function()
			f:i32(0)
			f:store(i)
		end)
		f:br(loop)
	end)
end)

-- Rebuild the hash part, dropping pairs whose value is nil. Like C Lua, the array part grows
-- to the biggest power of 2 size that would be more than half used, counting the current
-- array as full, & integer keys that fit move over to it. The new hash is 4 times the pairs left
local rehash = func(R.tbl, void, function(f, tab)
	local old, new, arr = f:locals(R.vals, 3)
	local nums = f:locals(R.i32s)
	local i, n, cnt, asz, best, moved, tot, b, s, cap = f:locals(i32, 10)
	local k, v = f:locals(V, 2)
	local fl = f:locals(f64)
	f:load(tab)
	f:structget(tbl, 'asize')
	f:tee(asz)
	f:store(best)
	f:load(tab)
	f:structget(tbl, 'hash')
	f:tee(old)
	f:arraylen()
	f:store(n)
	-- nums[b] counts live integer keys above the array whose slot needs an array of size 2^b
	f:i32(32)
	f:arraynewdefault(i32s)
	f:store(nums)
	f:loop(function(loop)
		f:load(i)
		f:load(n)
		f:ltu()
		f:iff(function()
			f:load(old)
			f:load(i)
			f:i32(1)
			f:add()
			f:arrayget(vals)
			f:refisnull()
			f:eqz()
			f:iff(function()
				f:load(cnt)
				f:i32(1)
				f:add()
				f:store(cnt)
				f:load(old)
				f:load(i)
				f:arrayget(vals)
				f:store(k)
				keyslot(f, k, fl)
				f:tee(s)
				f:load(asz)
				f:ges()
				f:iff(function()
					f:load(nums)
					f:i32(32)
					f:load(s)
					f:clz()
					f:sub()
					f:tee(b)
					f:load(nums)
					f:load(b)
					f:arrayget(i32s)
					f:i32(1)
					f:add()
					f:arrayset(i32s)
				end)
			end)
			f:load(i)
			f:i32(2)
			f:add()
			f:store(i)
			f:br(loop)
		end)
	end)
	-- pick the size
	f:i32(0)
	f:store(b)
	f:loop(function(loop)
		f:load(tot)
		f:load(nums)
		f:load(b)
		f:arrayget(i32s)
		f:add()
		f:store(tot)
		f:i32(1)
		f:load(b)
		f:shl()
		f:tee(s)
		f:load(asz)
		f:gtu()
		f:iff(function()
			f:load(asz)
			f:load(tot)
			f:add()
			f:i32(1)
			f:shl()
			f:load(s)
			f:gtu()
			f:iff(function()
				f:load(s)
				f:store(best)
				f:load(tot)
				f:store(moved)
			end)
		end)
		f:load(b)
		f:i32(1)
		f:add()
		f:tee(b)
		f:i32(30)
		f:leu()
		f:brif(loop)
	end)
	f:load(tab)
	f:structget(tbl, 'arr')
	f:store(arr)
	f:load(best)
	f:load(asz)
	f:ne()
	f:iff(function()
		f:load(arr)
		f:arraylen()
		f:load(best)
		f:ltu()
		f:iff(function()
			f:load(best)
			f:arraynewdefault(vals)
			f:tee(new)
			f:i32(0)
			f:load(arr)
			f:i32(0)
			f:load(asz)
			f:arraycopy(vals, vals)
			f:load(new)
			f:store(arr)
			f:load(tab)
			f:load(arr)
			f:refasnonnull()
			f:structset(tbl, 'arr')
		end)
		f:load(tab)
		f:load(best)
		f:structset(tbl, 'asize')
	end)
	-- new hash
	f:i32(4)
	f:store(cap)
	f:loop(function(loop)
		f:load(cap)
		f:load(cnt)
		f:load(moved)
		f:sub()
		f:i32(2)
		f:shl()
		f:ltu()
		f:iff(function()
			f:load(cap)
			f:i32(1)
			f:shl()
			f:store(cap)
			f:br(loop)
		end)
	end)
	f:load(cap)
	f:i32(1)
	f:shl()
	f:arraynewdefault(vals)
	f:store(new)
	f:i32(0)
	f:store(cnt)
	f:i32(0)
	f:store(i)
	f:loop(function(loop)
		f:load(i)
		f:load(n)
		f:ltu()
		f:iff(function()
			f:load(old)
			f:load(i)
			f:i32(1)
			f:add()
			f:arrayget(vals)
			f:tee(v)
			f:refisnull()
			f:eqz()
			f:iff(function()
				f:load(old)
				f:load(i)
				f:arrayget(vals)
				f:store(k)
				keyslot(f, k, fl)
				f:tee(s)
				f:load(asz)
				f:ges()
				f:load(s)
				f:load(best)
				f:ltu()
				f:band()
				f:iff(function()
					f:load(arr)
					f:load(s)
					f:load(v)
					f:arrayset(vals)
				end, function()
					f:load(new)
					f:load(k)
					f:load(v)
					f:load(k)
					f:call(hash)
					f:call(rawinsert)
					f:load(cnt)
					f:i32(1)
					f:add()
					f:store(cnt)
				end)
			end)
			f:load(i)
			f:i32(2)
			f:add()
			f:store(i)
			f:br(loop)
		end)
	end)
	f:load(tab)
	f:load(new)
	f:refasnonnull()
	f:structset(tbl, 'hash')
	f:load(tab)
	f:load(cnt)
	f:structset(tbl, 'hlen')
	-- the array grew, so key best+1 may be in the hash
	f:load(best)
	f:load(asz)
	f:ne()
	f:load(cnt)
	f:i32(0)
	f:ne()
	f:band()
	f:iff(function()
		f:load(tab)
		f:load(best)
		f:i32(1)
		f:add()
		f:i64extendu()
		f:call(hashtake)
		f:tee(v)
		f:refisnull()
		f:eqz()
		f:iff(function()
			f:load(tab)
			f:load(v)
			f:call(tblappend)
		end)
	end)
end)

-- Set in the hash part
local hashset = func(R.tbl, V, V, void, function(f, tab, key, val)
	local arr = f:locals(R.vals)
	local cap, i, n = f:locals(i32, 3)
	local k = f:locals(V)
	f:load(tab)
	f:structget(tbl, 'hash')
	f:tee(arr)
	f:arraylen()
	f:i32(1)
	f:shru()
	f:store(cap)
	f:load(key)
	f:call(hash)
	f:load(cap)
	f:remu()
	f:store(i)
	f:loop(function(loop)
		f:load(arr)
		f:load(i)
		f:i32(1)
		f:shl()
		f:arrayget(vals)
		f:tee(k)
		f:refisnull()
		f:iff(function()
			-- new key. Setting a missing key to nil does nothing
			f:load(val)
			f:refisnull()
			f:iff(function()
				f:ret()
			end)
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:shl()
			f:load(key)
			f:arrayset(vals)
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:shl()
			f:i32(1)
			f:add()
			f:load(val)
			f:arrayset(vals)
			-- the key could be a metamethod name
			f:load(tab)
			f:i32(0)
			f:structset(tbl, 'noflags')
			f:load(tab)
			f:load(tab)
			f:structget(tbl, 'hlen')
			f:i32(1)
			f:add()
			f:tee(n)
			f:structset(tbl, 'hlen')
			-- keep at most half full
			f:load(n)
			f:i32(1)
			f:shl()
			f:load(cap)
			f:gtu()
			f:iff(function()
				f:load(tab)
				f:call(rehash)
			end)
			f:ret()
		end)
		f:load(k)
		f:load(key)
		f:call(eq)
		f:iff(function()
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:shl()
			f:i32(1)
			f:add()
			f:tee(i)
			f:arrayget(vals)
			f:refisnull()
			f:iff(function()
				-- nil to a value counts as a new key
				f:load(tab)
				f:i32(0)
				f:structset(tbl, 'noflags')
			end)
			f:load(arr)
			f:load(i)
			f:load(val)
			f:arrayset(vals)
			f:ret()
		end)
		f:load(i)
		f:i32(1)
		f:add()
		f:tee(i)
		f:load(cap)
		f:eq()
		f:iff(function()
			f:i32(0)
			f:store(i)
		end)
		f:br(loop)
	end)
end)


-- t[key] = val
local tblset = func(R.tbl, V, V, void, function(f, tab, key, val)
	local s, n = f:locals(i32, 2)
	local fl = f:locals(f64)
	keyslot(f, key, fl)
	f:tee(s)
	f:load(tab)
	f:structget(tbl, 'asize')
	f:tee(n)
	f:ltu()
	f:iff(function()
		f:load(tab)
		f:structget(tbl, 'arr')
		f:load(s)
		f:load(val)
		f:arrayset(vals)
		f:ret()
	end)
	f:load(s)
	f:load(n)
	f:eq()
	f:iff(function()
		-- the hash has no value for this key, so setting nil does nothing
		f:load(val)
		f:refisnull()
		f:eqz()
		f:iff(function()
			f:load(tab)
			f:load(val)
			f:call(tblappend)
		end)
		f:ret()
	end)
	f:load(tab)
	f:load(key)
	f:load(val)
	f:call(hashset)
end)

-- t[key]
local tblget = func(R.tbl, V, V, function(f, tab, key)
	local s = f:locals(i32)
	local fl = f:locals(f64)
	keyslot(f, key, fl)
	f:tee(s)
	f:load(tab)
	f:structget(tbl, 'asize')
	f:ltu()
	f:iff(function()
		f:load(tab)
		f:structget(tbl, 'arr')
		f:load(s)
		f:arrayget(vals)
		f:ret()
	end)
	getter(f, tab, function()
		f:load(key)
		f:call(hash)
	end, function(k)
		f:load(k)
		f:load(key)
		f:call(eq)
	end)
end)

-- t[x] for an integer x, without making an int object
local tblgeti = func(R.tbl, i64, V, function(f, tab, x)
	f:load(x)
	f:i64(1)
	f:sub()
	f:load(tab)
	f:structget(tbl, 'asize')
	f:i64extendu()
	f:ltu()
	f:iff(function()
		f:load(tab)
		f:structget(tbl, 'arr')
		f:load(x)
		f:i32wrap()
		f:i32(1)
		f:sub()
		f:arrayget(vals)
		f:ret()
	end)
	getter(f, tab, function()
		hashi64(f, x)
	end, function(k)
		f:load(k)
		f:load(x)
		f:call(eqi64)
	end)
end)

-- Length of a table's sequence: a border n where t[n] ~= nil and t[n+1] == nil (or n == 0).
-- The hash never has key asize+1, so when the array's last slot is set that's asize.
-- Else there's a border in the array. Like luaH_getn: look within 4 of the last one found, then binary search
local tbllen = func(R.tbl, i32, function(f, tab)
	local arr = f:locals(R.vals)
	local n, lo, hi, lim, c = f:locals(i32, 5)
	-- is arr[x-1] nil, x from 1 to n
	local function empty(x)
		f:load(arr)
		f:load(x)
		f:i32(1)
		f:sub()
		f:arrayget(vals)
		f:refisnull()
	end
	local function found(x)
		f:load(tab)
		f:load(x)
		f:structset(tbl, 'len')
		f:load(x)
		f:ret()
	end
	f:load(tab)
	f:structget(tbl, 'asize')
	f:tee(n)
	f:eqz()
	f:iff(function()
		f:i32(0)
		f:ret()
	end)
	f:load(tab)
	f:structget(tbl, 'arr')
	f:store(arr)
	empty(n)
	f:eqz()
	f:iff(function()
		found(n)
	end)
	-- hint in 1..n
	f:i32(1)
	f:load(tab)
	f:structget(tbl, 'len')
	f:tee(lim)
	f:load(lim)
	f:eqz()
	f:select()
	f:tee(lim)
	f:load(n)
	f:load(lim)
	f:load(n)
	f:leu()
	f:select()
	f:store(lim)
	-- binary search below sets lo & hi: lo is 0 or arr[lo-1] isn't nil, arr[hi] is nil
	empty(lim)
	f:iff(function()
		f:loop(function(loop)
			f:load(c)
			f:i32(4)
			f:ltu()
			f:load(lim)
			f:i32(1)
			f:gtu()
			f:band()
			f:iff(function()
				f:load(lim)
				f:i32(1)
				f:sub()
				f:store(lim)
				empty(lim)
				f:eqz()
				f:iff(function()
					found(lim)
				end)
				f:load(c)
				f:i32(1)
				f:add()
				f:store(c)
				f:br(loop)
			end)
		end)
		f:load(lim)
		f:i32(1)
		f:sub()
		f:store(hi)
	end, function()
		f:loop(function(loop)
			f:load(c)
			f:i32(4)
			f:ltu()
			f:load(lim)
			f:load(n)
			f:ltu()
			f:band()
			f:iff(function()
				f:load(lim)
				f:i32(1)
				f:add()
				f:store(lim)
				empty(lim)
				f:iff(function()
					f:load(lim)
					f:i32(1)
					f:sub()
					f:store(lim)
					found(lim)
				end)
				f:load(c)
				f:i32(1)
				f:add()
				f:store(c)
				f:br(loop)
			end)
		end)
		f:load(lim)
		f:store(lo)
		f:load(n)
		f:i32(1)
		f:sub()
		f:store(hi)
	end)
	f:loop(function(loop)
		f:load(lo)
		f:load(hi)
		f:ltu()
		f:iff(function()
			f:load(lo)
			f:load(hi)
			f:add()
			f:i32(1)
			f:shru()
			f:store(c)
			f:load(arr)
			f:load(c)
			f:arrayget(vals)
			f:refisnull()
			f:iff(function()
				f:load(c)
				f:store(hi)
			end, function()
				f:load(c)
				f:i32(1)
				f:add()
				f:store(lo)
			end)
			f:br(loop)
		end)
	end)
	found(lo)
end)

-- Pair after key (first pair when key is nil) whose value isn't nil. nil, nil past the last.
-- The array comes first, its keys are slot+1. Then the hash
-- TODO a key that isn't in the table should raise an error, it gives nil, nil for now
local tblnext = func(R.tbl, V, { V, V }, function(f, tab, key)
	local arr = f:locals(R.vals)
	local i, n, cap, s, asz = f:locals(i32, 5)
	local fl = f:locals(f64)
	f:load(tab)
	f:structget(tbl, 'asize')
	f:store(asz)
	f:load(key)
	f:refisnull()
	f:eqz()
	f:iff(function()
		keyslot(f, key, fl)
		f:tee(s)
		f:load(asz)
		f:ltu()
		f:iff(function()
			f:load(s)
			f:i32(1)
			f:add()
			f:store(s)
		end, function()
			f:load(asz)
			f:store(s)
			f:load(tab)
			f:structget(tbl, 'hash')
			f:tee(arr)
			f:arraylen()
			f:i32(1)
			f:shru()
			f:store(cap)
			-- probe for key's pair like tblget, then start after it. Keys are never removed, so it's there
			f:load(key)
			f:call(hash)
			f:load(cap)
			f:remu()
			f:store(i)
			f:block(function(found)
				f:loop(function(loop)
					f:load(arr)
					f:load(i)
					f:i32(1)
					f:shl()
					f:arrayget(vals)
					f:refisnull()
					f:iff(function()
						f:refnull(M.heap.eq)
						f:refnull(M.heap.eq)
						f:ret()
					end)
					f:load(arr)
					f:load(i)
					f:i32(1)
					f:shl()
					f:arrayget(vals)
					f:load(key)
					f:call(eq)
					f:brif(found)
					f:load(i)
					f:i32(1)
					f:add()
					f:tee(i)
					f:load(cap)
					f:eq()
					f:iff(function()
						f:i32(0)
						f:store(i)
					end)
					f:br(loop)
				end)
			end)
			f:load(i)
			f:i32(1)
			f:shl()
			f:i32(2)
			f:add()
			f:store(i)
		end)
	end)
	-- array slots from s
	f:load(tab)
	f:structget(tbl, 'arr')
	f:store(arr)
	f:loop(function(loop)
		f:load(s)
		f:load(asz)
		f:ltu()
		f:iff(function()
			f:load(arr)
			f:load(s)
			f:arrayget(vals)
			f:refisnull()
			f:iff(function()
				f:load(s)
				f:i32(1)
				f:add()
				f:store(s)
				f:br(loop)
			end)
			f:load(s)
			f:i32(1)
			f:add()
			f:refi31()
			f:load(arr)
			f:load(s)
			f:arrayget(vals)
			f:ret()
		end)
	end)
	-- hash pairs from i
	f:load(tab)
	f:structget(tbl, 'hash')
	f:tee(arr)
	f:arraylen()
	f:store(n)
	f:loop(function(loop)
		f:load(i)
		f:load(n)
		f:ltu()
		f:iff(function()
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:add()
			f:arrayget(vals)
			f:refisnull()
			f:iff(function()
				f:load(i)
				f:i32(2)
				f:add()
				f:store(i)
				f:br(loop)
			end)
			f:load(arr)
			f:load(i)
			f:arrayget(vals)
			f:load(arr)
			f:load(i)
			f:i32(1)
			f:add()
			f:arrayget(vals)
			f:ret()
		end)
	end)
	f:refnull(M.heap.eq)
	f:refnull(M.heap.eq)
end)

return {
	tblget = tblget,
	tblgeti = tblgeti,
	tblset = tblset,
	tbllen = tbllen,
	tblnext = tblnext,
	eqi64 = eqi64,
}
