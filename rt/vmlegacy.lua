-- Old hand-written op handlers, brought back from 2bdc2d2^:rt/vm.lua
-- They let the vm run while ops move over to microbc one at a time.
-- Delete a handler here once microbc covers that op (vm.lua checks this).
local M = require 'make'

local alloc = require 'alloc'
local types, obj, num, str, vec, buf, tbl, functy, coro, allocsizef, nextid, newobj, newi64, newf64, newstrbuf, newvec, newvec1, newtbl =
	alloc.types, alloc.obj, alloc.num, alloc.str, alloc.vec, alloc.buf, alloc.tbl, alloc.functy, alloc.coro,
	alloc.allocsizef, alloc.nextid, alloc.newobj, alloc.newi64, alloc.newf64, alloc.newstrbuf, alloc.newvec, alloc.newvec1, alloc.newtbl

local _table = require '_table'
local tblget, tblset, tbllen = _table.tblget, _table.tblset, _table.tbllen

local stack = require 'stack'
local tmppush, tmppop, nthtmp, setnthtmp, extendtmp =
	stack.tmppush, stack.tmppop, stack.nthtmp, stack.setnthtmp, stack.extendtmp

local util = require 'util'
local extendstr, extendvec, memcpy4, tonum, toint =
	util.extendstr, util.extendvec, util.memcpy4, util.tonum, util.toint

local _string = require '_string'
local _obj = require 'obj'

local ops = require 'bc'

local rt = require 'rt'

-- Returns an ordered list: label, handler, label, handler, ...
-- Order matters: a handler can only branch to labels that come after it.
-- L holds the locals & helpers of vm's eval function.
return function(f, L)
	local a, b, c, d, e = L.a, L.b, L.c, L.d, L.e
	local meta_callty, meta_retb, meta_retc, meta_key, meta_off = L.meta_callty, L.meta_retb, L.meta_retc, L.meta_key, L.meta_off
	local framebase, objbase, base, bc, pc = L.framebase, L.objbase, L.base, L.bc, L.pc
	local a64 = L.a64
	local readArg, readArg4 = L.readArg, L.readArg4
	local dataframe, objframe, calltypes = L.dataframe, L.objframe, L.calltypes

	local arms = {}
	local function arm(label, fn)
		arms[#arms+1] = label
		arms[#arms+1] = fn
	end

	-- Copy this frame's varargs (base+dotdotdot up to base+locals) to the top of the stack.
	-- Leaves their size in bytes in meta_off. Uses a, b
	local function pushvarg()
		f:load(framebase)
		f:i32load16u(dataframe.locals)
		f:load(framebase)
		f:i32load16u(dataframe.dotdotdot)
		f:sub()
		f:tee(meta_off)
		f:i32(0)
		f:gts()
		f:iff(function()
			f:loadg(oluastack)
			f:i32load(coro.stack)
			f:i32load(buf.len)
			f:store(a)
			f:load(meta_off)
			f:call(extendtmp)

			-- extendtmp may have moved the stack, reload
			f:loadg(oluastack)
			f:i32load(coro.stack)
			f:i32load(buf.ptr)
			f:i32(vec.base)
			f:add()
			f:tee(b)
			f:load(a)
			f:add()
			f:load(b)
			f:load(base)
			f:add()
			f:load(framebase)
			f:i32load16u(dataframe.dotdotdot)
			f:add()
			f:load(meta_off)
			f:call(memcpy4)
		end, function()
			f:i32(0)
			f:store(meta_off)
		end)
	end

	arm(ops.CmpEq, function(scopes)
		f:i32(8)
		f:call(nthtmp)
		f:tee(c)
		f:i32(4)
		f:call(nthtmp)
		f:tee(d)
		f:call(_obj.eq)
		f:iff(i32, function()
			f:i32(TRUE)
		end, function()
			-- if neq, check if both tables
			-- if both tables, check if same meta
			-- if same meta, push metaeqframe
			f:load(c)
			f:i32load8u(obj.type)
			f:i32(types.tbl)
			f:eq()
			f:load(d)
			f:i32load8u(obj.type)
			f:i32(types.tbl)
			f:eq()
			f:band()
			f:iff(function()
				f:load(c)
				f:i32load(tbl.meta)
				f:load(d)
				f:i32load(tbl.meta)
				f:tee(c)
				f:eq()
				f:iff(function()
					f:load(c)
					f:i32(GS.__eq)
					f:call(tblget)
					f:tee(d)
					f:iff(function()
						f:i32(calltypes.bool)
						f:store(meta_callty)
						f:i32(8)
						f:store(meta_retb)
						f:i32(1)
						f:store(meta_retc)
						f:i32(GS.__eq)
						f:store(meta_key)
						f:i32(8)
						f:store(meta_off)
						f:br(scopes.meta)
					end)
				end)
			end)
			f:i32(FALSE)
		end)
		f:i32(8)
		f:call(setnthtmp)
		f:call(tmppop)
		f:br(scopes.nop)
	end)
	arm(ops.Idx, function(scopes)
		f:loop(function(loop)
			-- TODO Lua limits chains to 2000 length to try detect infinite loops
			f:i32(8)
			f:call(nthtmp)
			f:tee(a)
			f:i32load8u(obj.type)
			f:tee(b)
			f:i32(types.tbl)
			f:eq()
			f:iff(function()
				f:load(a)
				f:i32(4)
				f:call(nthtmp)
				f:call(tblget)
				f:tee(b)
				f:eqz()
				f:iff(function()
					f:load(a)
					f:i32load(tbl.meta)
					f:tee(b)
					f:iff(function()
						f:load(b)
						f:i32(GS.__index)
						f:call(tblget)
						f:tee(d)
						f:iff(function()
							f:load(d)
							f:i32load8u(obj.type)
							f:i32(types.functy)
							f:eq()
							f:iff(function()
								f:i32(calltypes.norm)
								f:store(meta_callty)
								f:i32(8)
								f:store(meta_retb)
								f:i32(1)
								f:store(meta_retc)
								f:i32(GS.__index)
								f:store(meta_key)
								f:i32(8)
								f:store(meta_off)
								f:br(scopes.meta)
							end)
							-- __index is a table: index it next
							f:load(d)
							f:i32(8)
							f:call(setnthtmp)
							f:br(loop)
						end)
					end)
				end)
				f:load(b)
				f:i32(8)
				f:call(setnthtmp)
				f:call(tmppop)
				f:br(scopes.nop)
			end, function()
				f:load(b)
				f:i32(types.str)
				f:eq()
				f:iff(function()
					-- strings index their metatable's __index (the string library)
					-- TODO __index function on strings
					f:loadg(ostrmt)
					f:i32(GS.__index)
					f:call(tblget)
					f:i32(8)
					f:call(setnthtmp)
					f:br(loop)
				end)
				f:load(b)
				f:i32(types.vec)
				f:eq()
				f:iff(function()
					-- vecs (eg the lexer's value list) index from 1 with integers, nil past the end
					f:i32(4)
					f:call(nthtmp)
					f:tee(d)
					f:i32load8u(obj.type)
					f:i32(types.int)
					f:ne()
					f:iff(function()
						f:unreachable()
					end)
					f:load(d)
					f:i64load(num.val)
					f:i32wrap()
					f:i32(1)
					f:sub()
					f:i32(2)
					f:shl()
					f:tee(d)
					-- unsigned compare also catches keys below 1
					f:load(a)
					f:i32load(vec.len)
					f:ltu()
					f:iff(i32, function()
						f:load(a)
						f:load(d)
						f:add()
						f:i32load(vec.base)
					end, function()
						f:i32(NIL)
					end)
					f:i32(8)
					f:call(setnthtmp)
					f:call(tmppop)
					f:br(scopes.nop)
				end)
				f:unreachable()
			end)
		end)
	end)
	arm(ops.Len, function(scopes)
		f:i32(4)
		f:call(nthtmp)
		f:tee(a)
		f:i32load8u(obj.type)
		f:tee(b)
		f:i32(types.str)
		f:eq()
		f:iff(i32, function()
			f:load(a)
			f:i32load(str.len)
		end, function()
			f:load(b)
			f:i32(types.tbl)
			f:eq()
			f:iff(i32, function()
				f:load(a)
				f:i32load(tbl.meta)
				f:tee(b)
				f:iff(function()
					f:load(b)
					f:i32(GS.__len)
					f:call(tblget)
					f:tee(d)
					f:iff(function()
						f:i32(calltypes.norm)
						f:store(meta_callty)
						f:i32(4)
						f:store(meta_retb)
						f:i32(1)
						f:store(meta_retc)
						f:i32(GS.__len)
						f:store(meta_key)
						f:i32(4)
						f:store(meta_off)
						f:br(scopes.meta)
					end)
				end)
				f:load(a)
				f:call(tbllen)
			end, function()
				f:unreachable()
			end)
		end)
		f:i64extendu()
		f:call(newi64)
		f:i32(4)
		f:call(setnthtmp)
		f:br(scopes.nop)
	end)
	-- return ...: push varargs, then it's a normal Return of everything on the stack
	arm(ops.ReturnVarg, function(scopes)
		pushvarg()
		f:br(scopes[ops.Return])
	end)
	arm(ops.Return, function(scopes)
		f:load(framebase)
		f:i32load16s(dataframe.retb)
		f:load(base)
		f:add()
		f:store(meta_retb)

		f:block(function(skiptopopframe)
			f:load(framebase)
			f:i32load8u(dataframe.type)
			f:tee(meta_callty)
			f:i32(calltypes.init)
			f:eq()
			f:iff(function()
				-- if init: setup ret for resume call in caller coro
				f:loadg(oluastack)
				f:i32load(coro.caller)
				f:tee(a)
				f:iff(function()
					-- extend caller stack to fit our ret stack
					f:load(a)
					f:i32load(coro.stack)
					f:tee(a)
					f:load(a)
					f:i32load(buf.len)
					f:store(b)

					f:loadg(oluastack)
					f:i32load(coro.stack)
					f:i32load(buf.len)
					f:load(base)
					f:sub()
					f:load(framebase)
					f:i32load16u(dataframe.frame)
					f:i32(objframe.sizeof)
					f:add()
					f:sub()

					f:call(extendvec)
					-- memcpy(caller.stack+b,
					---- d = oluastack.stack+base+frame+sizeof(frame),
					---- oluastack.stack.len-d)
					f:tee(a)
					f:i32load(buf.ptr)
					f:load(b)
					f:add()

					f:loadg(oluastack)
					f:i32load(coro.stack)
					f:tee(b)
					f:i32load(buf.ptr)
					f:load(base)
					f:add()
					f:call(loadframebase)
					f:i32load16u(dataframe.frame)
					f:add()
					f:i32(dataframe.sizeof)
					f:add()
					f:tee(d)

					f:load(b)
					f:i32load(buf.len)
					f:load(d)
					f:sub()
					f:call(memcpy4)

					-- oluastack = oluastack.caller
					f:loadg(oluastack)
					f:i32load(coro.caller)
					f:storeg(oluastack)

					-- reload framebase for what follows's sake
					f:call(loadframebase)
					f:tee(framebase)
					f:i32load(dataframe.base)
					f:store(base)
				end, function()
					-- Return from main let's caller work things out
					f:i32(1)
					f:ret()
				end)
			end, function()
				f:load(meta_callty)
				f:i32(calltypes.bool)
				f:eq()
				f:iff(function()
					-- assume retc == 1
					-- b = stack.ptr
					f:loadg(oluastack)
					f:i32load(coro.stack)
					f:i32load(buf.ptr)
					f:tee(b)
					f:load(meta_retb)
					f:add()

					-- return false if stack empty
					f:load(base)
					f:load(framebase)
					f:i32load16u(dataframe.frame)
					f:add()
					f:i32(objframe.sizeof)
					f:add()
					f:tee(a)
					f:loadg(oluastack)
					f:i32load(coro.stack)
					f:i32load(buf.len)
					f:eq()
					f:iff(i32, function()
						f:i32(FALSE)
					end, function()
						-- *retb = pop()?TRUE:FALSE
						f:i32(TRUE)
						f:i32(FALSE)
						f:load(a)
						f:load(b)
						f:add()
						f:i32load(vec.base)
						f:i32(TRUE)
						f:geu()
						f:select()
					end)
					f:i32store(vec.base)

					f:loadg(oluastack)
					f:i32load(coro.stack)
					f:load(meta_retb)
					f:i32(4)
					f:add()
					f:i32store(buf.len)

					f:br(skiptopopframe)
				end)
			end)

			-- TODO stack pop needs to be different for coro
			f:load(framebase)
			f:i32load16u(dataframe.frame)
			f:load(base)
			f:add()
			f:i32(objframe.sizeof)
			f:add()
			f:store(e)

			-- push frames keep every result, their retc is how many fixed values sit below the function
			f:load(framebase)
			f:i32load16u(dataframe.retc)
			f:tee(meta_key)
			f:store(c)
			f:load(c)
			f:i32(65535)
			f:eq()
			f:load(meta_callty)
			f:i32(calltypes.push)
			f:eq()
			f:bor()
			f:iff(i32, function()
				f:loadg(oluastack)
				f:i32load(coro.stack)
				f:i32load(buf.len)
				f:load(e)
				f:sub()
			end, function()
				f:load(c)
				f:i32(2)
				f:shl()
			end)

			f:tee(c)
			f:iff(function()
				f:loop(function(loop)
					-- TODO don't push nils; copy less, nil fill target
					f:load(e)
					f:load(c)
					f:add()
					f:loadg(oluastack)
					f:i32load(coro.stack)
					f:i32load(buf.len)
					f:gtu()
					f:iff(function()
						f:i32(NIL)
						f:call(tmppush)
						f:br(loop)
					end)
				end)

				-- copy to retb. push frames append from there after the frame is popped
				f:loadg(oluastack)
				f:i32load(coro.stack)
				f:i32load(buf.ptr)
				f:i32(vec.base)
				f:add()
				f:tee(a)
				f:load(meta_retb)
				f:add()
				f:load(a)
				f:load(e)
				f:add()
				f:load(c)
				f:call(memcpy4)
			end)

			-- call? blargh
		end)

		-- pop stack frame
		f:loadg(oluastack)
		f:i32load(coro.stack)
		f:load(meta_retb)
		f:load(c)
		f:add()
		f:i32store(buf.len)

		f:loadg(oluastack)
		f:i32load(coro.data)
		f:tee(a)
		f:load(a)
		f:i32load(buf.len)
		f:i32(dataframe.sizeof)
		f:sub()
		f:tee(b)
		f:i32store(buf.len)

		-- set pc, base
		f:load(a)
		f:i32load(buf.ptr)
		f:load(b)
		f:add()
		f:i32(dataframe.sizeof)
		f:sub()
		f:tee(framebase)
		f:i32load(dataframe.pc)
		f:store(pc)

		f:load(framebase)
		f:i32load(dataframe.base)
		f:store(base)

		-- call frame: results are now args of the next function in the chain,
		-- whose frame is on top with pc 0. Do the rest of Call's setup for it
		f:load(meta_callty)
		f:i32(calltypes.call)
		f:eq()
		f:iff(function()
			-- a = args*4
			f:loadg(oluastack)
			f:i32load(coro.stack)
			f:i32load(buf.len)
			f:load(base)
			f:sub()
			f:store(a)

			-- b = where locals start = max(args, params)*4
			f:load(a)
			f:load(framebase)
			f:i32load16u(dataframe.dotdotdot)
			f:tee(b)
			f:load(a)
			f:load(b)
			f:gtu()
			f:select()
			f:store(b)

			-- e = localc*4
			f:loadg(oluastack)
			f:i32load(coro.stack)
			f:i32load(buf.ptr)
			f:load(base)
			f:add()
			f:i32load(vec.base - 4)
			f:i32load(functy.localc)
			f:i32(2)
			f:shl()
			f:store(e)

			-- room for missing params, locals & objframe. New slots are nil
			f:load(b)
			f:load(a)
			f:sub()
			f:load(e)
			f:add()
			f:i32(objframe.sizeof)
			f:add()
			f:call(extendtmp)

			-- extendtmp may have moved things, reload
			f:call(loadframebase)
			f:tee(framebase)
			f:load(b)
			f:i32store16(dataframe.locals)

			f:load(framebase)
			f:load(b)
			f:load(e)
			f:add()
			f:i32store16(dataframe.frame)

			f:loadg(oluastack)
			f:i32load(coro.stack)
			f:i32load(buf.ptr)
			f:load(base)
			f:add()
			f:i32load(vec.base - 4)
			f:tee(d)
			f:i32load(functy.bc)
			f:i32(objframe.tmpbc)
			f:call(setnthtmp)

			f:load(d)
			f:i32load(functy.consts)
			f:i32(objframe.tmpconsts)
			f:call(setnthtmp)

			f:load(d)
			f:i32load(functy.frees)
			f:i32(objframe.tmpfrees)
			f:call(setnthtmp)
		end)

		-- push frame: stack is table, n fixed values, then results from retb on.
		-- Append values & results as t[1..], then leave only the table
		f:load(meta_callty)
		f:i32(calltypes.push)
		f:eq()
		f:iff(function()
			-- meta_key = offset of first value, meta_off = offset being appended
			f:load(meta_retb)
			f:load(meta_key)
			f:i32(2)
			f:shl()
			f:sub()
			f:tee(meta_key)
			f:store(meta_off)
			f:block(function(done)
				f:loop(function(loop)
					f:load(meta_off)
					f:load(meta_retb)
					f:load(c)
					f:add()
					f:geu()
					f:brif(done)

					-- key = 1 + nth value
					f:load(meta_off)
					f:load(meta_key)
					f:sub()
					f:i32(2)
					f:shru()
					f:i32(1)
					f:add()
					f:i64extendu()
					f:call(newi64)
					f:store(d)

					-- newi64 may have moved the stack, so reload it
					f:loadg(oluastack)
					f:i32load(coro.stack)
					f:i32load(buf.ptr)
					f:tee(a)
					f:load(meta_key)
					f:add()
					f:i32load(vec.base - 4)
					f:load(d)
					f:load(a)
					f:load(meta_off)
					f:add()
					f:i32load(vec.base)
					f:call(tblset)

					f:load(meta_off)
					f:i32(4)
					f:add()
					f:store(meta_off)
					f:br(loop)
				end)
			end)
			f:loadg(oluastack)
			f:i32load(coro.stack)
			f:load(meta_key)
			f:i32store(buf.len)
		end)

		f:br(scopes.nop)
	end)
	-- Call & AppendCall share this. callty is the type of the outermost new frame.
	-- varg: this frame's varargs are pushed & passed as extra args to the innermost call
	local function callarm(callty, varg)
	return function(scopes)
		if varg then
			pushvarg()
		end
		readArg()
		f:store(b)

		-- setup to reload bc after extendstr
		f:load(base)
		f:load(framebase)
		f:i32load16u(dataframe.frame)
		f:add()

		-- Setup to find current dataframe after extendstr
		f:loadg(oluastack)
		f:i32load(coro.data)
		f:i32load(buf.len)
		f:i32(dataframe.sizeof)
		f:sub()

		-- Setup for extendstr before loop
		f:loadg(oluastack)
		f:i32load(coro.data)
		readArg()
		f:tee(a)
		f:i32(dataframe.sizeof)
		f:mul()

		f:load(framebase)
		f:load(pc)
		f:load(a)
		f:i32(2)
		f:shl()
		f:add()
