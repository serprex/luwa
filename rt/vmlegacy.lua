		f:i32store16(dataframe.locals + dataframe.sizeof)

		f:load(c)
		f:load(b)
		f:load(e)
		f:load(base)
		f:add()
		f:i32load(vec.base - 4)
		f:tee(b)
		f:i32load(functy.localc)
		f:i32(2)
		f:shl()
		f:add()
		f:i32store16(dataframe.frame + dataframe.sizeof)

