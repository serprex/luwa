			f:call(nthtmp)
			f:call(tblset)

			f:load(a)
			f:i32(4)
			f:sub()
			f:tee(a)
			f:brif(loop)
		end)

		f:loadg(oluastack)
		f:i32load(coro.stack)
		f:tee(a)
		f:load(a)
		f:i32load(buf.len)
		f:load(c)
		f:i32(4)
		f:sub()
		f:sub()
		f:i32store(buf.len)

		f:br(scopes.nop)
	end)
	arm('meta', function(scopes)
		-- TODO fill in nils when paramc > metaparamc
		-- d is func
		-- push objframe
		-- a, c, e = stack.len, localc*4, paramc*4
		f:loadg(oluastack)
		f:i32load(coro.stack)
		f:tee(b)
		f:i32load(buf.len)
		f:tee(a)
		f:load(meta_retb)
		f:sub()
		f:store(base)

		f:load(b)
		f:i32(objframe.sizeof)
		f:load(d)
		f:i32load(functy.localc)
		f:i32(2)
		f:shl()
		f:tee(b)
		f:add()
		f:load(d)
		f:i32load(functy.paramc)
		f:i32(2)
		f:shl()
		f:tee(e)
		f:add()
		f:call(extendvec)

		-- writeobjframe
		f:tee(c)
		f:i32load(buf.ptr)
		f:load(c)
		f:i32load(buf.len)
		f:add()
		f:tee(c)
		assert(functy.consts == functy.bc + 4)
		assert(objframe.consts == objframe.bc + 4)

		-- reload metafunc
		f:loadg(oluastack)
		f:i32load(coro.stack)
		f:tee(d)
		f:i32load(buf.ptr)
		f:load(d)
		f:i32load(buf.len)
		f:add()
		f:load(meta_off)
		f:sub()
		f:i32load(vec.base)
		f:store(d)

		f:load(meta_key)
		f:iff(function()
			f:load(d)
			f:i32load(tbl.meta)
			f:load(meta_key)
			f:call(tblget)
			f:store(d)
		end)

		f:load(d)
		f:i64load(functy.bc)
		f:i64store(objframe.bc)

		f:load(c)
		f:load(d)
		f:i32load(functy.frees)
		f:i32store(objframe.frees)

		f:load(d)
		f:i32load(functy.paramc)

		-- push dataframe
		f:loadg(oluastack)
		f:i32load(coro.data)
		f:i32(dataframe.sizeof)
		f:call(extendstr)

		-- write dataframe
		f:tee(framebase)
		f:i32load(buf.ptr)
		f:load(framebase)
		f:i32load(buf.len)
		f:add()
		f:i32(dataframe.sizeof)
		f:sub()
		f:tee(framebase)
		f:load(meta_callty)
		f:i32store8(dataframe.type)

		f:load(framebase)
		f:i32(0)
		f:i32store(dataframe.pc)

		f:load(framebase)
		f:load(base)
		f:i32store(dataframe.base)

		f:load(framebase)
		f:load(e)
		f:i32store16(dataframe.dotdotdot)

		f:load(framebase)
		f:i32(0)
		f:i32store16(dataframe.retb)

		f:load(framebase)
		f:load(meta_retc)
		f:i32store16(dataframe.retc)

		f:load(framebase)
		f:load(a)
		f:load(base)
		f:sub()
		f:tee(a)
		f:i32store16(dataframe.locals)

		f:load(framebase)
		f:load(a)
		f:load(c)
		f:add()
		f:i32store16(dataframe.frame)

		f:br(scopes.nop)
	end)
	arm('pcp4', function(scopes)
		f:load(pc)
		f:i32(4)
		f:add()
		f:store(pc)
		f:br(scopes.nop) -- TODO remove when Nop is reachable
	end)
	arm(ops.Nop, function() f:unreachable() end)

	return arms
end
