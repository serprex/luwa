local M = require 'make'
local func = M.func

local alloc = require 'alloc'
local types, R, typeof, coro, corostate = alloc.types, alloc.R, alloc.typeof, alloc.coro, alloc.corostate
local vals = alloc.vals

local stack = require 'stack'
local tmppush, sget, df = stack.tmppush, stack.sget, stack.df

local frame = require 'frame'
local param, vargc, getf, setf = frame.param, frame.vargc, frame.getf, frame.setf

-- create(fn): a new suspended coro. fn waits in slot 0 of its stack until the first resume
-- TODO error when fn isn't a function
local coro_create = func(function(f)
	local co = f:locals(R.coro)
	local st = f:locals(R.stack)
	f:call(alloc.newcoro)
	f:tee(co)
	f:i32(16)
	f:call(alloc.newstack)
	f:tee(st)
	f:structset(coro, 'stack')
	f:load(co)
	f:i32(df.sizeof * 4)
	f:call(alloc.newframes)
	f:structset(coro, 'data')
	f:load(st)
	f:structget(alloc.stack, 'arr')
	f:i32(0)
	f:i32(0)
	f:call(param)
	f:arrayset(vals)
	f:load(st)
	f:i32(1)
	f:structset(alloc.stack, 'len')
	f:load(co)
	f:call(tmppush)
end)

-- resume(co, ...): run co until it yields, returns or errors. The values come back
-- to this frame (see frame.coroback), which carries on at nextpc. Returns the pc to run next
local coro_resume = func(i32, i32, function(f, nextpc)
	local co = f:locals(R.coro)
	local n, i = f:locals(i32, 2)
	local src = f:locals(R.stack)
	f:i32(df.pc)
	f:load(nextpc)
	f:call(stack.fset)
	f:i32(0)
	f:call(param)
	f:call(typeof)
	f:i32(types.coro)
	f:ne()
	f:iff(function()
		f:loadg(GS['bad argument #1 to resume (coroutine expected)'])
		f:call(frame.throw)
		f:ret()
	end)
	f:i32(0)
	f:call(param)
	f:refcast(R.coro)
	f:tee(co)
	f:structget(coro, 'state', false)
	f:i32(corostate.wait)
	f:ne()
	f:iff(function()
		alloc.lfalse(f)
		f:call(tmppush)
		f:load(co)
		f:structget(coro, 'state', false)
		f:i32(corostate.dead)
		f:eq()
		f:iff(R.str, function()
			f:loadg(GS['cannot resume dead coroutine'])
		end, function()
			f:loadg(GS['cannot resume non-suspended coroutine'])
		end)
		f:call(tmppush)
		f:load(nextpc)
		f:ret()
	end)

	-- the args to pass on are resume's varargs
	f:call(vargc)
	f:store(n)
	getf(f, 'base')
	getf(f, 'dotdotdot')
	f:add()
	f:store(i)
	f:loadg(gstack)
	f:store(src)

	-- this coro waits as normal while co runs
	f:loadg(oluastack)
	f:i32(corostate.norm)
	f:structset(coro, 'state')
	f:load(co)
	f:loadg(oluastack)
	f:structset(coro, 'caller')
	f:load(co)
	f:i32(corostate.live)
	f:structset(coro, 'state')
	f:load(co)
	f:call(frame.switchto)
	f:load(src)
	f:load(i)
	f:load(n)
	f:call(frame.pushfrom)

	f:loadg(gframes)
	f:structget(alloc.frames, 'len')
	f:eqz()
	f:iff(i32, function()
		-- first resume: call fn with the args. Its frame is type init, so returning ends co
		f:i32(frame.calltypes.init)
		f:i32(1)
		f:i32(frame.RETALL)
		f:call(frame.pushframe)
		f:i32(0)
		f:call(sget)
		f:refcast(R.functy)
		f:call(frame.framefor)
		f:i32(0)
	end, function()
		-- co is in yield, whose Return gives back the args just pushed
		getf(f, 'pc')
	end)
end)

-- yield(...): go back to the caller, whose resume returns true & the args
local coro_yield = func(i32, i32, function(f, nextpc)
	f:i32(df.pc)
	f:load(nextpc)
	f:call(stack.fset)
	f:loadg(oluastack)
	f:structget(coro, 'caller')
	f:refisnull()
	f:iff(function()
		f:loadg(GS['attempt to yield from outside a coroutine'])
		f:call(frame.throw)
		f:ret()
	end)
	f:i32(1)
	getf(f, 'base')
	getf(f, 'dotdotdot')
	f:add()
	f:call(vargc)
	f:i32(corostate.wait)
	f:call(frame.coroback)
end)

-- running(): the running coro, & whether it's the main one
local coro_running = func(function(f)
	f:loadg(oluastack)
	f:call(tmppush)
	f:loadg(oluastack)
	f:structget(coro, 'caller')
	f:refisnull()
	alloc.lbool(f)
	f:call(tmppush)
end)

local coro_status = func(function(f)
	local a = f:locals(V)
	f:i32(0)
	f:call(param)
	f:tee(a)
	f:call(typeof)
	f:i32(types.coro)
	f:ne()
	f:iff(function()
		-- error
		f:unreachable()
	end)
	f:block(R.str, function(res)
		f:switch(function()
			f:load(a)
			f:refcast(R.coro)
			f:structget(coro, 'state', false)
		end, corostate.dead, function()
			f:loadg(GS.dead)
			f:br(res)
		end, corostate.norm, function()
			f:loadg(GS.normal)
			f:br(res)
		end, corostate.live, function()
			f:loadg(GS.running)
			f:br(res)
		end, corostate.wait)
		f:loadg(GS.suspended)
	end)
	f:call(tmppush)
end)

return {
	coro_create = coro_create,
	coro_resume = coro_resume,
	coro_yield = coro_yield,
	coro_running = coro_running,
	coro_status = coro_status,
}
