-- Lua lexer in wasm. Produces a token string & a vec of the constants it found
-- (strings & numbers, each once). Tokens are bytes from lex.lua, idents, strings & numbers
-- are followed by their constant's index as 4 bytes.
-- This was written for linear memory. The body is kept as it was: the helpers below stand in
-- for the memory reads & Lua stack slots it used. Source "addresses" are indices into lxsrc,
-- & the stack slots for the output & temp string buffers became globals
local M = require 'make'
local func = M.func

local tokens = require 'lex'
local srcslot, lexslot = 20, 16

local alloc = require 'alloc'
local _float = require '_float'
local types, R, typeof, bytes, vals, stack, int = alloc.types, alloc.R, alloc.typeof, alloc.bytes, alloc.vals, alloc.stack, alloc.int

local _table = require '_table'
local tblget, tblset = _table.tblget, _table.tblset

-- sets the gstack global
local _stack = require 'stack'

-- Growable byte buffer
local bbuf = M.struct({
	{ i32, mut = true, name = 'len' },
	{ M.ref(bytes), mut = true, name = 'arr' },
}, { name = 'bbuf' })
local Rbbuf = M.refnull(bbuf)

local lxsrc = M.global(R.bytes, true)
-- token output, & the buffer for the string literal being read
local lxout = M.global(Rbbuf, true)
local lxtmp = M.global(Rbbuf, true)
-- last constant made, for lxaddval
local lxobj = M.global(V, true)
-- constant -> index. Floats have their own table, so 1 & 1.0 stay apart
local lxrmap = M.global(R.tbl, true)
local lxfrmap = M.global(R.tbl, true)
local lxconsts = M.global(R.stack, true)
-- token offset (from 1, like Lua's string index) -> line. lxline is the line at source index lxlnpos.
-- lxskip counts the 4 index bytes after a valued token, which aren't token starts
local lxlines = M.global(R.tbl, true)
local lxline = M.global(i32, true)
local lxlnpos = M.global(i32, true)
local lxskip = M.global(i32, true)
-- set when the source has a lexing error: its code (1 up, see lexerrors in prelude.lua),
-- where the bad token starts & where its text for the message ends (-1 for <eof>)
local lxerr = M.global(i32, true)
local lxerrs = M.global(i32, true)
local lxerre = M.global(i32, true)

local newbbuf = func(i32, M.ref(bbuf), function(f, cap)
	f:i32(0)
	f:load(cap)
	f:arraynewdefault(bytes)
	f:structnew(bbuf)
end)
local bbpush = func(Rbbuf, i32, void, function(f, b, ch)
	local arr, narr = f:locals(R.bytes, 2)
	local len = f:locals(i32)
	f:load(b)
	f:structget(bbuf, 'len')
	f:tee(len)
	f:load(b)
	f:structget(bbuf, 'arr')
	f:tee(arr)
	f:arraylen()
	f:eq()
	f:iff(function()
		f:load(len)
		f:i32(1)
		f:shl()
		f:i32(16)
		f:add()
		f:arraynewdefault(bytes)
		f:tee(narr)
		f:i32(0)
		f:load(arr)
		f:i32(0)
		f:load(len)
		f:arraycopy(bytes, bytes)
		f:load(b)
		f:load(narr)
		f:refasnonnull()
		f:structset(bbuf, 'arr')
		f:load(narr)
		f:store(arr)
	end)
	f:load(arr)
	f:load(len)
	f:load(ch)
	f:arrayset(bytes)
	f:load(b)
	f:load(len)
	f:i32(1)
	f:add()
	f:structset(bbuf, 'len')
end)
-- String of a buffer's bytes
local bbstr = func(Rbbuf, M.ref(alloc.str), function(f, b)
	local narr = f:locals(R.bytes)
	f:load(b)
	f:structget(bbuf, 'len')
	f:arraynewdefault(bytes)
	f:tee(narr)
	f:i32(0)
	f:load(b)
	f:structget(bbuf, 'arr')
	f:i32(0)
	f:load(b)
	f:structget(bbuf, 'len')
	f:arraycopy(bytes, bytes)
	f:load(narr)
	f:call(alloc.strfrombytes)
end)

-- n bytes of source from i, little endian. 0 past the end
local lxrd = func(i32, i32, i64, function(f, i, n)
	local len, k = f:locals(i32, 2)
	local r = f:locals(i64)
	f:loadg(lxsrc)
	f:arraylen()
	f:store(len)
	f:loop(function(loop)
		f:load(k)
		f:load(n)
		f:ltu()
		f:iff(function()
			f:load(i)
			f:load(k)
			f:add()
			f:load(len)
			f:ltu()
			f:iff(function()
				f:loadg(lxsrc)
				f:load(i)
				f:load(k)
				f:add()
				f:arrayget(bytes, false)
				f:i64extendu()
				f:load(k)
				f:i64extendu()
				f:i64(3)
				f:shl()
				f:shl()
				f:load(r)
				f:bor()
				f:store(r)
			end)
			f:load(k)
			f:i32(1)
			f:add()
			f:store(k)
			f:br(loop)
		end)
	end)
	f:load(r)
end)
local lxbyte = func(i32, i32, function(f, i)
	f:load(i)
	f:loadg(lxsrc)
	f:arraylen()
	f:ltu()
	f:iff(i32, function()
		f:loadg(lxsrc)
		f:load(i)
		f:arrayget(bytes, false)
	end, function()
		f:i32(0)
	end)
end)
local function lxn(n, wrap)
	return func(i32, wrap and i32 or i64, function(f, i)
		f:load(i)
		f:i32(n)
		f:call(lxrd)
		if wrap then
			f:i32wrap()
		end
	end)
end
local lx16, lx32, lx64 = lxn(2, true), lxn(4, true), lxn(8, false)

-- Stand ins for the Lua stack: the source's slot gives address 0, the output's gives handle 1
local nthtmp = func(i32, i32, function(f, slot)
	f:load(slot)
	f:i32(lexslot)
	f:eq()
	f:iff(i32, function()
		f:i32(1)
	end, function()
		f:load(slot)
		f:i32(srcslot)
		f:ne()
		f:load(slot)
		f:i32(srcslot + 4)
		f:ne()
		f:band()
		f:iff(function()
			f:unreachable()
		end)
		f:i32(0)
	end)
end)
-- Buffers are changed in place, so putting one back does nothing
local setnthtmp = func(i32, i32, void, function(f, h, slot) end)
local tmppush = func(i32, void, function(f, h) end)
local tmppop = func(function(f) end)
-- New string literal buffer, handle 2
local newstrbuf = func(i32, i32, function(f, cap)
	f:load(cap)
	f:call(newbbuf)
	f:storeg(lxtmp)
	f:i32(2)
end)
local pushstr = func(i32, i32, i32, function(f, h, ch)
	f:load(h)
	f:i32(1)
	f:eq()
	f:iff(Rbbuf, function()
		f:loadg(lxout)
	end, function()
		f:loadg(lxtmp)
	end)
	f:load(ch)
	f:call(bbpush)
	f:load(h)
end)
-- pushstr, & when ch starts a token of the output, note its line. pos is where the lexer is in the source,
-- somewhere inside the token or just after it, so newlines before pos are the ones before the token
local pushstrat = func(i32, i32, i32, i32, function(f, h, ch, pos)
	local b = f:locals(i32)
	f:load(h)
	f:i32(1)
	f:eq()
	f:iff(function()
		f:loadg(lxskip)
		f:iff(function()
			f:loadg(lxskip)
			f:i32(1)
			f:sub()
			f:storeg(lxskip)
		end, function()
			-- count newlines in src[lxlnpos, pos). \n, \r, \r\n & \n\r each count once
			f:block(function(done)
				f:loop(function(loop)
					f:loadg(lxlnpos)
					f:load(pos)
					f:ges()
					f:brif(done)
					f:loadg(lxlnpos)
					f:call(lxbyte)
					f:tee(b)
					f:i32(10)
					f:eq()
					f:load(b)
					f:i32(13)
					f:eq()
					f:bor()
					f:iff(function()
						f:loadg(lxline)
						f:i32(1)
						f:add()
						f:storeg(lxline)
						-- 10 + 13: the other half of the pair, skip it
						f:load(b)
						f:loadg(lxlnpos)
						f:i32(1)
						f:add()
						f:call(lxbyte)
						f:add()
						f:i32(23)
						f:eq()
						f:iff(function()
							f:loadg(lxlnpos)
							f:i32(1)
							f:add()
							f:storeg(lxlnpos)
						end)
					end)
					f:loadg(lxlnpos)
					f:i32(1)
					f:add()
					f:storeg(lxlnpos)
					f:br(loop)
				end)
			end)
			f:loadg(lxlines)
			f:loadg(lxout)
			f:structget(bbuf, 'len')
			f:i32(1)
			f:add()
			f:i64extendu()
			f:call(alloc.newi64)
			f:loadg(lxline)
			f:i64extendu()
			f:call(alloc.newi64)
			f:call(tblset)
			-- idents, strings & numbers have a 4 byte index after them
			f:load(ch)
			f:i32(192)
			f:band()
			f:iff(function()
				f:i32(4)
				f:storeg(lxskip)
			end)
		end)
	end)
	f:load(h)
	f:load(ch)
	f:call(pushstr)
end)

-- Constants are made into lxobj, then lxaddval adds it
local unbufstr = func(i32, i32, function(f, h)
	f:loadg(lxtmp)
	f:call(bbstr)
	f:storeg(lxobj)
	f:i32(0)
end)
local newi64 = func(i64, i32, function(f, x)
	f:load(x)
	f:call(alloc.newi64)
	f:storeg(lxobj)
	f:i32(0)
end)
local newf64 = func(f64, i32, function(f, x)
	f:load(x)
	f:call(alloc.newf64)
	f:storeg(lxobj)
	f:i32(0)
end)
-- src[start, start+len)
local lxsubstr = func(i32, i32, i32, function(f, start, len)
	local narr = f:locals(R.bytes)
	f:load(len)
	f:arraynewdefault(bytes)
	f:tee(narr)
	f:i32(0)
	f:loadg(lxsrc)
	f:load(start)
	f:load(len)
	f:arraycopy(bytes, bytes)
	f:load(narr)
	f:call(alloc.strfrombytes)
	f:storeg(lxobj)
	f:i32(0)
end)

-- Long string src[start, start+len): a newline right after the opening bracket is dropped,
-- and each newline (\n, \r, \r\n or \n\r) becomes \n
local lxlongstr = func(i32, i32, i32, function(f, start, len)
	local buf, narr = f:locals(R.bytes, 2)
	local k, stop, n, c = f:locals(i32, 4)
	local function isnl(get)
		get()
		f:i32(10)
		f:eq()
		get()
		f:i32(13)
		f:eq()
		f:bor()
	end
	local function loadc() f:load(c) end
	local function nextc()
		f:load(k)
		f:call(lxbyte)
	end
	-- c was a newline: skip the other half of a \r\n or \n\r
	local function skippair()
		f:load(k)
		f:load(stop)
		f:ltu()
		f:iff(function()
			isnl(nextc)
			nextc()
			f:load(c)
			f:ne()
			f:band()
			f:iff(function()
				f:load(k)
				f:i32(1)
				f:add()
				f:store(k)
			end)
		end)
	end
	f:load(len)
	f:arraynewdefault(bytes)
	f:store(buf)
	f:load(start)
	f:tee(k)
	f:load(len)
	f:add()
	f:store(stop)
	f:load(k)
	f:load(stop)
	f:ltu()
	f:iff(function()
		nextc()
		f:store(c)
		isnl(loadc)
		f:iff(function()
			f:load(k)
			f:i32(1)
			f:add()
			f:store(k)
			skippair()
		end)
	end)
	f:loop(function(loop)
		f:load(k)
		f:load(stop)
		f:ltu()
		f:iff(function()
			nextc()
			f:store(c)
			f:load(k)
			f:i32(1)
			f:add()
			f:store(k)
			isnl(loadc)
			f:iff(function()
				skippair()
				f:i32(10)
				f:store(c)
			end)
			f:load(buf)
			f:load(n)
			f:load(c)
			f:arrayset(bytes)
			f:load(n)
			f:i32(1)
			f:add()
			f:store(n)
			f:br(loop)
		end)
	end)
	f:load(n)
	f:arraynewdefault(bytes)
	f:tee(narr)
	f:i32(0)
	f:load(buf)
	f:i32(0)
	f:load(n)
	f:arraycopy(bytes, bytes)
	f:load(narr)
	f:call(alloc.strfrombytes)
	f:storeg(lxobj)
	f:i32(0)
end)

-- Index of lxobj in the constants, adding it if it's new
local lxaddval = func(i32, i32, function(f, dummy)
	local map = f:locals(R.tbl)
	local idx = f:locals(V)
	local n = f:locals(i32)
	f:loadg(lxobj)
	f:call(typeof)
	f:i32(types.float)
	f:eq()
	f:iff(R.tbl, function()
		f:loadg(lxfrmap)
	end, function()
		f:loadg(lxrmap)
	end)
	f:tee(map)
	f:loadg(lxobj)
	f:call(tblget)
	f:tee(idx)
	f:refisnull()
	f:iff(i32, function()
		f:loadg(lxconsts)
		f:structget(stack, 'len')
		f:store(n)
		-- the consts list is a Lua stack struct, borrow its push
		f:loadg(gstack)
		f:loadg(lxconsts)
		f:storeg(gstack)
		f:loadg(lxobj)
		f:call(_stack.tmppush)
		f:storeg(gstack)
		f:load(map)
		f:loadg(lxobj)
		f:load(n)
		f:i64extendu()
		f:call(alloc.newi64)
		f:call(tblset)
		f:load(n)
	end, function()
		f:load(idx)
		f:refcast(M.ref(int))
		f:structget(int, 'val')
		f:i32wrap()
	end)
end)

local CHZERO = string.byte('0')

-- Decimal number starting at src[i], whose first digit is ch (the caller passes '0' for .5).
-- Makes lxobj & gives the index just past the number. Keeps up to 19 digits exactly,
-- so ints are exact & floats round right. Ints too big for i64 become floats, like Lua
local decnum = func(i32, i32, i32, i32, i32, function(f, src, srclen, i, ch)
	local m = f:locals(i64)
	local nd, e10, trunc, isflt, d, ev, eneg, j = f:locals(i32, 8)
	local function byteat(idx)
		f:load(idx)
		f:load(src)
		f:add()
		f:call(lxbyte)
	end
	-- add digit d to m. In the fraction each digit kept lowers e10,
	-- in the int part each digit dropped raises it
	local function digit(frac)
		f:load(m)
		f:i64(0)
		f:eq()
		f:load(d)
		f:eqz()
		f:band()
		f:iff(function()
			-- leading zero
			if frac then
				f:load(e10)
				f:i32(1)
				f:sub()
				f:store(e10)
			end
		end, function()
			f:load(nd)
			f:i32(19)
			f:lts()
			f:iff(function()
				f:load(m)
				f:i64(10)
				f:mul()
				f:load(d)
				f:i64extendu()
				f:add()
				f:store(m)
				f:load(nd)
				f:i32(1)
				f:add()
				f:store(nd)
				if frac then
					f:load(e10)
					f:i32(1)
					f:sub()
					f:store(e10)
				end
			end, function()
				if not frac then
					f:load(e10)
					f:i32(1)
					f:add()
					f:store(e10)
				end
				f:load(d)
				f:iff(function()
					f:i32(1)
					f:store(trunc)
				end)
			end)
		end)
	end
	-- digits from i+1 on, leaves i at the first non digit
	local function digits(frac)
		f:loop(function(loop)
			f:load(i)
			f:i32(1)
			f:add()
			f:tee(i)
			f:load(srclen)
			f:ltu()
			f:iff(function()
				byteat(i)
				f:i32(CHZERO)
				f:sub()
				f:tee(d)
				f:i32(10)
				f:ltu()
				f:iff(function()
					digit(frac)
					f:br(loop)
				end)
			end)
		end)
	end
	local function isat(idx, c)
		f:load(idx)
		f:load(srclen)
		f:ltu()
		f:iff(i32, function()
			byteat(idx)
			f:i32(string.byte(c))
			f:eq()
		end, function()
			f:i32(0)
		end)
	end

	f:load(ch)
	f:i32(CHZERO)
	f:sub()
	f:store(d)
	digit(false)
	digits(false)
	isat(i, '.')
	f:iff(function()
		f:i32(1)
		f:store(isflt)
		digits(true)
	end)
	-- exponent: e or E, then maybe a sign, then at least one digit
	isat(i, 'e')
	isat(i, 'E')
	f:bor()
	f:iff(function()
		f:load(i)
		f:i32(1)
		f:add()
		f:store(j)
		isat(j, '-')
		f:tee(eneg)
		isat(j, '+')
		f:bor()
		f:iff(function()
			f:load(j)
			f:i32(1)
			f:add()
			f:store(j)
		end)
		f:block(function(noexp)
			f:load(j)
			f:load(srclen)
			f:geu()
			f:brif(noexp)
			byteat(j)
			f:i32(CHZERO)
			f:sub()
			f:i32(10)
			f:geu()
			f:brif(noexp)
			f:i32(1)
			f:store(isflt)
			f:loop(function(loop)
				f:load(j)
				f:load(srclen)
				f:ltu()
				f:iff(function()
					byteat(j)
					f:i32(CHZERO)
					f:sub()
					f:tee(d)
					f:i32(10)
					f:ltu()
					f:iff(function()
						-- big enough to mean 0 or inf, without overflowing
						f:load(ev)
						f:i32(100000)
						f:lts()
						f:iff(function()
							f:load(ev)
							f:i32(10)
							f:mul()
							f:load(d)
							f:add()
							f:store(ev)
						end)
						f:load(j)
						f:i32(1)
						f:add()
						f:store(j)
						f:br(loop)
					end)
				end)
			end)
			f:load(j)
			f:store(i)
			f:load(e10)
			f:i32(0)
			f:load(ev)
			f:sub()
			f:load(ev)
			f:load(eneg)
			f:select()
			f:add()
			f:store(e10)
		end)
	end)
	-- e10 is only above 0 here when int digits were dropped
	f:load(isflt)
	f:load(e10)
	f:bor()
	f:eqz()
	f:load(m)
	f:i64(0x7fffffffffffffff)
	f:leu()
	f:band()
	f:iff(i32, function()
		f:load(m)
		f:call(newi64)
	end, function()
		f:load(m)
		f:load(e10)
		f:load(trunc)
		f:call(_float.dectof64)
		f:call(newf64)
	end)
	f:drop()
	f:load(i)
end)

-- Hex digit's value, -1 if ch isn't one
local chex = func(i32, i32, function(f, ch)
	f:load(ch)
	f:i32(48)
	f:sub()
	f:tee(ch)
	f:i32(10)
	f:ltu()
	f:iff(i32, function()
		f:load(ch)
	end, function()
		f:load(ch)
		f:i32(17)
		f:sub()
		f:tee(ch)
		f:i32(6)
		f:geu()
		f:iff(function()
			f:i32(-1)
			f:load(ch)
			f:i32(32)
			f:sub()
			f:tee(ch)
			f:i32(6)
			f:geu()
			f:brif(f)
			f:drop()
		end)
		f:load(ch)
		f:i32(10)
		f:add()
	end)
end)

-- Where a numeral starting at p ends by C Lua's rule: it takes hex digits, dots &
-- exponents with their sign, then one letter or _ too. If that's not where the
-- number we read ends, it's a malformed number
local numend = func(i32, i32, function(f, p)
	local c, expo = f:locals(i32, 2)
	f:i32(string.byte('E'))
	f:store(expo)
	f:load(p)
	f:call(lxbyte)
	f:i32(string.byte('0'))
	f:eq()
	f:load(p)
	f:i32(1)
