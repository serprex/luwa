-- TODO unwind to pcall. For now print the message & trap
local std_error = func(function(f)
	f:call(param0)
	f:i32load(vec.base)
	f:call(rt.echoptr)
	f:drop()
	f:unreachable()
end)

local std_next = func(function(f)
	local hash, hlen, kv, key, mx = f:locals(i32, 5)

	f:call(param0)
	f:i32load(vec.base + 4)
	f:tee(key)
	f:call(_obj.hash)

	f:call(param0)
	f:i32load(vec.base)
	f:i32load(tbl.hash)
	f:tee(hash)
	f:i32load(vec.len)
	f:tee(hlen)
	f:remu()
	f:i32(-8)
	f:band()

	f:load(hash)
	f:add()
	f:store(kv)

	f:load(hash)
	f:load(hlen)
	f:add()
	f:store(mx)

	f:load(key)
	f:iff(function(findnext)
		f:loop(function(loop)
			f:load(kv)
			f:i32load(vec.base)
			f:eqz()
			f:iff(function()
				f:i32(NIL)
				f:call(tmppush)
				f:ret()
			end)

			f:load(kv)
			f:i32load(vec.base)
			f:load(key)
			f:call(_obj.eq)
			f:iff(function()
				f:load(kv)
				f:i32(8)
				f:add()
				f:tee(kv)
				f:load(mx)
				f:ne()
				f:brif(findnext)
				f:i32(NIL)
				f:call(tmppush)
				f:ret()
			end)

			f:load(kv)
			f:i32(8)
			f:add()
			f:tee(kv)
			f:load(mx)
			f:ne()
			f:brif(loop)
			f:i32(NIL)
			f:call(tmppush)
			f:ret()
		end)
	end)

	f:loop(function(loop)
		f:load(kv)
		f:i32load(vec.base)
		f:iff(function()
			f:load(kv)
			f:i32load(vec.base)
			f:call(tmppush)
			f:load(kv)
			f:i32load(vec.base + 4)
			f:call(tmppush)
			f:ret()
		end)
		f:load(kv)
		f:i32(8)
		f:add()
		f:tee(kv)
		f:load(mx)
		f:ne()
		f:brif(loop)
	end)
	f:i32(NIL)
	f:call(tmppush)
end)

local std_pcall = func(function(f)
	-- > func, p1, p2, ...
	-- < true, p1, p2, ...
	-- modify datastack: 2, 0, framesz, retc, base+1
	local a, valvec, base = f:locals(i32, 3)
	f:loadg(oluastack)
	f:i32load(coro.stack)
	f:i32load(buf.ptr)
	f:tee(valvec)
	f:loadg(oluastack)
	f:i32load(coro.data)
	f:tee(a)
	f:i32load(buf.ptr)
	f:load(a)
	f:i32load(buf.len)
	f:add()
	f:i32(dataframe.sizeof)
	f:sub()
	f:tee(a)
	-- TODO load localc from p0 & assign to dataframe

	f:i32load(dataframe.base)
	f:tee(base)
	f:add()
	f:i32(TRUE)
	f:i32store(vec.base)

	f:load(a)
	f:i32(calltypes.prot)
	f:i32store8(dataframe.type)

	f:load(a)
	f:i32(0)
	f:i32store(dataframe.pc)

	f:load(a)
	f:load(a)
	f:i32load(dataframe.retb)
	f:i32(4)
	f:add()
	f:i32store(dataframe.retb)
end)

local std_rawget = func(function(f)
	f:call(param0)
	f:i32load(vec.base)
	f:call(param0)
	f:i32load(vec.base + 4)
	f:call(_table.tblget)
	f:call(tmppush)
end)

local std_rawset = func(function(f)
	f:call(param0)
	f:i32load(vec.base)
	f:call(param0)
	f:i32load(vec.base + 4)
	f:call(param0)
	f:i32load(vec.base + 8)
