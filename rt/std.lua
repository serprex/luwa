-- Integer value of param i, or dflt when it's nil. Traps when it isn't an integer
-- TODO raise an error once error unwinding works
local function intparam(f, i, dflt)
	local tmp = f:locals(V)
	loadparam(f, i)
	f:tee(tmp)
	f:refisnull()
	f:iff(i32, dflt, function()
		f:load(tmp)
		f:call(toint)
		f:tee(tmp)
		f:refisnull()
		f:iff(function()
			f:unreachable()
		end)
		f:load(tmp)
		f:call(inti64)
		f:i32wrap()
	end)
end

-- _luwa.frame(co, n): function, pc & call type of frame n of coro co (nil for the running one),
-- counting from the top at 0. Nothing past the last frame. The function is nil when the frame has none
-- (the main init frame). pc is the frame's next op, for frames under the top that's just after their call
local std_frame = func(function(f)
	local co = f:locals(R.coro)
	local fr = f:locals(M.refnull(alloc.frames))
	local st = f:locals(M.refnull(alloc.stack))
	local arr = f:locals(R.i32s)
	local off, base = f:locals(i32, 2)
	loadparam(f, 0)
	f:refisnull()
	f:iff(R.coro, function()
		f:loadg(oluastack)
	end, function()
		loadparam(f, 0)
		f:refcast(R.coro)
	end)
	f:tee(co)
	f:structget(alloc.coro, 'stack')
	f:store(st)
	f:load(co)
	f:structget(alloc.coro, 'data')
	f:tee(fr)
	f:refisnull()
	f:iff(function()
		f:ret()
	end)
	f:load(fr)
	f:structget(alloc.frames, 'len')
	intparam(f, 1, function() f:i32(0) end)
	f:i32(1)
	f:add()
	f:i32(stack.df.sizeof)
	f:mul()
	f:sub()
	f:tee(off)
	f:i32(0)
	f:lts()
	f:iff(function()
		f:ret()
	end)
	f:load(fr)
	f:structget(alloc.frames, 'arr')
	f:tee(arr)
	f:load(off)
	f:i32(stack.df.base)
	f:add()
	f:arrayget(alloc.i32s)
	f:tee(base)
	f:i32(0)
	f:gts()
	f:load(base)
	f:load(st)
	f:structget(alloc.stack, 'len')
	f:les()
	f:band()
	f:iff(V, function()
		f:load(st)
		f:structget(alloc.stack, 'arr')
		f:load(base)
		f:i32(1)
		f:sub()
		f:arrayget(vals)
	end, function()
		f:refnull(M.heap.eq)
	end)
	f:call(tmppush)
	for _, field in ipairs{ 'pc', 'type' } do
		f:load(arr)
		f:load(off)
		f:i32(stack.df[field])
		f:add()
		f:arrayget(alloc.i32s)
		f:i64extends()
		f:call(newi64)
		f:call(tmppush)
	end
end)

-- _luwa.fn_info(fn): the info table load gave fn. false for wasm builtins (their bytecode starts with Syscall),
-- nil for prelude functions & non functions
local std_fn_info = func(function(f)
	local fn = f:locals(R.functy)
	local info = f:locals(V)
	local bc = f:locals(M.refnull(bytes))
	loadparam(f, 0)
	f:call(typeof)
	f:i32(types.functy)
	f:eq()
	f:iff(V, function()
		loadparam(f, 0)
		f:refcast(R.functy)
		f:tee(fn)
		f:structget(functy, 'info')
		f:tee(info)
		f:refisnull()
		f:iff(V, function()
			f:load(fn)
			f:structget(functy, 'bc')
			f:tee(bc)
			f:refisnull()
			f:iff(i32, function()
				f:i32(0)
			end, function()
				f:load(bc)
				f:arraylen()
				f:iff(i32, function()
					f:load(bc)
					f:i32(0)
					f:arrayget(bytes, false)
					f:i32(require('bc').Syscall)
					f:eq()
				end, function()
					f:i32(0)
				end)
			end)
			f:iff(V, function()
				alloc.lfalse(f)
			end, function()
				f:refnull(M.heap.eq)
			end)
		end, function()
			f:load(info)
		end)
	end, function()
		f:refnull(M.heap.eq)
	end)
	f:call(tmppush)
end)

