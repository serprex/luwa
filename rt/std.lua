	f:storeg(frame.callerrfn)
end)

-- Is v the string "#"
local ishash = func(V, i32, function(f, v)
	local b = f:locals(R.bytes)
	f:load(v)
	f:call(typeof)
	f:i32(types.str)
	f:ne()
	f:iff(function()
		f:i32(0)
		f:ret()
	end)
	f:load(v)
	f:refcast(R.str)
	f:structget(str, 'bytes')
	f:tee(b)
	f:arraylen()
	f:i32(1)
	f:eq()
	f:iff(i32, function()
		f:load(b)
		f:i32(0)
		f:arrayget(bytes, false)
		f:i32(string.byte('#'))
		f:eq()
	end, function()
		f:i32(0)
	end)
end)

-- select('#', ...) pushes the vararg count. select(n, ...) pushes the varargs from n on,
-- negative n counts from the end. Returns the pc to run next, like type, so bad n can raise
local std_select = func(i32, i32, function(f, nextpc)
	local n, cnt, len = f:locals(i32, 3)
	local function throw(msg)
		f:loadg(GS[msg])
		f:call(frame.throw)
		f:ret()
	end
	f:call(vargc)
	f:store(cnt)
	loadparam(f, 0)
	f:call(ishash)
	f:iff(function()
		f:load(cnt)
		f:i64extendu()
		f:call(newi64)
		f:call(tmppush)
		f:load(nextpc)
		f:ret()
	end)

	-- n = index of first vararg to return, from 0
	intparam(f, 0, function() throw("bad argument #1 to 'select' (number expected)") end)
	f:tee(n)
	f:i32(0)
	f:lts()
	f:iff(i32, function()
		f:load(cnt)
		f:load(n)
		f:add()
	end, function()
		f:load(n)
		f:i32(1)
		f:sub()
	end)
	f:tee(n)
	f:i32(0)
	f:lts()
	f:iff(function()
		throw("bad argument #1 to 'select' (index out of range)")
	end)
	f:load(n)
	f:load(cnt)
	f:gts()
	f:iff(function()
		f:load(cnt)
		f:store(n)
	end)

	-- cnt = how many to copy
	f:load(cnt)
	f:load(n)
	f:sub()
	f:tee(cnt)
	f:iff(function()
		f:call(stacklen)
		f:store(len)
		f:load(cnt)
		f:call(extendtmp)
		f:load(len)
		getf(f, 'base')
		getf(f, 'dotdotdot')
		f:add()
		f:load(n)
		f:add()
		f:load(cnt)
		f:call(scopy)
	end)
	f:load(nextpc)
end)

-- string.byte(s, i=1, j=i): push the bytes s[i..j] as integers. Negative i, j count from the end
local std_string_byte = func(function(f)
	local len, i, j = f:locals(i32, 3)
	local b = f:locals(R.bytes)

	loadparam(f, 0)
	f:call(typeof)
	f:i32(types.str)
	f:ne()
	f:iff(function()
		f:unreachable()
	end)
	loadparam(f, 0)
	f:refcast(R.str)
	f:structget(str, 'bytes')
	f:tee(b)
	f:arraylen()
	f:store(len)

	intparam(f, 1, function()
		f:i32(1)
	end)
	f:store(i)
	intparam(f, 2, function()
		f:load(i)
	end)
	f:store(j)

	-- negative: from the end
	f:load(i)
	f:i32(0)
	f:lts()
	f:iff(function()
		f:load(len)
		f:load(i)
		f:add()
		f:i32(1)
		f:add()
		f:store(i)
	end)
	f:load(j)
	f:i32(0)
	f:lts()
	f:iff(function()
		f:load(len)
		f:load(j)
		f:add()
		f:i32(1)
		f:add()
		f:store(j)
	end)
	-- clamp to 1..len
	f:load(i)
	f:i32(1)
	f:lts()
	f:iff(function()
		f:i32(1)
		f:store(i)
	end)
	f:load(j)
	f:load(len)
	f:gts()
	f:iff(function()
		f:load(len)
		f:store(j)
	end)

	f:block(function(done)
		f:loop(function(loop)
			f:load(i)
			f:load(j)
			f:gts()
			f:brif(done)
			f:load(b)
			f:load(i)
			f:i32(1)
			f:sub()
			f:arrayget(bytes, false)
			f:i64extendu()
			f:call(newi64)
			f:call(tmppush)
			f:load(i)
			f:i32(1)
			f:add()
			f:store(i)
			f:br(loop)
		end)
	end)
end)

-- string.char(...): string made of the given byte values
local std_string_char = func(function(f)
	local n, k = f:locals(i32, 2)
	local b = f:locals(R.bytes)
	local v = f:locals(V)

	f:call(vargc)
	f:tee(n)
	f:arraynewdefault(bytes)
	f:store(b)

	f:block(function(done)
		f:loop(function(loop)
			f:load(k)
			f:load(n)
			f:geu()
			f:brif(done)

			f:load(k)
			f:call(varg)
			f:call(toint)
			f:tee(v)
			f:refisnull()
			f:iff(function()
				f:unreachable()
			end)
			f:load(b)
			f:load(k)
			f:load(v)
			f:call(inti64)
			f:i32wrap()
			f:arrayset(bytes)

			f:load(k)
			f:i32(1)
			f:add()
			f:store(k)
			f:br(loop)
		end)
	end)

	f:load(b)
	f:call(alloc.strfrombytes)
	f:call(tmppush)
end)

-- string.sub(s, i=1, j=-1): bytes s[i..j]. Negative i, j count from the end
local std_string_sub = func(function(f)
	local len, i, j = f:locals(i32, 3)
	local b, nb = f:locals(R.bytes, 2)

	loadparam(f, 0)
	f:call(typeof)
	f:i32(types.str)
	f:ne()
	f:iff(function()
		f:unreachable()
	end)
	loadparam(f, 0)
	f:refcast(R.str)
	f:structget(str, 'bytes')
	f:tee(b)
	f:arraylen()
	f:store(len)

	intparam(f, 1, function()
		f:i32(1)
	end)
	f:store(i)
	intparam(f, 2, function()
		f:i32(-1)
	end)
	f:store(j)

	-- negative: from the end
	f:load(i)
	f:i32(0)
	f:lts()
	f:iff(function()
		f:load(len)
		f:load(i)
		f:add()
		f:i32(1)
		f:add()
		f:store(i)
	end)
	f:load(j)
	f:i32(0)
	f:lts()
	f:iff(function()
		f:load(len)
		f:load(j)
		f:add()
		f:i32(1)
		f:add()
		f:store(j)
	end)
	-- clamp to 1..len
	f:load(i)
	f:i32(1)
	f:lts()
	f:iff(function()
		f:i32(1)
		f:store(i)
	end)
	f:load(j)
	f:load(len)
	f:gts()
	f:iff(function()
		f:load(len)
		f:store(j)
	end)
	-- empty when i > j: copy 0 bytes from the start
	f:load(i)
	f:load(j)
	f:gts()
	f:iff(function()
		f:i32(1)
		f:store(i)
		f:i32(0)
		f:store(j)
	end)

	f:load(j)
	f:load(i)
	f:sub()
	f:i32(1)
	f:add()
	f:arraynewdefault(bytes)
	f:tee(nb)
	f:i32(0)
	f:load(b)
	f:load(i)
	f:i32(1)
	f:sub()
	f:load(j)
	f:load(i)
	f:sub()
	f:i32(1)
	f:add()
	f:arraycopy(bytes, bytes)
	f:load(nb)
	f:call(alloc.strfrombytes)
	f:call(tmppush)
end)

-- table.unpack(t, i=1, j=#t): push t[i..j]. # is the raw length
local std_table_unpack = func(function(f)
	local i, j = f:locals(i32, 2)
	local t = f:locals(R.tbl)
	loadparam(f, 0)
	f:refcast(R.tbl)
	f:store(t)
	intparam(f, 1, function()
		f:i32(1)
	end)
	f:store(i)
	intparam(f, 2, function()
		f:load(t)
		f:call(_table.tbllen)
	end)
	f:store(j)
	f:block(function(done)
		f:loop(function(loop)
			f:load(i)
			f:load(j)
			f:gts()
			f:brif(done)
			f:load(t)
			f:load(i)
			f:i64extends()
			f:call(_table.tblgeti)
			f:call(tmppush)
			f:load(i)
			f:i32(1)
			f:add()
			f:store(i)
			f:br(loop)
		end)
	end)
end)

-- _luwa.reinterp(x): an integer's bits as a float, or a float's bits as an integer
