-- Builtins written in wasm. Each reads its params with param(i) & pushes its results,
-- the builtin's bytecode then returns them
local M = require 'make'
local func = M.func

local alloc = require 'alloc'
local types, R, typeof, str, bytes, vals, vec, tbl, functy, newi64 =
	alloc.types, alloc.R, alloc.typeof, alloc.str, alloc.bytes, alloc.vals, alloc.vec, alloc.tbl, alloc.functy, alloc.newi64

local stack = require 'stack'
local tmppush, extendtmp, stacklen, scopy = stack.tmppush, stack.extendtmp, stack.stacklen, stack.scopy

local _table = require '_table'
local _obj = require 'obj'

local util = require 'util'
local toint, inti64 = util.toint, util.inti64

local rt = require 'rt'
local frame = require 'frame'
local param, vargc, varg, getf = frame.param, frame.vargc, frame.varg, frame.getf

local function loadparam(f, i)
	f:i32(i)
	f:call(param)
end

-- error(msg): unwind to the nearest pcall, see frame.throw. Returns the pc to run next
-- TODO level, & adding the position to string messages
local std_error = func(i32, i32, function(f, nextpc)
	-- error() or error(nil) raises this string, like Lua 5.5
	loadparam(f, 0)
	f:refisnull()
	f:iff(V, function()
		f:loadg(GS['<no error object>'])
	end, function()
		loadparam(f, 0)
	end)
	f:call(frame.throw)
end)

-- next(t, k): the next key & value, or just nil at the end
local std_next = func(function(f)
	local k, v = f:locals(V, 2)
	loadparam(f, 0)
	f:refcast(R.tbl)
	loadparam(f, 1)
	f:call(_table.tblnext)
	f:store(v)
	f:tee(k)
	f:call(tmppush)
	f:load(k)
	f:refisnull()
	f:eqz()
	f:iff(function()
		f:load(v)
		f:call(tmppush)
	end)
end)

-- pcall(fn, ...): push true, fn & the args, then call fn in a prot frame.
-- fn's results land after the true, & pcall's Return at nextpc gives them back.
-- On an error frame.throw finds the prot frame & turns the true into false
-- TODO a non-function fn traps in setupframe
local std_pcall = func(i32, i32, function(f, nextpc)
	local n = f:locals(i32)
	f:i32(stack.df.pc)
	f:load(nextpc)
	f:call(stack.fset)
	alloc.ltrue(f)
	f:call(tmppush)
	loadparam(f, 0)
	f:call(tmppush)
	f:call(frame.pushvarg)
	f:store(n)
	f:i32(frame.calltypes.prot)
	f:call(stacklen)
	f:load(n)
	f:sub()
	f:i32(frame.RETALL)
	f:call(frame.pushframe)
	f:call(frame.setupframe)
	f:i32(0)
end)

-- xpcall(fn, msgh, ...): pcall, but the frame is xprot, so errors call msgh first (see frame.throw).
-- msgh stays as this frame's param 1
local std_xpcall = func(i32, i32, function(f, nextpc)
	local n = f:locals(i32)
	f:i32(stack.df.pc)
	f:load(nextpc)
	f:call(stack.fset)
	alloc.ltrue(f)
	f:call(tmppush)
	loadparam(f, 0)
	f:call(tmppush)
	f:call(frame.pushvarg)
	f:store(n)
	f:i32(frame.calltypes.xprot)
	f:call(stacklen)
	f:load(n)
	f:sub()
	f:i32(frame.RETALL)
	f:call(frame.pushframe)
	f:call(frame.setupframe)
	f:i32(0)
end)

