-- _luwa.fn_set_*(fn, x): set a field of fn. val leaves the value to store
local function fnset(field, val)
	return func(function(f)
		loadparam(f, 0)
		f:refcast(R.functy)
		val(f)
		f:structset(functy, field)
	end)
end
local std_fn_set_localc = fnset('localc', function(f)
	intparam(f, 1, function() f:i32(0) end)
end)
local std_fn_set_paramc = fnset('paramc', function(f)
	intparam(f, 1, function() f:i32(0) end)
end)
local std_fn_set_isdotdotdot = fnset('isdotdotdot', function(f)
	loadparam(f, 1)
	f:call(_obj.truthy)
end)
local std_fn_set_bc = fnset('bc', function(f)
	loadparam(f, 1)
	f:refcast(R.str)
	f:structget(str, 'bytes')
end)
local function vecarr(f)
	loadparam(f, 1)
	f:refcast(R.vec)
	f:structget(vec, 'arr')
end
local std_fn_set_frees = fnset('frees', vecarr)
local std_fn_set_info = fnset('info', function(f)
	loadparam(f, 1)
end)
local std_fn_set_consts = fnset('consts', vecarr)

-- _luwa.vec_new(...): a vec holding the args
local std_vec_new = func(function(f)
	local n = f:locals(i32)
	local arr = f:locals(R.vals)
	f:call(vargc)
	f:tee(n)
	f:arraynewdefault(vals)
	f:tee(arr)
	f:i32(0)
	f:loadg(gstack)
	f:structget(alloc.stack, 'arr')
	getf(f, 'base')
	getf(f, 'dotdotdot')
	f:add()
	f:load(n)
	f:arraycopy(vals, vals)
	f:i32(types.vec)
	f:load(arr)
	f:refasnonnull()
	f:structnew(vec)
	f:call(tmppush)
end)

-- type(v): declared with no params & varargs, so type() with no args can raise.
-- Returns the pc to run next, like error
local std_type = func(i32, i32, function(f, nextpc)
	local a = f:locals(V)
	f:call(vargc)
	f:eqz()
	f:iff(function()
		f:loadg(GS["bad argument #1 to 'type' (value expected)"])
		f:call(frame.throw)
		f:ret()
	end)
	f:block(R.str, function(res)
		f:switch(function()
			loadparam(f, 0)
			f:tee(a)
			f:call(typeof)
		end, types.int, types.float, function()
			f:loadg(GS.number)
			f:br(res)
		end, types.single, function()
			f:load(a)
			f:refisnull()
			f:iff(R.str, function()
				f:loadg(GS['nil'])
			end, function()
				f:loadg(GS.boolean)
			end)
			f:br(res)
		end, types.tbl, function()
			f:loadg(GS.table)
			f:br(res)
		end, types.str, function()
			f:loadg(GS.string)
			f:br(res)
		end, types.vec, types.buf, function()
			f:loadg(GS.userdata)
			f:br(res)
		end, types.functy, function()
			f:loadg(GS['function'])
			f:br(res)
		end, types.coro)
		f:loadg(GS.thread)
	end)
	f:call(tmppush)
	f:load(nextpc)
end)

-- _luwa.lexgen(src): token string, value vec & token offset -> line table
local std_lexgen = func(function(f)
	local vs = f:locals(R.vec)
	local ls = f:locals(R.tbl)
	loadparam(f, 0)
	f:refcast(R.str)
	f:call(require('_lex').lex)
	f:store(ls)
	f:store(vs)
	f:call(tmppush)
	f:load(vs)
	f:call(tmppush)
	f:load(ls)
	f:call(tmppush)
end)

