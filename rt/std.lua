end)

-- select('#', ...) pushes the vararg count. select(n, ...) pushes the varargs from n on,
-- negative n counts from the end. The builtin's Return then returns everything pushed
-- TODO bad n should raise an error, it traps for now
local std_select = func(function(f)
	local framebase, base, n, cnt, p0 = f:locals(i32, 5)

	f:call(loadframebase)
	f:tee(framebase)
	f:i32load(dataframe.base)
	f:store(base)

	-- cnt = vararg count
	f:load(framebase)
	f:i32load16u(dataframe.locals)
	f:load(framebase)
	f:i32load16u(dataframe.dotdotdot)
	f:sub()
	f:i32(2)
	f:shru()
	f:store(cnt)

	f:loadg(oluastack)
	f:i32load(coro.stack)
	f:i32load(buf.ptr)
	f:load(base)
	f:add()
	f:i32load(vec.base)
	f:tee(p0)
	f:i32load8u(obj.type)
	f:i32(types.str)
	f:eq()
	f:iff(function()
		assert(str.base & 7 ~= 0)
		f:load(p0)
		f:i32load8u(str.base)
		f:i32(string.byte('#'))
		f:eq()
		f:load(p0)
		f:i32load(str.len)
		f:i32(1)
		f:eq()
		f:band()
		f:iff(function()
			f:load(cnt)
			f:i64extendu()
			f:call(newi64)
			f:call(tmppush)
			f:ret()
		end)
	end)

	f:load(p0)
	f:call(toint)
	f:tee(p0)
	f:eqz()
	f:iff(function()
		f:unreachable()
	end)

	-- n = index of first vararg to return, from 0
	f:load(p0)
	f:i64load(num.val)
	f:i32wrap()
	f:tee(n)
	f:i32(0)
	f:lts()
	f:iff(i32, function()
		f:load(cnt)
		f:load(n)
		f:add()
	end, function()
		f:load(n)
		f:i32(1)
		f:sub()
	end)
	f:tee(n)
	f:i32(0)
	f:lts()
	f:iff(function()
		f:unreachable()
	end)
	f:load(n)
	f:load(cnt)
	f:gts()
	f:iff(function()
		f:load(cnt)
		f:store(n)
	end)

	-- cnt = bytes to copy, p0 = old stack len
	f:load(cnt)
	f:load(n)
	f:sub()
	f:i32(2)
	f:shl()
	f:tee(cnt)
	f:iff(function()
		f:loadg(oluastack)
		f:i32load(coro.stack)
		f:i32load(buf.len)
		f:store(p0)
		f:load(cnt)
		f:call(extendtmp)

		-- extendtmp may have moved the stack, reload
		f:loadg(oluastack)
		f:i32load(coro.stack)
		f:i32load(buf.ptr)
		f:i32(vec.base)
		f:add()
		f:tee(base)
		f:load(p0)
		f:add()

		f:load(base)
		f:load(framebase)
		f:i32load(dataframe.base)
		f:add()
		f:load(framebase)
		f:i32load16u(dataframe.dotdotdot)
		f:add()
		f:load(n)
		f:i32(2)
		f:shl()
		f:add()

		f:load(cnt)
		f:call(memcpy4)
	end)
end)

-- Integer value of a param, or dflt when it's nil. Traps when it isn't an integer
-- TODO raise an error once error unwinding works
local function intparam(f, off, dflt)
	local tmp = f:locals(i32)
	f:call(param0)
	f:i32load(vec.base + off)
	f:tee(tmp)
	f:iff(i32, function()
		f:load(tmp)
		f:call(toint)
		f:tee(tmp)
		f:eqz()
		f:iff(function()
			f:unreachable()
		end)
		f:load(tmp)
		f:i64load(num.val)
		f:i32wrap()
	end, dflt)
end

-- string.byte(s, i=1, j=i): push the bytes s[i..j] as integers. Negative i, j count from the end
local std_string_byte = func(function(f)
	local len, i, j = f:locals(i32, 3)

	f:call(param0)
	f:i32load(vec.base)
	f:tee(len)
	f:i32load8u(obj.type)
	f:i32(types.str)
	f:ne()
	f:iff(function()
		f:unreachable()
	end)
	f:load(len)
	f:i32load(str.len)
	f:store(len)

	intparam(f, 4, function()
		f:i32(1)
	end)
	f:store(i)
	intparam(f, 8, function()
		f:load(i)
	end)
	f:store(j)

	-- negative: from the end
	f:load(i)
	f:i32(0)
	f:lts()
	f:iff(function()
		f:load(len)
		f:load(i)
		f:add()
		f:i32(1)
		f:add()
		f:store(i)
	end)
	f:load(j)
	f:i32(0)
	f:lts()
	f:iff(function()
		f:load(len)
		f:load(j)
		f:add()
		f:i32(1)
		f:add()
		f:store(j)
	end)
	-- clamp to 1..len
	f:load(i)
	f:i32(1)
	f:lts()
	f:iff(function()
		f:i32(1)
		f:store(i)
	end)
	f:load(j)
	f:load(len)
	f:gts()
	f:iff(function()
		f:load(len)
		f:store(j)
	end)

	f:block(function(done)
		f:loop(function(loop)
			f:load(i)
			f:load(j)
			f:gts()
			f:brif(done)
			-- s is reloaded each time, pushing can move the stack
			f:call(param0)
			f:i32load(vec.base)
			f:load(i)
			f:add()
			f:i32load8u(str.base - 1)
			f:i64extendu()
			f:call(newi64)
			f:call(tmppush)
			f:load(i)
			f:i32(1)
			f:add()
			f:store(i)
			f:br(loop)
		end)
	end)
end)

-- string.char(...): string made of the given byte values
local std_string_char = func(function(f)
	local framebase, n, k, s, b = f:locals(i32, 5)

	-- n = vararg count*4
	f:call(loadframebase)
	f:tee(framebase)
	f:i32load16u(dataframe.locals)
	f:load(framebase)
	f:i32load16u(dataframe.dotdotdot)
	f:sub()
	f:tee(n)
	f:i32(2)
	f:shru()
	f:call(newstr)
	f:storeg(otmp)

	f:block(function(done)
		f:loop(function(loop)
			f:load(k)
			f:load(n)
			f:geu()
			f:brif(done)

			-- vararg k: frames can't move here, but the stack buffer can
			f:call(loadframebase)
			f:tee(framebase)
			f:i32load(dataframe.base)
			f:load(framebase)
			f:i32load16u(dataframe.dotdotdot)
			f:add()
			f:load(k)
			f:add()
			f:loadg(oluastack)
			f:i32load(coro.stack)
			f:i32load(buf.ptr)
			f:add()
			f:i32load(vec.base)
			f:call(toint)
			f:tee(b)
			f:eqz()
			f:iff(function()
				f:unreachable()
			end)

			f:loadg(otmp)
			f:load(k)
			f:i32(2)
			f:shru()
			f:add()
			f:load(b)
			f:i64load(num.val)
			f:i32wrap()
			f:i32store8(str.base)

			f:load(k)
			f:i32(4)
			f:add()
			f:store(k)
			f:br(loop)
		end)
	end)

	f:loadg(otmp)
	f:call(tmppush)
end)

-- _luwa.fn_new(): an empty function object, filled in by the fn_set_* calls
local std_fn_new = func(function(f)
	f:call(newfunc)
	f:call(tmppush)
end)

-- _luwa.fn_set_localc(fn, n) & fn_set_paramc(fn, n)
local function fnsetcount(field)
	return func(function(f)
		local n = f:locals(i32)
		intparam(f, 4, function()
			f:i32(0)
		end)
		f:store(n)
		f:call(param0)
		f:i32load(vec.base)
		f:load(n)
		f:i32store(functy[field])
	end)
end
local std_fn_set_localc = fnsetcount('localc')
local std_fn_set_paramc = fnsetcount('paramc')

-- _luwa.vec_new(...): a vec holding the args
local std_vec_new = func(function(f)
	local framebase, n = f:locals(i32, 2)
	f:call(loadframebase)
	f:tee(framebase)
	f:i32load16u(dataframe.locals)
	f:load(framebase)
	f:i32load16u(dataframe.dotdotdot)
	f:sub()
	f:tee(n)
	f:call(newvec)
	f:storeg(otmp)

	-- newvec may move the stack, find the varargs after it
	f:loadg(otmp)
	f:i32(vec.base)
	f:add()
	f:call(loadframebase)
	f:tee(framebase)
	f:i32load(dataframe.base)
	f:load(framebase)
	f:i32load16u(dataframe.dotdotdot)
	f:add()
	f:loadg(oluastack)
	f:i32load(coro.stack)
	f:i32load(buf.ptr)
	f:add()
	f:i32(vec.base)
	f:add()
	f:load(n)
	f:call(memcpy4)

	f:loadg(otmp)
	f:call(tmppush)
end)

local std_type = func(function(f)
	local a = f:locals(i32)
	f:block(i32, function(res)
		f:switch(function()
			f:call(param0)
			f:i32load(vec.base)
			f:tee(a)
			f:i32load8u(obj.type)
		end, types.int, types.float, function()
			f:i32(GS.number)
			f:br(res)
		end, types.single, function()
			f:i32(GS.boolean)
			f:i32(GS['nil'])
			f:load(a)
			f:select()
			f:br(res)
		end, types.tbl, function()
			f:i32(GS.table)
			f:br(res)
		end, types.str, function()
			f:i32(GS.string)
			f:br(res)
		end, types.vec, types.buf, function()
			f:i32(GS.userdata)
			f:br(res)
		end, types.functy, function()
			f:i32(GS['function'])
			f:br(res)
		end, types.coro)
		f:i32(GS.thread)
	end)
	f:call(tmppush)
end)

return {
	error = std_error,
	next = std_next,
	pcall = std_pcall,
	rawget = std_rawget,
	rawset = std_rawset,
	select = std_select,
	type = std_type,
	string_byte = std_string_byte,
	fn_new = std_fn_new,
	fn_set_localc = std_fn_set_localc,
	fn_set_paramc = std_fn_set_paramc,
	vec_new = std_vec_new,
	string_char = std_string_char,
}
