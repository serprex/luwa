-- Call frames & metamethod lookup, as wasm helpers that microbc ops call.
-- Frame switching helpers return the pc to run next, or -1 when the main function returned.
-- Stack layout of a frame, in slots from base: the function at base-1, params, varargs,
-- locals, then the operand stack. eval gets bc, consts & frees from the function
local M = require 'make'
local func = M.func

local alloc = require 'alloc'
local types, R, typeof, tbl, vec, vals, int, functy, bytes, coro, nextid, newi64 =
	alloc.types, alloc.R, alloc.typeof, alloc.tbl, alloc.vec, alloc.vals, alloc.int, alloc.functy, alloc.bytes, alloc.coro,
	alloc.nextid, alloc.newi64
local corostate, lfalse = alloc.corostate, alloc.lfalse

local _table = require '_table'
local tblget, tblset = _table.tblget, _table.tblset

local _obj = require 'obj'

local stack = require 'stack'
local tmppush, extendtmp, stacklen, setstacklen, sget, sset, scopy, df, fget, fset, fpush, fpop =
	stack.tmppush, stack.extendtmp, stack.stacklen, stack.setstacklen, stack.sget, stack.sset, stack.scopy,
	stack.df, stack.fget, stack.fset, stack.fpush, stack.fpop

local rt = require 'rt' -- also makes GS, oluastack, ostrmt

local calltypes = {
	norm = 0, -- Reload locals
	init = 1, -- Return stack to coro src, src nil for main
	prot = 2, -- Reload locals
	call = 3, -- Continue call chain
	push = 4, -- Append intermediates to table
	bool = 5, -- Cast result to bool
	xprot = 6, -- Like prot, from xpcall: errors first call the handler, param 1 of the frame below
	xh = 7, -- xpcall's handler running, on top of the frames that raised. Its result is the error to unwind with
	tail = 8, -- Like call, but the next function in the chain is a tail call of the frame below
}
-- retc for "keep every result"
local RETALL = 0xffff

-- Little endian i32 at bc[i]: bytecode args are 4 bytes
local bcarg = func(R.bytes, i32, i32, function(f, bc, i)
	for k = 0, 3 do
		f:load(bc)
		f:load(i)
		if k > 0 then
			f:i32(k)
			f:add()
		end
		f:arrayget(bytes, false)
		if k > 0 then
			f:i32(k * 8)
			f:shl()
			f:bor()
		end
	end
end)

local function getf(f, field)
	f:i32(df[field])
	f:call(fget)
end
local function setf(f, field, val)
	f:i32(df[field])
	val()
	f:call(fset)
end
-- Faster ways to read & write fields when doing several: ftop loads the frames array into
-- local arr & the top frame's index into local at, then frd & fwr use them
local function ftop(f, arr, at)
	f:loadg(gframes)
	f:structget(alloc.frames, 'arr')
	f:store(arr)
	f:loadg(gframes)
	f:structget(alloc.frames, 'len')
	f:i32(df.sizeof)
	f:sub()
	f:store(at)
end
local function frd(f, arr, at, field)
	f:load(arr)
	f:load(at)
	if df[field] ~= 0 then
		f:i32(df[field])
		f:add()
	end
	f:arrayget(alloc.i32s)
end
local function fwr(f, arr, at, field, val)
	f:load(arr)
	f:load(at)
	if df[field] ~= 0 then
		f:i32(df[field])
		f:add()
	end
	val()
	f:arrayset(alloc.i32s)
end

-- Param i of the running function
local param = func(i32, V, function(f, i)
	getf(f, 'base')
	f:load(i)
	f:add()
	f:call(sget)
end)
-- How many varargs the running function got, & vararg i
local vargc = func(i32, function(f)
	getf(f, 'locals')
	getf(f, 'dotdotdot')
	f:sub()
end)
local varg = func(i32, V, function(f, i)
	getf(f, 'base')
	getf(f, 'dotdotdot')
	f:add()
	f:load(i)
	f:add()
	f:call(sget)
end)

-- Metatable of any value, nil if it has none
local getmeta = func(V, R.tbl, function(f, o)
	local ty = f:locals(i32)
	f:load(o)
	f:call(typeof)
	f:tee(ty)
	f:i32(types.tbl)
	f:eq()
	f:iff(R.tbl, function()
		f:load(o)
		f:refcast(M.ref(tbl))
		f:structget(tbl, 'meta')
	end, function()
		f:load(ty)
		f:i32(types.str)
		f:eq()
		f:iff(R.tbl, function()
			f:loadg(ostrmt)
		end, function()
			f:refnull(tbl)
		end)
	end)
end)

-- Bit in tbl.noflags for each common metamethod name. metaget's mask is the name's bit, or 0 for other names
local metabits = {}
for i, name in ipairs{ '__index', '__newindex', '__call', '__eq', '__lt', '__le', '__len', '__unm', '__concat',
	'__add', '__sub', '__mul', '__div', '__idiv', '__mod', '__pow',
	'__bnot', '__band', '__bor', '__bxor', '__shl', '__shr' } do
	metabits[name] = 1 << (i - 1)
end

-- o's metatable's field key, nil if no metatable. mask is key's metabits bit or 0.
-- When the metatable's bit is set the field is known missing, so it skips the probe.
-- A missing field sets the bit
local metaget = func(V, R.str, i32, V, function(f, o, key, mask)
	local m = f:locals(R.tbl)
	local v = f:locals(V)
	f:load(o)
	f:call(getmeta)
	f:tee(m)
	f:refisnull()
	f:iff(function()
		f:refnull(M.heap.eq)
		f:ret()
	end)
	f:load(m)
	f:structget(tbl, 'noflags')
	f:load(mask)
	f:band()
	f:iff(function()
		f:refnull(M.heap.eq)
		f:ret()
	end)
	f:load(m)
	f:load(key)
	f:call(tblget)
	f:tee(v)
	f:refisnull()
	f:iff(function()
		f:load(m)
		f:load(m)
		f:structget(tbl, 'noflags')
		f:load(mask)
		f:bor()
		f:structset(tbl, 'noflags')
	end)
	f:load(v)
end)

-- Metamethod for a binary op: a's, else b's
local binmeta = func(V, V, R.str, i32, V, function(f, a, b, key, mask)
	local h = f:locals(V)
	f:load(a)
	f:load(key)
	f:load(mask)
	f:call(metaget)
	f:tee(h)
	f:refisnull()
	f:iff(V, function()
		f:load(b)
		f:load(key)
		f:load(mask)
		f:call(metaget)
	end, function()
		f:load(h)
	end)
end)

-- Lua functions from the prelude (_luwa.seterrfns) that raise runtime errors with a good message.
-- errfn(kind, operands...) is called by the Error mop, callerrfn(value, args...) in place of a value
-- that can't be called. Until they're set errors are 'invalid operation' & calls of non functions trap
local errfn = M.global(V, true)
local callerrfn = M.global(V, true)
-- tbcfn(msg, depth) closes to-be-closed variables after a pcall catches msg, giving the error to return.
-- Also set by seterrfns
local tbcfn = M.global(V, true)
-- set while unwinding with the result of an xpcall handler, so the handler isn't called again
local nohandler = M.global(i32, true)

-- Receiver for idxwalk's result when it's an __index function to call, otherwise nil
local idxself = M.global(V, true)

-- a[b], following __index tables. When it reaches an __index function,
-- returns that function & sets idxself to the value to call it with
local idxwalk = func(V, V, V, function(f, a, b)
	local ty, i = f:locals(i32, 2)
	local v, h = f:locals(V, 2)
	local arr = f:locals(R.vals)
	f:refnull(M.heap.eq)
	f:storeg(idxself)
	f:loop(function(loop)
		-- TODO Lua limits chains to 2000 length to try detect infinite loops
		f:load(a)
		f:call(typeof)
		f:tee(ty)
		f:i32(types.tbl)
		f:eq()
		f:iff(function()
			f:load(a)
			f:refcast(R.tbl)
			f:load(b)
			f:call(tblget)
			f:tee(v)
			f:refisnull()
			f:eqz()
			f:iff(function()
				f:load(v)
				f:ret()
			end)
			f:load(a)
			f:loadg(GS.__index)
			f:i32(metabits.__index)
			f:call(metaget)
			f:tee(h)
			f:refisnull()
			f:iff(function()
				f:refnull(M.heap.eq)
				f:ret()
			end)
		end, function()
			f:load(ty)
			f:i32(types.vec)
			f:eq()
			f:iff(function()
				-- vecs (eg the lexer's value list) index from 1 with integers, nil past the end
				f:load(b)
				f:call(typeof)
				f:i32(types.int)
				f:ne()
				f:iff(function()
					f:unreachable()
				end)
				f:load(b)
				alloc.intvalst(f)
				f:i32wrap()
				f:i32(1)
				f:sub()
				f:tee(i)
				-- unsigned compare also catches keys below 1
				f:load(a)
				f:refcast(M.ref(vec))
				f:structget(vec, 'arr')
				f:tee(arr)
				f:arraylen()
				f:ltu()
				f:iff(V, function()
					f:load(arr)
					f:load(i)
					f:arrayget(vals)
				end, function()
					f:refnull(M.heap.eq)
				end)
				f:ret()
			end)
			f:load(a)
			f:loadg(GS.__index)
			f:i32(metabits.__index)
			f:call(metaget)
			f:tee(h)
			f:refisnull()
			f:iff(function()
				-- TODO error: attempt to index a value
				f:unreachable()
			end)
		end)
		f:load(h)
		f:call(typeof)
		f:i32(types.functy)
		f:eq()
		f:iff(function()
			f:load(a)
			f:storeg(idxself)
			f:load(h)
			f:ret()
		end)
		-- __index is a table (or string): index it next
		f:load(h)
		f:store(a)
		f:br(loop)
	end)
	f:unreachable()
end)

-- a[b] = c, following __newindex tables. Stores & returns nil, or when it reaches
-- an __newindex function returns that function & sets idxself to the value to call it with.
-- a is a table, or has a __newindex
local newidxwalk = func(V, V, V, V, function(f, a, b, c)
	local h = f:locals(V)
	f:refnull(M.heap.eq)
	f:storeg(idxself)
	f:loop(function(loop)
		-- TODO Lua limits chains to 2000 length to try detect infinite loops
		f:load(a)
		f:call(typeof)
		f:i32(types.tbl)
		f:eq()
		f:iff(function()
			-- no metatable, a key already there, or no __newindex: raw set
			f:load(a)
			f:refcast(R.tbl)
			f:structget(tbl, 'meta')
			f:refisnull()
			f:iff(i32, function()
				f:i32(0)
			end, function()
				f:load(a)
				f:refcast(R.tbl)
				f:load(b)
				f:call(tblget)
				f:refisnull()
			end)
			f:iff(i32, function()
				f:load(a)
				f:loadg(GS.__newindex)
				f:i32(metabits.__newindex)
				f:call(metaget)
				f:tee(h)
				f:refisnull()
			end, function()
				f:i32(1)
			end)
			f:iff(function()
				f:load(a)
				f:refcast(R.tbl)
				f:load(b)
				f:load(c)
				f:call(tblset)
				f:refnull(M.heap.eq)
				f:ret()
			end)
		end, function()
			f:load(a)
			f:loadg(GS.__newindex)
			f:i32(metabits.__newindex)
			f:call(metaget)
			f:tee(h)
			f:refisnull()
			f:iff(function()
				-- TODO error: attempt to index a value
				f:unreachable()
			end)
		end)
		f:load(h)
		f:call(typeof)
		f:i32(types.functy)
		f:eq()
		f:iff(function()
			f:load(a)
			f:storeg(idxself)
			f:load(h)
			f:ret()
		end)
		-- __newindex is a table: set in it next
		f:load(h)
		f:store(a)
		f:br(loop)
	end)
	f:unreachable()
end)

-- Push a frame. dotdotdot, locals & frame are filled in by setupframe
local pushframe = func(i32, i32, i32, void, function(f, callty, base, retc)
	local at = f:locals(i32)
	local arr = f:locals(R.i32s)
	f:call(fpush)
	f:store(at)
	f:loadg(gframes)
	f:structget(alloc.frames, 'arr')
	f:store(arr)
	fwr(f, arr, at, 'type', function() f:load(callty) end)
	fwr(f, arr, at, 'pc', function() f:i32(0) end)
	fwr(f, arr, at, 'base', function() f:load(base) end)
	-- results go where the function was
	fwr(f, arr, at, 'retb', function() f:i32(-1) end)
	fwr(f, arr, at, 'retc', function() f:load(retc) end)
	for _, k in ipairs{'dotdotdot', 'locals', 'frame'} do
		fwr(f, arr, at, k, function() f:i32(0) end)
	end
end)

-- Finish the top frame for fn, whose args go from base to the end of the stack.
-- Adds missing params & locals after the args
local framefor = func(R.functy, void, function(f, fn)
	local at, argc, paramc, localc, locals = f:locals(i32, 5)
	local arr = f:locals(R.i32s)
	ftop(f, arr, at)
	f:call(stacklen)
	frd(f, arr, at, 'base')
	f:sub()
	f:store(argc)

	f:load(fn)
	f:structget(functy, 'paramc')
	f:store(paramc)
	f:load(fn)
	f:structget(functy, 'localc')
	f:store(localc)

	-- locals start after params & varargs: max(args, params)
	f:load(argc)
	f:load(paramc)
	f:load(argc)
	f:load(paramc)
	f:gts()
	f:select()
	f:store(locals)

	-- new slots are nil
	f:load(locals)
	f:load(argc)
	f:sub()
	f:load(localc)
	f:add()
	f:call(extendtmp)

	fwr(f, arr, at, 'dotdotdot', function() f:load(paramc) end)
	fwr(f, arr, at, 'locals', function() f:load(locals) end)
	fwr(f, arr, at, 'frame', function()
		f:load(locals)
		f:load(localc)
		f:add()
	end)
end)

-- Finish the top frame, its function is at base-1
local setupframe = func(function(f)
	local fn, h = f:locals(V, 2)
	local base, n = f:locals(i32, 2)
	getf(f, 'base')
	f:i32(1)
	f:sub()
	f:call(sget)
	f:store(fn)
	f:loop(function(loop)
		f:load(fn)
		f:call(typeof)
		f:i32(types.functy)
		f:ne()
		f:iff(function()
			-- not a function: call its __call with it as the first arg
			-- TODO error when there's no __call
			f:load(fn)
			f:loadg(GS.__call)
			f:i32(metabits.__call)
			f:call(metaget)
			f:tee(h)
			f:refisnull()
			f:iff(function()
				-- call callerrfn with the value instead, it raises the error
				f:loadg(callerrfn)
				f:tee(h)
				f:refisnull()
				f:iff(function()
					f:unreachable()
				end)
			end)
			-- shift fn & args up 1 slot, then put h where fn was
			getf(f, 'base')
			f:tee(base)
			f:call(stacklen)
			f:load(base)
			f:sub()
			f:i32(1)
			f:add()
			f:store(n)
			f:i32(1)
			f:call(extendtmp)
			f:load(base)
			f:load(base)
			f:i32(1)
			f:sub()
			f:load(n)
			f:call(scopy)
			f:load(base)
			f:i32(1)
			f:sub()
			f:load(h)
			f:call(sset)
			f:load(h)
			f:store(fn)
			f:br(loop)
		end)
	end)
	f:load(fn)
	f:refcast(R.functy)
	f:call(framefor)
end)

-- Call the function under the top argc values, keeping retc results.
-- nextpc is where the current frame carries on after
local callmeta = func(i32, i32, i32, i32, i32, function(f, argc, callty, retc, nextpc)
	setf(f, 'pc', function() f:load(nextpc) end)
	f:load(callty)
	f:call(stacklen)
	f:load(argc)
	f:sub()
	f:load(retc)
	f:call(pushframe)
	f:call(setupframe)
	f:i32(0)
end)

-- Copy this frame's varargs to the top of the stack. Returns how many
local pushvarg = func(i32, function(f)
	local n, len, src = f:locals(i32, 3)
	getf(f, 'locals')
	getf(f, 'dotdotdot')
	f:sub()
	f:tee(n)
	f:i32(0)
	f:gts()
	f:iff(i32, function()
		getf(f, 'base')
		getf(f, 'dotdotdot')
		f:add()
		f:store(src)
		f:call(stacklen)
		f:store(len)
		f:load(n)
		f:call(extendtmp)
		f:load(len)
		f:load(src)
		f:load(n)
		f:call(scopy)
		f:load(n)
	end, function()
		f:i32(0)
	end)
end)

-- Push the first n varargs, nil past the last one
local loadvarg = func(i32, void, function(f, n)
	local i, vlen, src = f:locals(i32, 3)
	getf(f, 'locals')
	getf(f, 'dotdotdot')
	f:sub()
	f:store(vlen)
	getf(f, 'base')
	getf(f, 'dotdotdot')
	f:add()
	f:store(src)
	f:block(function(done)
		f:loop(function(loop)
			f:load(i)
			f:load(n)
			f:geu()
			f:brif(done)

			f:load(i)
			f:load(vlen)
			f:lts()
			f:iff(V, function()
				f:load(src)
				f:load(i)
				f:add()
				f:call(sget)
			end, function()
				f:refnull(M.heap.eq)
			end)
			f:call(tmppush)

			f:load(i)
			f:i32(1)
			f:add()
			f:store(i)
			f:br(loop)
		end)
	end)
end)

-- Stack is table, then n values. Set t[1..n] to them & leave only the table
local appendn = func(i32, void, function(f, n)
	local first, i = f:locals(i32, 2)
	local t = f:locals(R.tbl)
	f:call(stacklen)
	f:load(n)
	f:sub()
	f:tee(first)
	f:i32(1)
	f:sub()
	f:call(sget)
	f:refcast(R.tbl)
	f:store(t)
	f:block(function(done)
		f:loop(function(loop)
			f:load(i)
			f:load(n)
			f:geu()
			f:brif(done)

			f:load(t)
			f:load(i)
			f:i32(1)
			f:add()
			f:i64extendu()
			f:call(newi64)
			f:load(first)
			f:load(i)
			f:add()
			f:call(sget)
			f:call(tblset)

			f:load(i)
			f:i32(1)
			f:add()
			f:store(i)
			f:br(loop)
		end)
	end)
	f:load(first)
	f:call(setstacklen)
end)

-- Like appendn, then append this frame's varargs too
local appendvarg = func(i32, void, function(f, n)
	f:load(n)
	f:call(pushvarg)
	f:add()
	f:call(appendn)
end)

-- Copy of function proto, with the top n stack values popped into its frees
local makeclosure = func(V, i32, V, function(f, protov, n)
	local proto = f:locals(R.functy)
	local frees = f:locals(R.vals)
	local len = f:locals(i32)
	f:load(protov)
	f:refcast(R.functy)
	f:store(proto)

	f:load(n)
	f:iff(R.vals, function()
		f:load(n)
		f:arraynewdefault(vals)
		f:tee(frees)
		f:i32(0)
		f:loadg(gstack)
		f:structget(alloc.stack, 'arr')
		f:call(stacklen)
		f:load(n)
		f:sub()
		f:tee(len)
		f:load(n)
		f:arraycopy(vals, vals)
		f:load(len)
		f:call(setstacklen)
		f:load(frees)
	end, function()
		f:load(proto)
		f:structget(functy, 'frees')
	end)
	f:store(frees)

	f:i32(types.functy)
	f:call(nextid)
	f:load(proto)
	f:structget(functy, 'isdotdotdot', false)
	f:load(proto)
	f:structget(functy, 'bc')
	f:load(proto)
	f:structget(functy, 'consts')
	f:load(frees)
	f:load(proto)
	f:structget(functy, 'localc')
	f:load(proto)
	f:structget(functy, 'paramc')
	f:load(proto)
	f:structget(functy, 'info')
	-- closures share the proto's JIT'd code
	f:load(proto)
	f:structget(functy, 'jit')
	f:structnew(functy)
end)

-- Most frames a coro can have, & how many more an error handler gets after a stack overflow.
-- Past those the error is "error in error handling", like C Lua
local MAXFRAMES, EXTRAFRAMES = 200000, 2000
-- set from a stack overflow until the stack is well below the limit again
local overflowing = M.global(i32, true)
local throw -- below, callchain raises with it

-- Is v a Lua function from load (its info is a table). Only those get tail calls:
-- builtins & prelude functions stand in for C functions, which keep the caller's frame in C Lua too
local isluafn = func(V, i32, function(f, v)
	f:load(v)
	f:call(typeof)
	f:i32(types.functy)
	f:eq()
	f:iff(i32, function()
		f:load(v)
		f:refcast(R.functy)
		f:structget(functy, 'info')
		f:call(typeof)
		f:i32(types.tbl)
		f:eq()
	end, function()
		f:i32(0)
	end)
end)

-- Tail call from the top frame: the function at slot src & its args (up to the end of the stack)
-- move down to replace the frame's function & args. The frame keeps its type, retb & retc.
-- When it isn't a Lua function, call it in a new frame keeping every result instead,
-- the frame's next op is a Return that returns them. Returns the pc to run next
local tailcall = func(i32, i32, function(f, src)
	local base, n = f:locals(i32, 2)
	f:load(src)
	f:call(sget)
	f:call(isluafn)
	f:eqz()
	f:iff(function()
		f:i32(calltypes.norm)
		f:load(src)
		f:i32(1)
		f:add()
		f:i32(RETALL)
		f:call(pushframe)
		f:call(setupframe)
		f:i32(0)
		f:ret()
	end)
	getf(f, 'base')
	f:i32(1)
	f:sub()
	f:tee(base)
	f:load(src)
	f:call(stacklen)
	f:load(src)
	f:sub()
	f:tee(n)
	f:call(scopy)
	f:load(base)
	f:load(n)
	f:add()
	f:call(setstacklen)
	-- the function is at base-1 now, a functy, so setupframe goes straight to framefor
	f:call(setupframe)
	f:i32(0)
end)

-- Call op family. Bytecode args from pc: retc, n, then n arg counts, outermost call first.
-- Stack holds f1 args1.. f2 args2.. ... fn argsn.., the innermost call runs first.
-- Outer calls get frames now (type call) & are set up as each inner one returns.
-- tail: the outermost call is a tail call. It gets no frame, the next call's frame is type tail,
-- so when that returns retframe calls tailcall. With one call tailcall runs now
local function mkcallchain(varg, tail)
	return func(R.bytes, i32, i32, i32, function(f, bc, pc, callty)
		local n, i, off, vb, cnt = f:locals(i32, 5)
		local function arg(k)
			f:load(bc)
			f:load(pc)
			k()
			f:i32(2)
			f:shl()
			f:add()
			f:call(bcarg)
		end
		arg(function() f:i32(1) end)
		f:store(n)

		if varg then
			f:call(pushvarg)
			f:store(vb)
		end

		setf(f, 'pc', function()
			f:load(pc)
			f:load(n)
			f:i32(2)
			f:add()
			f:i32(2)
			f:shl()
			f:add()
		end)

		-- too many frames: raise "stack overflow" with the prelude's errfn, which gets extra frames
		f:loadg(gframes)
		f:structget(alloc.frames, 'len')
		f:tee(cnt)
		f:i32(df.sizeof * MAXFRAMES)
		f:geu()
		f:iff(function()
			f:load(cnt)
			f:i32(df.sizeof * (MAXFRAMES + EXTRAFRAMES))
			f:geu()
			f:loadg(errfn)
			f:refisnull()
			f:bor()
			f:iff(function()
				f:loadg(GS['error in error handling'])
				f:call(throw)
				f:ret()
			end)
		end)
		-- the first time past the limit. Calls after that use the extra frames
		f:load(cnt)
		f:i32(df.sizeof * MAXFRAMES)
		f:geu()
		f:loadg(overflowing)
		f:eqz()
		f:band()
		f:iff(function()
			f:i32(1)
			f:storeg(overflowing)
			f:loadg(errfn)
			f:call(tmppush)
			f:loadg(GS.overflow)
			f:call(tmppush)
			f:i32(1)
			f:i32(calltypes.norm)
			f:i32(0)
			getf(f, 'pc')
			f:call(callmeta)
			f:ret()
		end)
		f:load(cnt)
		f:i32(df.sizeof * (MAXFRAMES - EXTRAFRAMES))
		f:ltu()
		f:iff(function()
			f:i32(0)
			f:storeg(overflowing)
		end)

		-- one call, the usual case: the function is under its args
		f:load(n)
		f:i32(1)
		f:eq()
		f:iff(function()
			f:call(stacklen)
			f:load(vb)
			f:sub()
			arg(function() f:i32(2) end)
			f:sub()
			f:i32(1)
			f:sub()
			if tail then
				f:call(tailcall)
				f:ret()
			end
			f:i32(1)
			f:add()
			f:store(off)
			f:load(callty)
			f:load(off)
			arg(function() f:i32(0) end)
			f:call(pushframe)
			f:call(setupframe)
			f:i32(0)
			f:ret()
		end)

		-- off = where the outermost function sits
		f:call(stacklen)
		f:load(vb)
		f:sub()
		f:store(off)
		f:loop(function(loop)
			f:load(off)
			arg(function()
				f:load(i)
				f:i32(2)
				f:add()
			end)
			f:i32(1)
			f:add()
			f:sub()
			f:store(off)

			f:load(i)
			f:i32(1)
			f:add()
			f:tee(i)
			f:load(n)
			f:ltu()
			f:brif(loop)
		end)

		f:i32(0)
		f:store(i)
		f:loop(function(loop)
			local function push()
				-- outermost: callty & retc, the rest: type call keeping every result
				f:i32(calltypes.call)
				f:load(callty)
				f:load(i)
				f:select()
				if tail then
					-- the call after the tail call
					f:i32(calltypes.tail)
					f:load(i)
					f:i32(1)
					f:ne()
					f:select()
				end
				f:load(off)
				f:i32(1)
				f:add()
				f:i32(RETALL)
				arg(function() f:i32(0) end)
				f:load(i)
				f:select()
				f:call(pushframe)
			end
			if tail then
				f:load(i)
				f:iff(push)
			else
				push()
			end

			f:load(off)
			arg(function()
				f:load(i)
				f:i32(2)
				f:add()
			end)
			f:i32(1)
			f:add()
			f:add()
			f:store(off)

			f:load(i)
			f:i32(1)
			f:add()
			f:tee(i)
			f:load(n)
			f:ltu()
			f:brif(loop)
		end)
		f:call(setupframe)
		f:i32(0)
	end)
end
local callchain = mkcallchain(false, false)
local callchainvarg = mkcallchain(true, false)
local tailchain = mkcallchain(false, true)
local tailchainvarg = mkcallchain(true, true)

-- Make co the running coro: its stack & frames become gstack & gframes
local switchto = func(R.coro, void, function(f, co)
	f:load(co)
	f:storeg(oluastack)
	f:load(co)
	f:structget(coro, 'stack')
	f:storeg(gstack)
	f:load(co)
	f:structget(coro, 'data')
	f:storeg(gframes)
end)

-- Push n values of another coro's stack, starting at slot i
local pushfrom = func(R.stack, i32, i32, void, function(f, src, i, n)
	local len = f:locals(i32)
	f:call(stacklen)
	f:store(len)
	f:load(n)
	f:call(extendtmp)
	f:loadg(gstack)
	f:structget(alloc.stack, 'arr')
	f:load(len)
	f:load(src)
	f:structget(alloc.stack, 'arr')
	f:load(i)
	f:load(n)
	f:arraycopy(vals, vals)
end)

-- The running coro stops & goes back to its caller, leaving itself in state st.
-- The caller's resume returns ok, then n values from slot i of the coro's stack.
-- Returns the caller's pc
local coroback = func(i32, i32, i32, i32, i32, function(f, ok, i, n, st)
	local co = f:locals(R.coro)
	local src = f:locals(R.stack)
	f:loadg(oluastack)
	f:tee(co)
	f:load(st)
	f:structset(coro, 'state')
	f:loadg(gstack)
	f:store(src)
	f:load(co)
	f:structget(coro, 'caller')
	f:call(switchto)
	f:load(co)
	f:refnull(coro)
	f:structset(coro, 'caller')
	f:loadg(oluastack)
	f:i32(corostate.live)
	f:structset(coro, 'state')
	f:load(ok)
	alloc.lbool(f)
	f:call(tmppush)
	f:load(src)
	f:load(i)
	f:load(n)
	f:call(pushfrom)
	getf(f, 'pc')
end)

-- Raise an error with value msg. Unwinds to the nearest pcall in this coro & makes it return false, msg.
-- With no pcall a coroutine dies & its resume returns false, msg. Returns the pc to run next
throw = func(V, i32, function(f, msg)
	local ty, base, off = f:locals(i32, 3)
	local arr = f:locals(R.i32s)
	-- Find what catches it without popping anything. When that's an xpcall, call its handler
	-- on top of everything, so it can look at the frames that raised
	f:loadg(nohandler)
	f:eqz()
	f:iff(function()
		f:loadg(gframes)
		f:structget(alloc.frames, 'arr')
		f:store(arr)
		f:loadg(gframes)
		f:structget(alloc.frames, 'len')
		f:i32(stack.df.sizeof)
		f:sub()
		f:store(off)
		f:block(function(done)
			f:loop(function(loop)
				f:load(off)
				f:i32(0)
				f:lts()
				f:brif(done)
				f:load(arr)
				f:load(off)
				f:arrayget(alloc.i32s)
				f:tee(ty)
				f:i32(calltypes.xprot)
				f:eq()
				f:iff(function()
					-- handler(msg) in an xh frame
					f:load(arr)
					f:load(off)
					f:i32(df.base - df.sizeof)
					f:add()
					f:arrayget(alloc.i32s)
					f:i32(1)
					f:add()
					f:call(sget)
					f:call(tmppush)
					f:load(msg)
					f:call(tmppush)
					f:i32(calltypes.xh)
					f:call(stacklen)
					f:i32(1)
					f:sub()
					f:i32(1)
					f:call(pushframe)
					f:call(setupframe)
					f:i32(0)
					f:ret()
				end)
				-- an error in the handler, or nothing more to look at: unwind
				f:load(ty)
				f:i32(calltypes.xh)
				f:eq()
				f:load(ty)
				f:i32(calltypes.prot)
				f:eq()
				f:bor()
				f:load(ty)
				f:i32(calltypes.init)
				f:eq()
				f:bor()
				f:brif(done)
				f:load(off)
				f:i32(df.sizeof)
				f:sub()
				f:store(off)
				f:br(loop)
			end)
		end)
	end)
	f:i32(0)
	f:storeg(nohandler)
	f:loop(function(loop)
		getf(f, 'type')
		f:tee(ty)
		f:i32(calltypes.prot)
		f:eq()
		f:load(ty)
		f:i32(calltypes.xprot)
		f:eq()
		f:bor()
		f:iff(function()
			-- pcall put true below the function, make it false & put msg where the function was
			getf(f, 'base')
			f:tee(base)
			f:i32(2)
			f:sub()
			lfalse(f)
			f:call(sset)
			f:load(base)
			f:i32(1)
			f:sub()
			f:call(setstacklen)
			f:call(fpop)
			f:loadg(tbcfn)
			f:refisnull()
			f:iff(function()
				f:load(msg)
				f:call(tmppush)
				getf(f, 'pc')
				f:ret()
			end)
			-- msg is tbcfn(msg, frames left), called on top of pcall's frame so __close sees pcall as its caller
			f:loadg(tbcfn)
			f:call(tmppush)
			f:load(msg)
			f:call(tmppush)
			f:loadg(gframes)
			f:structget(alloc.frames, 'len')
			f:i32(df.sizeof)
			f:divu()
			f:i64extendu()
			f:call(newi64)
			f:call(tmppush)
			f:i32(calltypes.norm)
			f:call(stacklen)
			f:i32(2)
			f:sub()
			f:i32(1)
			f:call(pushframe)
			f:call(setupframe)
			f:i32(0)
			f:ret()
		end)
		f:load(ty)
		f:i32(calltypes.init)
		f:eq()
		f:iff(function()
			f:loadg(oluastack)
			f:structget(coro, 'caller')
			f:refisnull()
			f:iff(function()
				-- nothing catches it: print it & stop
				f:load(msg)
				f:call(rt.echoobj)
				f:unreachable()
			end)
			f:load(msg)
			f:call(tmppush)
			f:i32(0)
			f:call(stacklen)
			f:i32(1)
			f:sub()
			f:i32(1)
			f:i32(corostate.dead)
			f:call(coroback)
			f:ret()
		end)
		-- an error got out of an xpcall handler, like C Lua that's an error in error handling
		f:load(ty)
		f:i32(calltypes.xh)
		f:eq()
		f:iff(function()
			f:loadg(GS['error in error handling'])
			f:store(msg)
		end)
		f:call(fpop)
		f:br(loop)
	end)
	f:unreachable()
end)

-- Return op: results are everything after the locals
local retframe = func(i32, function(f)
	local at, base, retb, ty, c, e, key, len = f:locals(i32, 8)
	local arr = f:locals(R.i32s)
	ftop(f, arr, at)
	frd(f, arr, at, 'base')
	f:tee(base)
	frd(f, arr, at, 'retb')
	f:add()
	f:store(retb)
	frd(f, arr, at, 'retc')
	f:store(key)
	frd(f, arr, at, 'type')
	f:store(ty)
	f:load(base)
	frd(f, arr, at, 'frame')
	f:add()
	f:store(e)
	f:call(stacklen)
	f:store(len)

	-- usual case, a norm frame keeping a fixed count: copy them, nil filled, pop & carry on in the caller
	f:load(ty)
	f:i32(calltypes.norm)
	f:eq()
	f:load(key)
	f:i32(RETALL)
	f:ne()
	f:band()
	f:iff(function()
		f:load(e)
		f:load(key)
		f:add()
		f:load(len)
		f:sub()
		f:tee(c)
		f:i32(0)
		f:gts()
		f:iff(function()
			f:load(c)
			f:call(extendtmp)
		end)
		f:load(retb)
		f:load(e)
		f:load(key)
		f:call(scopy)
		f:load(retb)
		f:load(key)
		f:add()
		f:call(setstacklen)
		f:loadg(gframes)
		f:load(at)
		f:structset(alloc.frames, 'len')
		f:load(arr)
		f:load(at)
		f:i32(df.pc - df.sizeof)
		f:add()
		f:arrayget(alloc.i32s)
		f:ret()
	end)

	-- xpcall's handler returned: unwind with its first result, without calling it again
	f:load(ty)
	f:i32(calltypes.xh)
	f:eq()
	f:iff(function()
		f:load(e)
		f:load(len)
		f:lts()
		f:iff(V, function()
			f:load(e)
			f:call(sget)
		end, function()
			f:refnull(M.heap.eq)
		end)
		f:load(base)
		f:i32(1)
		f:sub()
		f:call(setstacklen)
		f:call(fpop)
		f:i32(1)
		f:storeg(nohandler)
		f:call(throw)
		f:ret()
	end)

	f:block(function(copied)
		f:load(ty)
		f:i32(calltypes.init)
		f:eq()
		f:iff(function()
			f:loadg(oluastack)
			f:structget(coro, 'caller')
			f:refisnull()
			f:iff(function()
				-- main returned, results stay on the stack for the caller
				f:i32(-1)
				f:ret()
			end)
			-- a coroutine finished: its resume returns true & the results
			f:i32(1)
			f:load(e)
			f:load(len)
			f:load(e)
			f:sub()
			f:i32(corostate.dead)
			f:call(coroback)
			f:ret()
		end)

		-- first result made true/false, false if none
		f:load(ty)
		f:i32(calltypes.bool)
		f:eq()
		f:iff(function()
			f:load(retb)
			f:load(e)
			f:load(len)
			f:eq()
			f:iff(i32, function()
				f:i32(0)
			end, function()
				f:load(e)
				f:call(sget)
				f:call(_obj.truthy)
			end)
			alloc.lbool(f)
			f:call(sset)
			f:i32(1)
			f:store(c)
			f:br(copied)
		end)

		-- push frames keep every result, their retc is how many fixed values sit below the function
		f:load(key)
		f:i32(RETALL)
		f:eq()
		f:load(ty)
		f:i32(calltypes.push)
		f:eq()
		f:bor()
		f:iff(i32, function()
			f:load(len)
			f:load(e)
			f:sub()
		end, function()
			f:load(key)
		end)
		f:tee(c)
		f:iff(function()
			-- too few results: nil fill
			f:load(e)
			f:load(c)
			f:add()
			f:load(len)
			f:gts()
			f:iff(function()
				f:load(e)
				f:load(c)
				f:add()
				f:load(len)
				f:sub()
				f:call(extendtmp)
			end)
			f:load(retb)
			f:load(e)
			f:load(c)
			f:call(scopy)
		end)
	end)

	-- pop stack frame
	f:load(retb)
	f:load(c)
	f:add()
	f:call(setstacklen)
	f:call(fpop)

	-- call frame: results are now args of the next function in the chain,
	-- whose frame is on top with pc 0
	f:load(ty)
	f:i32(calltypes.call)
	f:eq()
	f:iff(function()
		f:call(setupframe)
	end)

	-- tail frame: the results are args of the tail call, which goes where the frame below's locals end
	f:load(ty)
	f:i32(calltypes.tail)
	f:eq()
	f:iff(function()
		getf(f, 'base')
		getf(f, 'frame')
		f:add()
		f:call(tailcall)
		f:ret()
	end)

	-- push frame: stack is table, key fixed values, then results from retb on.
	-- Append values & results as t[1..], then leave only the table
	f:load(ty)
	f:i32(calltypes.push)
	f:eq()
	f:iff(function()
		f:load(key)
		f:load(c)
		f:add()
		f:call(appendn)
	end)

	getf(f, 'pc')
end)

