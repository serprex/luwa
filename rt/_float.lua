-- Exact conversion between decimal & f64, for the lexer & tostring.
-- A fast guess in floating point, then checked & fixed one ulp (or one digit) at a time,
-- by comparing exactly with big integers
local M = require 'make'
local func = M.func

local alloc = require 'alloc'
local i32s, bytes, R = alloc.i32s, alloc.bytes, alloc.R

-- Big integers are arrays of BN u32 limbs, lowest first. Always the full length, no normalizing.
-- 1536 bits is enough for every compare below
local BN = 48

-- for i = from, to-1 (or down from from-1 to to when down is set)
local function fori(f, i, from, to, body, down)
	if down then
		f:i32(from - 1)
		f:store(i)
		f:loop(function(loop)
			body()
			f:load(i)
			f:i32(1)
			f:sub()
			f:tee(i)
			f:i32(to)
			f:ges()
			f:brif(loop)
		end)
	else
		f:i32(from)
		f:store(i)
		f:loop(function(loop)
			body()
			f:load(i)
			f:i32(1)
			f:add()
			f:tee(i)
			f:i32(to)
			f:lts()
			f:brif(loop)
		end)
	end
end

-- Big integer equal to x
local bnnew = func(i64, M.ref(i32s), function(f, x)
	local a = f:locals(R.i32s)
	f:i32(BN)
	f:arraynewdefault(i32s)
	f:tee(a)
	f:i32(0)
	f:load(x)
	f:i32wrap()
	f:arrayset(i32s)
	f:load(a)
	f:i32(1)
	f:load(x)
	f:i64(32)
	f:shru()
	f:i32wrap()
	f:arrayset(i32s)
	f:load(a)
	f:refasnonnull()
end)

-- a *= k, k fits in u32
local bnmulsmall = func(R.i32s, i64, void, function(f, a, k)
	local i = f:locals(i32)
	local t, carry = f:locals(i64, 2)
	fori(f, i, 0, BN, function()
		f:load(a)
		f:load(i)
		f:arrayget(i32s)
		f:i64extendu()
		f:load(k)
		f:mul()
		f:load(carry)
		f:add()
		f:store(t)
		f:load(a)
		f:load(i)
		f:load(t)
		f:i32wrap()
		f:arrayset(i32s)
		f:load(t)
		f:i64(32)
		f:shru()
		f:store(carry)
	end)
end)

-- a *= 5^e, e >= 0
local bnmul5 = func(R.i32s, i32, void, function(f, a, e)
	local k = f:locals(i64)
	-- 5^13 is the biggest power of 5 that fits in u32
	f:loop(function(loop)
		f:load(e)
		f:i32(13)
		f:ges()
		f:iff(function()
			f:load(a)
			f:i64(1220703125)
			f:call(bnmulsmall)
			f:load(e)
			f:i32(13)
			f:sub()
			f:store(e)
			f:br(loop)
		end)
	end)
	f:i64(1)
	f:store(k)
	f:loop(function(loop)
		f:load(e)
		f:iff(function()
			f:load(k)
			f:i64(5)
			f:mul()
			f:store(k)
			f:load(e)
			f:i32(1)
			f:sub()
			f:store(e)
			f:br(loop)
		end)
	end)
	f:load(a)
	f:load(k)
	f:call(bnmulsmall)
end)

-- a <<= s, s >= 0
local bnshl = func(R.i32s, i32, void, function(f, a, s)
	local i, q, j = f:locals(i32, 3)
	local r = f:locals(i64)
	f:load(s)
	f:i32(5)
	f:shru()
	f:store(q)
	f:load(s)
	f:i32(31)
	f:band()
	f:i64extendu()
	f:store(r)
	-- limb a[j] where j may be below 0, as u64
	local function limb()
		f:load(j)
		f:i32(0)
		f:ges()
		f:iff(i64, function()
			f:load(a)
			f:load(j)
			f:arrayget(i32s)
			f:i64extendu()
		end, function()
			f:i64(0)
		end)
	end
	-- top down, so limbs are read before they're written
	fori(f, i, BN, 0, function()
		f:load(a)
		f:load(i)
		-- ((a[i-q] << 32 | a[i-q-1]) << r) >> 32
		f:load(i)
		f:load(q)
		f:sub()
		f:store(j)
		limb()
		f:i64(32)
		f:shl()
		f:load(j)
		f:i32(1)
		f:sub()
		f:store(j)
		limb()
		f:bor()
		f:load(r)
		f:shl()
		f:i64(32)
		f:shru()
		f:i32wrap()
		f:arrayset(i32s)
	end, true)
end)

-- -1, 0 or 1 as a is less than, equal to or more than b
local bncmp = func(R.i32s, R.i32s, i32, function(f, a, b)
	local i, x, y = f:locals(i32, 3)
	fori(f, i, BN, 0, function()
		f:load(a)
		f:load(i)
		f:arrayget(i32s)
		f:tee(x)
		f:load(b)
		f:load(i)
		f:arrayget(i32s)
		f:tee(y)
		f:ne()
		f:iff(function()
			f:i32(1)
			f:i32(-1)
			f:load(x)
			f:load(y)
			f:gtu()
			f:select()
			f:ret()
		end)
	end, true)
	f:i32(0)
end)

-- Sign of a * 10^e10 - b * 2^e2, a & b unsigned
local cmpdec = func(i64, i32, i64, i32, i32, function(f, a, e10, b, e2)
	local A, B = f:locals(R.i32s, 2)
	local p2 = f:locals(i32)
	f:load(a)
	f:call(bnnew)
	f:store(A)
	f:load(b)
	f:call(bnnew)
	f:store(B)
	-- 10^e10 = 5^e10 * 2^e10, the 2s join e2
	f:load(e10)
	f:i32(0)
	f:ges()
	f:iff(function()
		f:load(A)
		f:load(e10)
		f:call(bnmul5)
	end, function()
		f:load(B)
		f:i32(0)
		f:load(e10)
		f:sub()
		f:call(bnmul5)
	end)
	f:load(e10)
	f:load(e2)
	f:sub()
	f:tee(p2)
	f:i32(0)
	f:ges()
	f:iff(function()
		f:load(A)
		f:load(p2)
		f:call(bnshl)
	end, function()
		f:load(B)
		f:i32(0)
		f:load(p2)
		f:sub()
		f:call(bnshl)
	end)
	f:load(A)
	f:load(B)
	f:call(bncmp)
end)

-- 10^k for k >= 0. Exact up to 22. Past that, steps of 1e22 each add a little rounding
local pow10 = func(i32, f64, function(f, k)
	local p = f:locals(f64)
	f:f64(1)
	f:store(p)
	f:loop(function(loop)
		f:load(k)
		f:i32(22)
		f:ges()
		f:iff(function()
			f:load(p)
			f:f64(1e22)
			f:mul()
			f:store(p)
			f:load(k)
			f:i32(22)
			f:sub()
			f:store(k)
			f:br(loop)
		end)
	end)
	f:loop(function(loop)
		f:load(k)
		f:i32(0)
		f:gts()
		f:iff(function()
			f:load(p)
			f:f64(10)
			f:mul()
			f:store(p)
			f:load(k)
			f:i32(1)
			f:sub()
			f:store(k)
			f:br(loop)
		end)
	end)
	f:load(p)
end)

-- About a * 10^k, k can be negative. a is positive & finite
local scale10 = func(f64, i32, f64, function(f, a, k)
	-- 10^k overflows past 308, so take 10^300 out first
	f:load(k)
	f:i32(300)
	f:gts()
	f:iff(function()
		f:load(a)
		f:f64(1e300)
		f:mul()
		f:store(a)
		f:load(k)
		f:i32(300)
		f:sub()
		f:store(k)
	end)
	f:load(k)
	f:i32(-300)
	f:lts()
	f:iff(function()
		f:load(a)
		f:f64(1e300)
		f:div()
		f:store(a)
		f:load(k)
		f:i32(300)
		f:add()
		f:store(k)
	end)
	f:load(k)
	f:i32(0)
	f:ges()
	f:iff(f64, function()
		f:load(a)
		f:load(k)
		f:call(pow10)
		f:mul()
	end, function()
		f:load(a)
		f:i32(0)
		f:load(k)
		f:sub()
		f:call(pow10)
		f:div()
	end)
end)

-- A positive finite float's bits as m * 2^e, m an integer
local function splitf64(f, x, m, e)
	local bits = f:locals(i64)
	f:load(x)
	f:i64reinterpret()
	f:tee(bits)
	f:i64(52)
	f:shru()
	f:i32wrap()
	f:tee(e)
	f:iff(function()
		-- normal: hidden bit
		f:load(bits)
		f:i64(0xfffffffffffff)
		f:band()
		f:i64(0x10000000000000)
		f:bor()
		f:store(m)
		f:load(e)
		f:i32(1075)
		f:sub()
		f:store(e)
	end, function()
		-- subnormal
		f:load(bits)
		f:store(m)
		f:i32(-1074)
		f:store(e)
	end)
end

-- The float nearest m * 10^e10 (ties to even). trunc says nonzero digits were dropped from m,
-- so the real value is a little more than m * 10^e10
local dectof64 = func(i64, i32, i32, f64, function(f, m, e10, trunc)
	local b = f:locals(f64)
	local bm, bits, hm = f:locals(i64, 3)
	local be, c, he = f:locals(i32, 3)
	f:load(m)
	f:eqz()
	f:iff(function()
		f:f64(0)
		f:ret()
	end)
	-- m >= 1, so this is past the max float
	f:load(e10)
	f:i32(310)
	f:gts()
	f:iff(function()
		f:f64(math.huge)
		f:ret()
	end)
	-- m < 2^64, so this is under half the min subnormal
	f:load(e10)
	f:i32(-400)
	f:lts()
	f:iff(function()
		f:f64(0)
		f:ret()
	end)
	-- m & 10^|e10| are exact as floats, so one multiply or divide rounds right
	f:load(trunc)
	f:eqz()
	f:load(m)
	f:i64(0x20000000000000)
	f:leu()
	f:band()
	f:load(e10)
	f:i32(-22)
	f:ges()
	f:band()
	f:load(e10)
	f:i32(22)
	f:les()
	f:band()
	f:iff(function()
		f:load(e10)
		f:i32(0)
		f:ges()
		f:iff(f64, function()
			f:load(m)
			f:f64convertu()
			f:load(e10)
			f:call(pow10)
			f:mul()
		end, function()
			f:load(m)
			f:f64convertu()
			f:i32(0)
			f:load(e10)
			f:sub()
			f:call(pow10)
			f:div()
		end)
		f:ret()
	end)

	f:load(m)
	f:f64convertu()
	f:load(e10)
	f:call(scale10)
	f:store(b)
	f:loop(function(loop)
		f:load(b)
		f:f64(math.huge)
		f:eq()
		f:iff(function()
			-- inf unless under the halfway point past the max float, (2^54-1) * 2^970.
			-- A tie goes to inf, max float's mantissa is odd
			f:load(m)
			f:load(e10)
			f:i64(0x3fffffffffffff)
			f:i32(970)
			f:call(cmpdec)
			f:i32(0)
			f:ges()
			f:iff(function()
				f:f64(math.huge)
				f:ret()
			end)
			f:f64(1.7976931348623157e308)
			f:store(b)
		end)
		f:load(b)
		f:i64reinterpret()
		f:store(bits)
		f:load(b)
		f:f64(0)
		f:gt()
		f:iff(function()
			splitf64(f, b, bm, be)
		end, function()
			f:i64(0)
			f:store(bm)
			f:i32(-1074)
			f:store(be)
		end)
		-- past the halfway point up, (2bm+1) * 2^(be-1): round up
		f:load(m)
		f:load(e10)
		f:load(bm)
		f:i64(1)
		f:shl()
		f:i64(1)
		f:bor()
		f:load(be)
		f:i32(1)
		f:sub()
		f:call(cmpdec)
		f:tee(c)
		f:i32(0)
		f:gts()
		f:load(c)
		f:eqz()
		f:load(trunc)
		f:load(bm)
		f:i32wrap()
		f:i32(1)
		f:band()
		f:bor()
		f:band()
		f:bor()
		f:iff(function()
			f:load(bits)
			f:i64(1)
			f:add()
			f:f64reinterpret()
			f:store(b)
			f:br(loop)
		end)
		f:load(bm)
		f:eqz()
		f:iff(function()
			f:load(b)
			f:ret()
		end)
		-- under the halfway point down: round down. The float below a power of 2 is half as far,
		-- so that halfway point is (4bm-1) * 2^(be-2), unless b is the smallest normal
		f:load(bm)
		f:i64(0x10000000000000)
		f:eq()
		f:load(be)
		f:i32(-1074)
		f:gts()
		f:band()
		f:iff(function()
			f:load(bm)
			f:i64(2)
			f:shl()
			f:i64(1)
			f:sub()
			f:store(hm)
			f:load(be)
			f:i32(2)
			f:sub()
			f:store(he)
		end, function()
			f:load(bm)
			f:i64(1)
			f:shl()
			f:i64(1)
			f:sub()
			f:store(hm)
			f:load(be)
			f:i32(1)
			f:sub()
			f:store(he)
		end)
		f:load(m)
		f:load(e10)
		f:load(hm)
		f:load(he)
		f:call(cmpdec)
		f:tee(c)
		f:i32(0)
		f:lts()
		f:load(c)
		f:eqz()
		f:load(trunc)
		f:eqz()
		f:band()
		f:load(bm)
		f:i32wrap()
		f:i32(1)
		f:band()
		f:band()
		f:bor()
		f:iff(function()
			f:load(bits)
			f:i64(1)
			f:sub()
			f:f64reinterpret()
			f:store(b)
			f:br(loop)
		end)
	end)
	f:load(b)
end)

-- x (positive, finite, not 0) rounded to p digits (ties to even): n with p digits, and e,
-- so x is about n * 10^(e-p+1)
local digits = func(f64, i32, { i64, i32 }, function(f, x, p)
	local n, lo, hi, xm = f:locals(i64, 4)
	local e, u, xe, c = f:locals(i32, 4)
	-- lo = 10^(p-1), hi = 10^p
	f:i64(1)
	f:store(lo)
	f:load(p)
	f:i32(1)
	f:sub()
	f:store(u)
	f:loop(function(loop)
		f:load(u)
		f:iff(function()
			f:load(lo)
			f:i64(10)
			f:mul()
			f:store(lo)
			f:load(u)
			f:i32(1)
			f:sub()
			f:store(u)
			f:br(loop)
		end)
	end)
	f:load(lo)
	f:i64(10)
	f:mul()
	f:store(hi)
	splitf64(f, x, xm, xe)

	-- guess e from the binary exponent: floor(e2 * log10(2))
	f:load(x)
	f:i64reinterpret()
	f:i64(52)
	f:shru()
	f:i32wrap()
	f:i32(1023)
	f:sub()
	f:i32(78913)
	f:mul()
	f:i32(18)
	f:shrs()
	f:store(e)
	f:block(function(done)
		f:loop(function(loop)
			-- n = x * 10^(p-1-e), rounded in floating point
			f:load(x)
			f:load(p)
			f:i32(1)
			f:sub()
			f:load(e)
			f:sub()
			f:call(scale10)
			f:nearest()
			f:i64truncs()
			f:tee(n)
			f:load(hi)
			f:ges()
			f:iff(function()
				f:load(e)
				f:i32(1)
				f:add()
				f:store(e)
				f:br(loop)
			end)
			f:load(n)
			f:load(lo)
			f:lts()
			f:iff(function()
				f:load(e)
				f:i32(1)
				f:sub()
				f:store(e)
				f:br(loop)
			end)
			-- fix n by exact compares. u is the exponent of n's last digit
			f:load(e)
			f:load(p)
			f:sub()
			f:i32(1)
			f:add()
			f:store(u)
			f:loop(function(fix)
				-- 2x past (2n+1) * 10^u: n is too small. A tie goes to even
				f:load(n)
				f:i64(1)
				f:shl()
				f:i64(1)
				f:add()
				f:load(u)
				f:load(xm)
				f:load(xe)
				f:i32(1)
				f:add()
				f:call(cmpdec)
				f:tee(c)
				f:i32(0)
				f:lts()
				f:load(c)
				f:eqz()
				f:load(n)
				f:i32wrap()
				f:i32(1)
				f:band()
				f:band()
				f:bor()
				f:iff(function()
					f:load(n)
					f:i64(1)
					f:add()
					f:store(n)
					f:br(fix)
				end)
				-- 2x under (2n-1) * 10^u: n is too big
				f:load(n)
				f:i64(1)
				f:shl()
				f:i64(1)
				f:sub()
				f:load(u)
				f:load(xm)
				f:load(xe)
				f:i32(1)
				f:add()
				f:call(cmpdec)
				f:tee(c)
				f:i32(0)
				f:gts()
				f:load(c)
				f:eqz()
				f:load(n)
				f:i32wrap()
				f:i32(1)
				f:band()
				f:band()
				f:bor()
				f:iff(function()
					f:load(n)
					f:i64(1)
					f:sub()
					f:store(n)
					f:br(fix)
				end)
			end)
			-- rounded up to p+1 digits: that's 10^(p-1) one place up
			f:load(n)
			f:load(hi)
			f:eq()
			f:iff(function()
				f:load(lo)
				f:store(n)
				f:load(e)
				f:i32(1)
				f:add()
				f:store(e)
				f:br(done)
			end)
			-- under p digits: x is a place lower than guessed
			f:load(n)
			f:load(lo)
			f:lts()
			f:iff(function()
				f:load(e)
				f:i32(1)
				f:sub()
				f:store(e)
				f:br(loop)
			end)
		end)
	end)
	f:load(n)
	f:load(e)
end)

-- A float as Lua 5.5 shows it: C's %.15g, or %.17g when 15 digits don't read back as the same float.
-- .0 is added when it would look like an integer
local flttostr = func(f64, M.ref(alloc.str), function(f, x)
	local buf, digs, outb = f:locals(R.bytes, 3)
	local pos, e, nd, i, p = f:locals(i32, 5)
	local a = f:locals(f64)
	local n = f:locals(i64)

	-- buf[pos] = c, pos += 1. c is a char, or a function that pushes a byte
	local function put(c)
		f:load(buf)
		f:load(pos)
		if type(c) == 'function' then
			c()
		else
			f:i32(c:byte())
		end
		f:arrayset(bytes)
		f:load(pos)
		f:i32(1)
		f:add()
		f:store(pos)
	end
	-- copy digs[from, to) to buf at pos. from & to are functions that push i32s
	local function putdigs(from, to)
		f:load(buf)
		f:load(pos)
		f:load(digs)
		from()
		to()
		from()
		f:sub()
		f:arraycopy(bytes, bytes)
		f:load(pos)
		to()
		from()
		f:sub()
		f:add()
		f:store(pos)
	end
	local function const(v)
		return function() f:i32(v) end
	end
	local function loadl(l)
		return function() f:load(l) end
	end
	-- digit d of e, as a char
	local function edigit(div)
		return function()
			f:load(e)
			if div > 1 then
				f:i32(div)
				f:divu()
			end
			f:i32(10)
			f:remu()
			f:i32(48)
			f:add()
		end
	end

	f:i32(32)
	f:arraynewdefault(bytes)
	f:store(buf)
	f:block(function(done)
		f:load(x)
		f:i64reinterpret()
		f:i64(0)
		f:lts()
		f:iff(function()
			put('-')
		end)
		f:load(x)
		f:abs()
		f:store(a)
		f:load(a)
		f:load(a)
		f:ne()
		f:iff(function()
			put('n')
			put('a')
			put('n')
			f:br(done)
		end)
		f:load(a)
		f:f64(math.huge)
		f:eq()
		f:iff(function()
			put('i')
			put('n')
			put('f')
			f:br(done)
		end)
		f:load(a)
		f:f64(0)
		f:eq()
		f:iff(function()
			put('0')
			put('.')
			put('0')
			f:br(done)
		end)

		f:i32(15)
		f:store(p)
		f:load(a)
		f:i32(15)
		f:call(digits)
		f:store(e)
		f:store(n)
		f:load(n)
		f:load(e)
		f:i32(14)
		f:sub()
		f:i32(0)
		f:call(dectof64)
		f:load(a)
		f:ne()
		f:iff(function()
			f:i32(17)
			f:store(p)
			f:load(a)
			f:i32(17)
			f:call(digits)
			f:store(e)
			f:store(n)
		end)

		-- the p digits of n
		f:i32(17)
		f:arraynewdefault(bytes)
		f:store(digs)
		f:load(p)
		f:store(i)
		f:loop(function(loop)
			f:load(i)
			f:i32(1)
			f:sub()
			f:store(i)
			f:load(digs)
			f:load(i)
			f:load(n)
			f:i64(10)
			f:remu()
			f:i32wrap()
			f:i32(48)
			f:add()
			f:arrayset(bytes)
			f:load(n)
			f:i64(10)
			f:divu()
			f:store(n)
			f:load(i)
			f:brif(loop)
		end)
		-- nd = digits left after dropping trailing zeros, at least 1
		f:load(p)
		f:store(nd)
		f:loop(function(loop)
			f:load(nd)
			f:i32(1)
			f:gts()
			f:iff(function()
				f:load(digs)
				f:load(nd)
				f:i32(1)
				f:sub()
				f:arrayget(bytes, false)
				f:i32(48)
				f:eq()
				f:iff(function()
					f:load(nd)
					f:i32(1)
					f:sub()
					f:store(nd)
					f:br(loop)
				end)
			end)
		end)

		-- %g picks exponent form when e < -4 or e >= precision
		f:load(e)
		f:i32(-4)
		f:lts()
		f:load(e)
		f:load(p)
		f:ges()
		f:bor()
		f:iff(function()
			put(function()
				f:load(digs)
				f:i32(0)
				f:arrayget(bytes, false)
			end)
			f:load(nd)
			f:i32(1)
			f:gts()
			f:iff(function()
				put('.')
				putdigs(const(1), loadl(nd))
			end)
			put('e')
			f:load(e)
			f:i32(0)
			f:lts()
			f:iff(function()
				put('-')
				f:i32(0)
				f:load(e)
				f:sub()
				f:store(e)
			end, function()
				put('+')
			end)
			-- at least 2 digits
			f:load(e)
			f:i32(100)
			f:ges()
			f:iff(function()
				put(edigit(100))
			end)
			put(edigit(10))
			put(edigit(1))
			f:br(done)
		end)
		f:load(e)
		f:i32(0)
		f:ges()
		f:iff(function()
			-- e+1 digits before the point
			local function intend()
				f:load(e)
				f:i32(1)
				f:add()
			end
			putdigs(const(0), intend)
			put('.')
			f:load(nd)
			intend()
			f:gts()
			f:iff(function()
				putdigs(intend, loadl(nd))
			end, function()
				put('0')
			end)
			f:br(done)
		end)
		-- -4 <= e < 0: 0.000ddd
		put('0')
		put('.')
		f:loop(function(loop)
			f:load(e)
			f:i32(-1)
			f:lts()
			f:iff(function()
				put('0')
				f:load(e)
				f:i32(1)
				f:add()
				f:store(e)
				f:br(loop)
			end)
		end)
		putdigs(const(0), loadl(nd))
	end)
	f:load(pos)
	f:arraynewdefault(bytes)
	f:tee(outb)
	f:i32(0)
	f:load(buf)
	f:i32(0)
	f:load(pos)
	f:arraycopy(bytes, bytes)
	f:load(outb)
	f:call(alloc.strfrombytes)
end)

return {
	dectof64 = dectof64,
	flttostr = flttostr,
}
