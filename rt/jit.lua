-- The JIT joins the pieces vm.jitpieces made into a module for a batch of hot functions.
-- mkrt puts each op's piece & its gaps in linear memory (image), & these funcs write the module after them.
-- rt.js calls jitbegin(n), jitbody(fn) for each of the n functions, then jitend, & reads the bytes from memory.
--
-- A JIT'd function is a loop around a br_table on pc, each op's code after its own block end:
-- loop, block B_N .. block B_0, block S_m .. block S_1, block T, br_table, end T, unreachable,
-- end S_1, stub 1 .. end S_m, stub m, end B_0, op 0, end B_1, op 1 .. end B_N.
-- So code falls through from op to op, op k jumps forward to op j with a br to B_j,
-- & jumps back by setting pc & going round the loop.
-- Values an op pushes can stay in locals (slots) for the next ops to pop, instead of going on the Lua stack.
-- d[k] is how many are in slots when op k starts, slot 0 being the lowest. Jump targets start with none,
-- so before a jump, or before an op that can't use slots, they're pushed onto the Lua stack (a flush).
-- The same happens in an op before it calls a metamethod or raises an error. When the br_table starts
-- op k with d[k] > 0, eg once a metamethod returned, its stub first pops those values back into slots
local M = require 'make'
local func = M.func

local alloc = require 'alloc'
local R, bytes, i32s, functy = alloc.R, alloc.bytes, alloc.i32s, alloc.functy

local mem = M.memory(1)
-- Where things are in memory, filled in by image. The funcs below read it when rt.wasm is compiled
local L = {}
-- where the next byte of the module goes
local gpos = M.global(i32, true)
-- where the code section's size goes, filled in by jitend
local gsec = M.global(i32, true)

local KIND = { arg = 0, pc = 1, nop = 2, push = 3, pop = 4, peek = 5, flush = 6, jmp = 7 }
-- Memory starts with 256 i32s, op number to where its record is (0 for no such op).
-- A record is these i32s, in bytes from its start, followed by its gaps, GAP bytes each
local LEN, SLOTS, NEED, TOP, FALL, FALLS, CODE, CODELEN, NGAPS, GAPS = 0, 4, 8, 12, 16, 20, 24, 28, 32, 36
local GKIND, GPOS, GA, GB, GINNER, GSP, GAP = 0, 4, 8, 12, 16, 20, 24

-- The memory's starting bytes, from what vm.jitpieces made (mkrt's jit table)
local function image(jit)
	local img = {}
	local function put(off, v)
		v = v & 0xffffffff
		for i = 0, 3 do
			img[off + i + 1] = v >> (8 * i) & 255
		end
	end
	local function blob(s)
		local off = #img
		for i = 1, #s do
			img[off + i] = s:byte(i)
		end
		return { off, #s }
	end
	for i = 1, 256 * 4 do
		img[i] = 0
	end
	local oplist = {}
	for op in pairs(jit.ops) do
		assert(op >= 0 and op < 256)
		oplist[#oplist+1] = op
	end
	table.sort(oplist)
	for _, op in ipairs(oplist) do
		local p = jit.ops[op]
		local rec = #img
		for i = 1, GAPS + GAP * #p.gaps do
			img[rec + i] = 0
		end
		put(op * 4, rec)
		local len = jit.oplen[op]
		put(rec + LEN, len == 'call' and -1 or len)
		put(rec + SLOTS, p.slots and 1 or 0)
		put(rec + NEED, p.need)
		put(rec + TOP, p.top)
		put(rec + FALL, p.fall or 0)
		put(rec + FALLS, p.fall and 1 or 0)
		put(rec + NGAPS, #p.gaps)
		for i, g in ipairs(p.gaps) do
			local at = rec + GAPS + GAP * (i - 1)
			put(at + GKIND, assert(KIND[g.kind], g.kind))
			put(at + GPOS, g.pos)
			if g.kind == 'arg' then
				put(at + GA, g[1])
			elseif g.kind == 'jmp' then
				put(at + GA, g[1] == 'arg' and 1 or 0)
				put(at + GB, g[2])
			end
			put(at + GINNER, g.inner or 0)
			put(at + GSP, g.sp or 0)
		end
		local code = blob(p.code)
		put(rec + CODE, code[1])
		put(rec + CODELEN, code[2])
	end
	for _, k in ipairs{ 'header', 'locals', 'prologue', 'backedge', 'realpush', 'realpop', 'realpeek' } do
		L[k] = blob(jit[k])
	end
	-- the copied rt funcs: their type indices, & their bodies each after its size
	local tys, codes = {}, {}
	for _, fu in ipairs(jit.funcs) do
		M.encode_varuint(tys, fu[1])
		M.encode_varuint(codes, #fu[2])
		for _, b in ipairs(fu[2]) do
			codes[#codes+1] = b
		end
	end
	L.ownty = blob(string.char(table.unpack(tys)))
	local parts = {}
	for i = 1, #codes, 4096 do
		parts[#parts+1] = string.char(table.unpack(codes, i, math.min(i + 4095, #codes)))
	end
	L.owncode = blob(table.concat(parts))
	L.nown = #jit.funcs
	L.nfuncs = jit.nfuncs
	L.fty = jit.fty
	L.pcl = jit.pclocal
	L.slot0 = jit.slot0
	L.nslot = jit.nslot
	L.out = (#img + 7) & ~7
	mem.sz = (#img >> 16) + 2
	return img
end

-- Make room for n more bytes
local room = func(i32, void, function(f, n)
	f:loadg(gpos)
	f:load(n)
	f:add()
	f:currentmemory()
	f:i32(16)
	f:shl()
	f:gtu()
	f:iff(function()
		f:load(n)
		f:i32(16)
		f:shru()
		f:i32(1)
		f:add()
		f:growmemory()
		f:drop()
	end)
end)
local byte = func(i32, void, function(f, b)
	f:i32(1)
	f:call(room)
	f:loadg(gpos)
	f:load(b)
	f:i32store8()
	f:loadg(gpos)
	f:i32(1)
	f:add()
	f:storeg(gpos)
end)
-- len bytes from off
local copy = func(i32, i32, void, function(f, off, len)
	f:load(len)
	f:call(room)
	f:loadg(gpos)
	f:load(off)
	f:load(len)
	f:memcopy()
	f:loadg(gpos)
	f:load(len)
	f:add()
	f:storeg(gpos)
end)
local function copyblob(f, b)
	f:i32(b[1])
	f:i32(b[2])
	f:call(copy)
end
local uleb = func(i32, void, function(f, x)
	local b = f:locals(i32)
	f:loop(function(again)
		f:load(x)
		f:i32(0x7f)
		f:band()
		f:store(b)
		f:load(x)
		f:i32(7)
		f:shru()
		f:tee(x)
		f:iff(function()
			f:load(b)
			f:i32(0x80)
			f:bor()
			f:call(byte)
			f:br(again)
		end)
		f:load(b)
		f:call(byte)
	end)
end)
local sleb = func(i32, void, function(f, x)
	local b = f:locals(i32)
	f:loop(function(again)
		f:load(x)
		f:i32(0x7f)
		f:band()
		f:store(b)
		f:load(x)
		f:i32(7)
		f:shrs()
		f:store(x)
		-- done when what's left is the sign of b: 0, or -1 when b's top bit (0x40) is set
		f:load(x)
		f:i32(0)
		f:load(b)
		f:i32(6)
		f:shru()
		f:sub()
		f:eq()
		f:iff(function()
			f:load(b)
			f:call(byte)
			f:ret()
		end)
		f:load(b)
		f:i32(0x80)
		f:bor()
		f:call(byte)
		f:br(again)
	end)
end)
-- Leave 5 bytes for a size not known yet, returns where they are
local pad = func(i32, function(f)
	f:i32(5)
	f:call(room)
	f:loadg(gpos)
	f:loadg(gpos)
	f:i32(5)
	f:add()
	f:storeg(gpos)
end)
-- Fill the 5 bytes pad left at at with how many bytes came after them, as an uleb with padding
local patch = func(i32, void, function(f, at)
	local v = f:locals(i32)
	f:loadg(gpos)
	f:load(at)
	f:sub()
	f:i32(5)
	f:sub()
	f:store(v)
	for i = 0, 4 do
		f:load(at)
		f:load(v)
		f:i32(7 * i)
		f:shru()
		f:i32(0x7f)
		f:band()
		if i < 4 then
			f:i32(0x80)
			f:bor()
		end
		f:i32store8(i)
	end
end)
-- 4 byte arg at i in the bytecode
local rd = func(R.bytes, i32, i32, function(f, bc, i)
	for k = 0, 3 do
		f:load(bc)
		f:load(i)
		f:i32(k)
		f:add()
		f:arrayget(bytes, false)
		if k > 0 then
			f:i32(8 * k)
			f:shl()
			f:bor()
		end
	end
end)
-- local.get / local.set (op) of slot i
local slot = func(i32, i32, void, function(f, i, op)
	f:load(op)
	f:call(byte)
	f:i32(L.slot0)
	f:load(i)
	f:add()
	f:call(uleb)
end)
-- push c slots onto the Lua stack
local flush = func(i32, void, function(f, c)
	local i = f:locals(i32)
	f:block(function(done)
		f:loop(function(again)
			f:load(i)
			f:load(c)
			f:ges()
			f:brif(done)
			f:load(i)
			f:i32(0x20)
			f:call(slot)
			copyblob(f, L.realpush)
			f:load(i)
			f:i32(1)
			f:add()
			f:store(i)
			f:br(again)
		end)
	end)
end)
-- Op index a jmp gap g of op k goes to, -1 if it's not an op start
local jmpto = func(R.bytes, i32, R.i32s, R.i32s, i32, i32, i32, function(f, bc, n, idx, starts, k, g)
	local t = f:locals(i32)
	f:load(starts)
	f:load(k)
	f:arrayget(i32s)
	f:i32(1)
	f:add()
	f:load(g)
	f:i32load(GB)
	f:add()
	f:store(t)
	f:load(g)
	f:i32load(GA)
	f:iff(function()
		f:load(bc)
		f:load(t)
		f:call(rd)
		f:store(t)
	end)
	f:load(t)
	f:load(n)
	f:ltu()
	f:iff(i32, function()
		f:load(idx)
		f:load(t)
		f:arrayget(i32s)
	end, function()
		f:i32(-1)
	end)
end)

-- One function's code, 0 when it has something the JIT can't handle (then nothing was written)
local body = func(R.functy, i32, function(f, fn)
	local bc = f:locals(R.bytes)
	local starts, idx, target, d, use, fa, stubs, stubof = f:locals(R.i32s, 8)
	local n, N, S, pc, k, i, j, rec, g, at, dk, cur, live, len, from = f:locals(i32, 15)
	local function get(arr, ix)
		f:load(arr)
		ix()
		f:arrayget(i32s)
	end
	local function set(arr, ix, v)
		f:load(arr)
		ix()
		v()
		f:arrayset(i32s)
	end
	local function lo(x)
		return function()
			f:load(x)
		end
	end
	local function int(x)
		return function()
			f:i32(x)
		end
	end
	local function fail()
		f:i32(0)
		f:ret()
	end
	-- the record of op k
	local function recof(kx)
		f:load(bc)
		get(starts, kx)
		f:arrayget(bytes, false)
		f:i32(2)
		f:shl()
		f:i32load()
	end
	local function field(x, off)
		f:load(x)
		f:i32load(off)
	end
	local function inc(x, by)
		f:load(x)
		f:i32(by or 1)
		f:add()
		f:store(x)
	end
	-- var from 0 while below lim
	local function each(var, lim, fn)
		f:i32(0)
		f:store(var)
		f:block(function(done)
			f:loop(function(again)
				f:load(var)
				lim()
				f:ges()
				f:brif(done)
				fn()
				inc(var)
				f:br(again)
			end)
		end)
	end
	local function gapof()
		f:load(rec)
		f:i32(GAPS)
		f:add()
		f:load(i)
		f:i32(GAP)
		f:mul()
		f:add()
		f:store(g)
	end
	local function emit(b)
		f:i32(b)
		f:call(byte)
	end

	f:load(fn)
	f:structget(functy, 'bc')
	f:tee(bc)
	f:arraylen()
	f:tee(n)
	f:eqz()
	f:iff(fail)
	for _, arr in ipairs{ starts, idx, target, d, use, fa, stubs, stubof } do
		f:load(n)
		f:arraynewdefault(i32s)
		f:store(arr)
	end
	f:load(idx)
	f:i32(0)
	f:i32(-1)
	f:load(n)
	f:arrayfill(i32s)
	-- op index of each pc an op starts at, else -1
	f:block(function(done)
		f:loop(function(again)
			f:load(pc)
			f:load(n)
			f:ges()
			f:brif(done)
			f:load(bc)
			f:load(pc)
			f:arrayget(bytes, false)
			f:i32(2)
			f:shl()
			f:i32load()
			f:tee(rec)
			f:eqz()
			f:iff(fail)
			set(idx, lo(pc), lo(N))
			set(starts, lo(N), lo(pc))
			inc(N)
			field(rec, LEN)
			f:tee(len)
			f:i32(0)
			f:lts()
			f:iff(function()
				-- a call op: 1 + 4 * (2 + count of calls), the count is 5 bytes in
				f:load(pc)
				f:i32(9)
				f:add()
				f:load(n)
				f:gtu()
				f:iff(fail)
				f:load(bc)
				f:load(pc)
				f:i32(5)
				f:add()
				f:call(rd)
				f:i32(2)
				f:add()
				f:i32(2)
				f:shl()
				f:i32(1)
				f:add()
				f:store(len)
			end)
			f:load(pc)
			f:load(len)
			f:add()
			f:tee(pc)
			f:load(n)
			f:gtu()
			f:iff(fail)
			f:br(again)
		end)
	end)
	-- jump targets
	set(target, int(0), int(1))
	each(k, lo(N), function()
		recof(lo(k))
		f:store(rec)
		each(i, function() field(rec, NGAPS) end, function()
			gapof()
			field(g, GKIND)
			f:i32(KIND.jmp)
			f:eq()
			f:iff(function()
				f:load(bc)
				f:load(n)
				f:load(idx)
				f:load(starts)
				f:load(k)
				f:load(g)
				f:call(jmpto)
				f:tee(j)
				f:i32(0)
				f:lts()
				f:iff(fail)
				set(target, lo(j), int(1))
			end)
		end)
	end)
	-- slots in use at the start of each op, whether it uses them, & how many to flush after it
	local function km1()
		f:load(k)
		f:i32(1)
		f:sub()
	end
	each(k, lo(N), function()
		recof(lo(k))
		f:store(rec)
		f:load(cur)
		f:i32(0)
		f:load(live)
		get(target, lo(k))
		f:eqz()
		f:band()
		f:select()
		f:store(dk)
		f:load(live)
		get(target, lo(k))
		f:band()
		f:load(cur)
		f:i32(0)
		f:gts()
		f:band()
		f:iff(function()
			set(fa, km1, lo(cur))
		end)
		field(rec, SLOTS)
		f:load(dk)
		field(rec, NEED)
		f:ges()
		f:band()
		f:load(dk)
		field(rec, TOP)
		f:add()
		f:i32(L.nslot)
		f:les()
		f:band()
		f:iff(function()
			set(use, lo(k), int(1))
		end, function()
			f:load(dk)
			f:i32(0)
			f:gts()
			f:iff(function()
				set(fa, km1, lo(dk))
			end)
			f:i32(0)
			f:store(dk)
		end)
		set(d, lo(k), lo(dk))
		field(rec, FALLS)
		f:store(live)
		f:load(dk)
		field(rec, FALL)
		f:add()
		f:i32(0)
		get(use, lo(k))
		f:select()
		f:store(cur)
	end)
	-- ops started from the br_table with values in slots get a stub
	each(k, lo(N), function()
		get(use, lo(k))
		get(d, lo(k))
		f:i32(0)
		f:gts()
		f:band()
		f:iff(function()
			set(stubs, lo(S), lo(k))
			inc(S)
			set(stubof, lo(k), lo(S))
		end)
	end)

	copyblob(f, L.locals)
	copyblob(f, L.prologue)
	emit(0x03)
	emit(0x40)
	each(i, function()
		f:load(N)
		f:load(S)
		f:add()
		f:i32(2)
		f:add()
	end, function()
		emit(0x02)
		emit(0x40)
	end)
	emit(0x20)
	f:i32(L.pcl)
	f:call(uleb)
	emit(0x0e)
	f:load(n)
	f:call(uleb)
	each(pc, lo(n), function()
		get(idx, lo(pc))
		f:tee(k)
		f:i32(0)
		f:lts()
		f:iff(i32, function()
			f:i32(0)
		end, function()
			get(stubof, lo(k))
			f:tee(j)
			f:load(S)
			f:i32(1)
			f:add()
			f:load(k)
			f:add()
			f:load(j)
			f:select()
		end)
		f:call(uleb)
	end)
	f:i32(0)
	f:call(uleb)
	emit(0x0b)
	emit(0x00)
	-- stubs: pop the values back into slots, then go to the op
	each(i, lo(S), function()
		get(stubs, lo(i))
		f:store(k)
		emit(0x0b)
		get(d, lo(k))
		f:store(j)
		f:block(function(done)
			f:loop(function(again)
				f:load(j)
				f:i32(1)
				f:sub()
				f:tee(j)
				f:i32(0)
				f:lts()
				f:brif(done)
				copyblob(f, L.realpop)
				f:load(j)
				f:i32(0x21)
				f:call(slot)
				f:br(again)
			end)
		end)
		emit(0x0c)
		f:load(S)
		f:load(i)
		f:sub()
		f:i32(1)
		f:sub()
		f:load(k)
		f:add()
		f:call(uleb)
	end)
	-- ops, live is now whether op k uses slots
	local function gapi(off)
		f:load(g)
		f:i32load(off)
	end
	local function case(kind, fn)
		gapi(GKIND)
		f:i32(KIND[kind])
		f:eq()
		f:iff(fn)
	end
	each(k, lo(N), function()
		get(starts, lo(k))
		f:store(at)
		recof(lo(k))
		f:store(rec)
		get(d, lo(k))
		f:store(dk)
		get(use, lo(k))
		f:store(live)
		emit(0x0b)
		-- pc is the pc after the opcode inside an op
		emit(0x41)
		f:load(at)
		f:i32(1)
		f:add()
		f:call(sleb)
		emit(0x21)
		f:i32(L.pcl)
		f:call(uleb)
		f:i32(0)
		f:store(from)
		each(i, function() field(rec, NGAPS) end, function()
			gapof()
			-- the code up to the gap
			field(rec, CODE)
			f:load(from)
			f:add()
			gapi(GPOS)
			f:load(from)
			f:sub()
			f:call(copy)
			gapi(GPOS)
			f:store(from)
			case('arg', function()
				emit(0x41)
				f:load(bc)
				f:load(at)
				f:i32(1)
				f:add()
				gapi(GA)
				f:add()
				f:call(rd)
				f:call(sleb)
			end)
			case('pc', function()
				emit(0x41)
				f:load(at)
				f:i32(1)
				f:add()
				f:call(sleb)
			end)
			case('nop', function()
				emit(0x0c)
				gapi(GINNER)
				f:call(uleb)
			end)
			case('push', function()
				f:load(live)
				f:iff(function()
					f:load(dk)
					gapi(GSP)
					f:add()
					f:i32(0x21)
					f:call(slot)
				end, function()
					copyblob(f, L.realpush)
				end)
			end)
			for _, kind in ipairs{ 'pop', 'peek' } do
				case(kind, function()
					f:load(live)
					f:iff(function()
						f:load(dk)
						gapi(GSP)
						f:add()
						f:i32(1)
						f:sub()
						f:i32(0x20)
						f:call(slot)
					end, function()
						copyblob(f, kind == 'pop' and L.realpop or L.realpeek)
					end)
				end)
			end
			local function flushgap()
				f:load(live)
				f:iff(function()
					f:load(dk)
					gapi(GSP)
					f:add()
					f:call(flush)
				end)
			end
			case('flush', flushgap)
			case('jmp', function()
				f:load(bc)
				f:load(n)
				f:load(idx)
				f:load(starts)
				f:load(k)
				f:load(g)
				f:call(jmpto)
				f:store(j)
				flushgap()
				f:load(j)
				f:load(k)
				f:gts()
				f:iff(function()
					emit(0x0c)
					gapi(GINNER)
					f:load(j)
					f:add()
					f:load(k)
					f:sub()
					f:i32(1)
					f:sub()
					f:call(uleb)
				end, function()
					emit(0x41)
					get(starts, lo(j))
					f:call(sleb)
					emit(0x21)
					f:i32(L.pcl)
					f:call(uleb)
					copyblob(f, L.backedge)
					emit(0x0c)
					gapi(GINNER)
					f:load(N)
					f:add()
					f:load(k)
					f:sub()
					f:call(uleb)
				end)
			end)
		end)
		field(rec, CODE)
		f:load(from)
		f:add()
		field(rec, CODELEN)
		f:load(from)
		f:sub()
		f:call(copy)
		get(fa, lo(k))
		f:call(flush)
	end)
	for _, b in ipairs{ 0x0b, 0x00, 0x0b, 0x00, 0x0b } do
		emit(b)
	end
	f:i32(1)
end)

-- "f" .. i, as a name with its length first
local fname = func(i32, void, function(f, i)
	local p, c = f:locals(i32, 2)
	f:i32(1)
	f:store(p)
	f:i32(1)
	f:store(c)
	f:block(function(done)
		f:loop(function(again)
			f:load(p)
			f:i32(10)
			f:mul()
			f:load(i)
			f:gtu()
			f:brif(done)
			f:load(p)
			f:i32(10)
			f:mul()
			f:store(p)
			f:load(c)
			f:i32(1)
			f:add()
			f:store(c)
			f:br(again)
		end)
	end)
	f:load(c)
	f:i32(1)
	f:add()
	f:call(byte)
	f:i32(string.byte('f'))
	f:call(byte)
	f:loop(function(again)
		f:load(i)
		f:load(p)
		f:divu()
		f:i32(10)
		f:remu()
		f:i32(string.byte('0'))
		f:add()
		f:call(byte)
		f:load(p)
		f:i32(10)
		f:divu()
		f:tee(p)
		f:brif(again)
	end)
end)

-- Start a module for n functions, returns where it starts in memory
local jitbegin = func(i32, i32, function(f, n)
	local at, i = f:locals(i32, 2)
	f:i32(L.out)
	f:storeg(gpos)
	copyblob(f, L.header)
	-- func section: the copied rt funcs, then the n functions
	f:i32(3)
	f:call(byte)
	f:call(pad)
	f:store(at)
	f:i32(L.nown)
	f:load(n)
	f:add()
	f:call(uleb)
	copyblob(f, L.ownty)
	f:block(function(done)
		f:loop(function(again)
			f:load(i)
			f:load(n)
			f:ges()
			f:brif(done)
			f:i32(L.fty)
			f:call(uleb)
			f:load(i)
			f:i32(1)
			f:add()
			f:store(i)
			f:br(again)
		end)
	end)
	f:load(at)
	f:call(patch)
	-- exports f0, f1..
	f:i32(7)
	f:call(byte)
	f:call(pad)
	f:store(at)
	f:load(n)
	f:call(uleb)
	f:i32(0)
	f:store(i)
	f:block(function(done)
		f:loop(function(again)
			f:load(i)
			f:load(n)
			f:ges()
			f:brif(done)
			f:load(i)
			f:call(fname)
			f:i32(0)
			f:call(byte)
			f:i32(L.nfuncs)
			f:load(i)
			f:add()
			f:call(uleb)
			f:load(i)
			f:i32(1)
			f:add()
			f:store(i)
			f:br(again)
		end)
	end)
	f:load(at)
	f:call(patch)
	-- code section, its size is filled in by jitend
	f:i32(10)
	f:call(byte)
	f:call(pad)
	f:storeg(gsec)
	f:i32(L.nown)
	f:load(n)
	f:add()
	f:call(uleb)
	copyblob(f, L.owncode)
	f:i32(L.out)
end)
-- Add fn's code. When the JIT can't handle fn, its code is just unreachable & this returns 0
local jitbody = func(R.functy, i32, function(f, fn)
	local at, ok = f:locals(i32, 2)
	f:call(pad)
	f:store(at)
	f:load(fn)
	f:call(body)
	f:tee(ok)
	f:eqz()
	f:iff(function()
		f:load(at)
		f:i32(5)
		f:add()
		f:storeg(gpos)
		-- no locals, unreachable, end
		for _, b in ipairs{ 0x00, 0x00, 0x0b } do
			f:i32(b)
			f:call(byte)
		end
	end)
	f:load(at)
	f:call(patch)
	f:load(ok)
end)
-- Finish the module, returns its size
local jitend = func(i32, function(f)
	f:loadg(gsec)
	f:call(patch)
	f:loadg(gpos)
	f:i32(L.out)
	f:sub()
end)

return {
	mem = mem,
	image = image,
	jitbegin = jitbegin,
	jitbody = jitbody,
	jitend = jitend,
}
