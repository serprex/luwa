-- String builtins in wasm for the prelude's string & table libraries.
-- The prelude checks args & raises errors, these only do the byte loops.
-- Positions in & out are 1 based, like Lua
local M = require 'make'
local func = M.func

local alloc = require 'alloc'
local types, R, str, bytes, newi64 = alloc.types, alloc.R, alloc.str, alloc.bytes, alloc.newi64

local stack = require 'stack'
local tmppush = stack.tmppush

local _table = require '_table'
local _string = require '_string'
local _float = require '_float'
local frame = require 'frame'

local function loadparam(f, i)
	f:i32(i)
	f:call(frame.param)
end
-- bytes of param i, which must be a string
local function strparam(f, i)
	loadparam(f, i)
	f:refcast(R.str)
	f:structget(str, 'bytes')
end
-- param i as an i64, it must be an integer
local function i64param(f, i)
	loadparam(f, i)
	alloc.intvalst(f)
end
local function i32param(f, i)
	i64param(f, i)
	f:i32wrap()
end
-- push the i32 on the stack as a Lua integer
local function pushint(f)
	f:i64extends()
	f:call(newi64)
	f:call(tmppush)
end
-- byte idx (0 based) of b
local function byteat(f, b, idx)
	f:load(b)
	f:load(idx)
	f:arrayget(bytes, false)
end

-- Character class table. Bytes 0-255: class number of a class letter (lower case), 0 if it isn't one.
-- Then 256 bytes per class: 1 when that byte is in the class
local classtests = {}
do
	local function isalpha(c) return (c >= 65 and c <= 90) or (c >= 97 and c <= 122) end
	local function isdigit(c) return c >= 48 and c <= 57 end
	local function ispunct(c) return (c >= 33 and c <= 47) or (c >= 58 and c <= 64) or (c >= 91 and c <= 96) or (c >= 123 and c <= 126) end
	classtests = {
		{ 97, isalpha }, -- a
		{ 99, function(c) return c < 32 or c == 127 end }, -- c
		{ 100, isdigit }, -- d
		{ 103, function(c) return c > 32 and c < 127 end }, -- g
		{ 108, function(c) return c >= 97 and c <= 122 end }, -- l
		{ 112, ispunct }, -- p
		{ 115, function(c) return c == 32 or (c >= 9 and c <= 13) end }, -- s
		{ 117, function(c) return c >= 65 and c <= 90 end }, -- u
		{ 119, function(c) return isalpha(c) or isdigit(c) end }, -- w
		{ 120, function(c) return isdigit(c) or (c >= 65 and c <= 70) or (c >= 97 and c <= 102) end }, -- x
		{ 122, function(c) return c == 0 end }, -- z, old name for byte 0
	}
end
local ctab = {}
for i = 1, 256 * (#classtests + 1) do
	ctab[i] = 0
end
for k, ct in ipairs(classtests) do
	ctab[ct[1] + 1] = k
	for c = 0, 255 do
		if ct[2](c) then
			ctab[k * 256 + c + 1] = 1
		end
	end
end
local classdata = M.passivedata(ctab)
local classtab = M.global(R.bytes, true)

-- The matcher, a port of lstrlib.c's do_match. One match runs at a time, its state is in these globals.
-- Positions are 0 based in here. A match gives the end of the match, or -1 for no match.
-- An error sets merr & gives -1, so callers that would try something else check merr first
local msrc = M.global(R.bytes, true)
local mpat = M.global(R.bytes, true)
local mslen = M.global(i32, true)
local mplen = M.global(i32, true)
local mlevel = M.global(i32, true)
local mdepth = M.global(i32, true)
local merr = M.global(i32, true)
-- 2 i32s per capture: its start, then its length or CAP_UNF / CAP_POS
local mcaps = M.global(R.i32s, true)
local MAXCAPTURES, MAXCCALLS = 32, 200
local CAP_UNF, CAP_POS = -1, -2
-- merr codes, the prelude has the messages. Bad capture index d is ERR_CAPIDX + d
local ERR_ENDPCT, ERR_BRACKET, ERR_BALANCE, ERR_FRONTIER, ERR_CAPTURE, ERR_MANYCAPS, ERR_COMPLEX, ERR_CAPIDX =
	1, 2, 3, 4, 5, 6, 7, 16

-- Made once by genesis
local initclasses = func(function(f)
	f:i32(0)
	f:i32(#ctab)
	f:arraynewdata(bytes, classdata)
	f:storeg(classtab)
	f:i32(MAXCAPTURES * 2)
	f:arraynewdefault(alloc.i32s)
	f:storeg(mcaps)
end)

-- Does byte c match %cl
local clmatch = func(i32, i32, i32, function(f, c, cl)
	local k = f:locals(i32)
	f:loadg(classtab)
	f:load(cl)
	f:i32(32)
	f:bor()
	f:arrayget(bytes, false)
	f:tee(k)
	f:eqz()
	f:iff(function()
		f:load(c)
		f:load(cl)
		f:eq()
		f:ret()
	end)
	f:loadg(classtab)
	f:load(k)
	f:i32(8)
	f:shl()
	f:load(c)
	f:add()
	f:arrayget(bytes, false)
	-- upper case letter: the complement
	f:load(cl)
	f:i32(65)
	f:sub()
	f:i32(26)
	f:ltu()
	f:xor()
end)

-- Does byte c match the set p[pi..ec], pi at '[' & ec at ']', 0 based
local bracket = func(i32, R.bytes, i32, i32, i32, function(f, c, p, pi, ec)
	local sig, pc = f:locals(i32, 2)
	f:i32(1)
	f:store(sig)
	f:load(pi)
	f:i32(1)
	f:add()
	f:store(pi)
	byteat(f, p, pi)
	f:i32(94) -- ^
	f:eq()
	f:iff(function()
		f:i32(0)
		f:store(sig)
		f:load(pi)
		f:i32(1)
		f:add()
		f:store(pi)
	end)
	f:block(function(done)
		f:loop(function(loop)
			f:load(pi)
			f:load(ec)
			f:ges()
			f:brif(done)
			byteat(f, p, pi)
			f:tee(pc)
			f:i32(37) -- %
			f:eq()
			f:iff(function()
				f:load(pi)
				f:i32(1)
				f:add()
				f:store(pi)
				f:load(c)
				byteat(f, p, pi)
				f:call(clmatch)
				f:iff(function()
					f:load(sig)
					f:ret()
				end)
			end, function()
				-- a-z: p[pi+1] is in bounds since pi < ec
				f:load(p)
				f:load(pi)
				f:i32(1)
				f:add()
				f:arrayget(bytes, false)
				f:i32(45) -- -
				f:eq()
				f:load(pi)
				f:i32(2)
				f:add()
				f:load(ec)
				f:lts()
				f:band()
				f:iff(function()
					f:load(pc)
					f:load(c)
					f:leu()
					f:load(c)
					f:load(p)
					f:load(pi)
					f:i32(2)
					f:add()
					f:arrayget(bytes, false)
					f:leu()
					f:band()
					f:iff(function()
						f:load(sig)
						f:ret()
					end)
					f:load(pi)
					f:i32(2)
					f:add()
					f:store(pi)
				end, function()
					f:load(pc)
					f:load(c)
					f:eq()
					f:iff(function()
						f:load(sig)
						f:ret()
					end)
				end)
			end)
			f:load(pi)
			f:i32(1)
			f:add()
			f:store(pi)
			f:br(loop)
		end)
	end)
	f:load(sig)
	f:eqz()
end)

-- Does byte c match the single class p[pi..ep), 0 based
local single1 = func(i32, R.bytes, i32, i32, i32, function(f, c, p, pi, ep)
	local pc = f:locals(i32)
	byteat(f, p, pi)
	f:tee(pc)
	f:i32(46) -- .
	f:eq()
	f:iff(function()
		f:i32(1)
		f:ret()
	end)
	f:load(pc)
	f:i32(37) -- %
	f:eq()
	f:iff(function()
		f:load(c)
		f:load(p)
		f:load(pi)
		f:i32(1)
		f:add()
		f:arrayget(bytes, false)
		f:call(clmatch)
		f:ret()
	end)
	f:load(pc)
	f:i32(91) -- [
	f:eq()
	f:iff(function()
		f:load(c)
		f:load(p)
		f:load(pi)
		f:load(ep)
		f:i32(1)
		f:sub()
		f:call(bracket)
		f:ret()
	end)
	f:load(pc)
	f:load(c)
	f:eq()
end)

-- _luwa.strmap(s, op): s with each byte upper cased (op 0), lower cased (1), or s reversed (2)
local std_strmap = func(function(f)
	local b, nb = f:locals(R.bytes, 2)
	local n, k, c, op, lo, d = f:locals(i32, 6)
	strparam(f, 0)
	f:tee(b)
	f:arraylen()
	f:tee(n)
	f:arraynewdefault(bytes)
	f:store(nb)
	i32param(f, 1)
	f:tee(op)
	f:i32(2)
	f:eq()
	f:iff(function()
		f:block(function(done)
			f:loop(function(loop)
				f:load(k)
				f:load(n)
				f:geu()
				f:brif(done)
				f:load(nb)
				f:load(k)
				f:load(b)
				f:load(n)
				f:i32(1)
				f:sub()
				f:load(k)
				f:sub()
				f:arrayget(bytes, false)
				f:arrayset(bytes)
				f:load(k)
				f:i32(1)
				f:add()
				f:store(k)
				f:br(loop)
			end)
		end)
	end, function()
		-- upper: a-z goes down 32, lower: A-Z goes up 32
		f:i32(65)
		f:i32(97)
		f:load(op)
		f:select()
		f:store(lo)
		f:i32(32)
		f:i32(-32)
		f:load(op)
		f:select()
		f:store(d)
		f:block(function(done)
			f:loop(function(loop)
				f:load(k)
				f:load(n)
				f:geu()
				f:brif(done)
				f:load(nb)
				f:load(k)
				byteat(f, b, k)
				f:tee(c)
				f:load(d)
				f:i32(0)
				f:load(c)
				f:load(lo)
				f:sub()
				f:i32(26)
				f:ltu()
				f:select()
				f:add()
				f:arrayset(bytes)
				f:load(k)
				f:i32(1)
				f:add()
				f:store(k)
				f:br(loop)
			end)
		end)
	end)
	f:load(nb)
	f:call(alloc.strfrombytes)
	f:call(tmppush)
end)

-- _luwa.strrep(s, n, sep): n copies of s with sep between. n >= 1 & the size fits, the prelude checks.
-- The result repeats s..sep, so after the first copy it doubles by copying from itself
local std_strrep = func(function(f)
	local b, sb, nb = f:locals(R.bytes, 3)
	local len, slen, cnt, total, filled, c = f:locals(i32, 6)
	strparam(f, 0)
	f:tee(b)
	f:arraylen()
	f:store(len)
	strparam(f, 2)
	f:tee(sb)
	f:arraylen()
	f:store(slen)
	i32param(f, 1)
	f:tee(cnt)
	f:load(len)
	f:load(slen)
	f:add()
	f:mul()
	f:load(slen)
	f:sub()
	f:tee(total)
	f:arraynewdefault(bytes)
	f:tee(nb)
	f:i32(0)
	f:load(b)
	f:i32(0)
	f:load(len)
	f:arraycopy(bytes, bytes)
	f:load(cnt)
	f:i32(1)
	f:gts()
	f:iff(function()
		f:load(nb)
		f:load(len)
		f:load(sb)
		f:i32(0)
		f:load(slen)
		f:arraycopy(bytes, bytes)
		f:load(len)
		f:load(slen)
		f:add()
		f:store(filled)
		f:block(function(done)
			f:loop(function(loop)
				f:load(filled)
				f:load(total)
				f:geu()
				f:brif(done)
				-- c = min(filled, total - filled)
				f:load(filled)
				f:load(total)
				f:load(filled)
				f:sub()
				f:tee(c)
				f:load(filled)
				f:load(c)
				f:ltu()
				f:select()
				f:store(c)
				f:load(nb)
				f:load(filled)
				f:load(nb)
				f:i32(0)
				f:load(c)
				f:arraycopy(bytes, bytes)
				f:load(filled)
				f:load(c)
				f:add()
				f:store(filled)
				f:br(loop)
			end)
		end)
	end)
	f:load(nb)
	f:call(alloc.strfrombytes)
	f:call(tmppush)
end)

-- Largest byte array V8 makes, same as MAXSTR in the prelude
local MAXSTR = 0x3fffffe0

-- Bytes of t[key] for concat: a string's, a number's as a string, null for anything else
local itembytes = func(R.tbl, i64, R.bytes, function(f, t, key)
	local v = f:locals(V)
	local ty = f:locals(i32)
	f:load(t)
	f:load(key)
	f:call(_table.tblgeti)
	f:tee(v)
	f:call(alloc.typeof)
	f:tee(ty)
	f:i32(types.str)
	f:eq()
	f:iff(function()
		f:load(v)
		f:refcast(R.str)
		f:structget(str, 'bytes')
		f:ret()
	end)
	f:load(ty)
	f:i32(types.int)
	f:eq()
	f:load(ty)
	f:i32(types.float)
	f:eq()
	f:bor()
	f:iff(function()
		f:load(v)
		f:call(_string.numtostr)
		f:structget(str, 'bytes')
		f:ret()
	end)
	f:refnull(bytes)
end)

-- _luwa.concat(t, sep, i, j): t[i]..sep..t[i+1]..sep..t[j], read raw. i <= j, the prelude checks.
-- Gives nil & the index of the first value that isn't a string or number, or just nil when it's too big.
-- Adds up the size first so it allocates once. Numbers turn into strings in both passes
local std_concat = func(function(f)
	local t = f:locals(R.tbl)
	local sb, nb, vb = f:locals(R.bytes, 3)
	local i, n, k = f:locals(i64, 3)
	local total, pos, slen = f:locals(i32, 3)
	-- past MAXSTR: just nil, the prelude raises "not enough memory".
	-- Each add is at most MAXSTR, so total can't wrap before this check
	local function toobig()
		f:load(total)
		f:i32(MAXSTR)
		f:gtu()
		f:iff(function()
			alloc.lnil(f)
			f:call(tmppush)
			f:ret()
		end)
	end
	loadparam(f, 0)
	f:refcast(R.tbl)
	f:store(t)
	strparam(f, 1)
	f:tee(sb)
	f:arraylen()
	f:store(slen)
	i64param(f, 2)
	f:store(i)
	-- n = j - i, the last k
	i64param(f, 3)
	f:load(i)
	f:sub()
	f:store(n)

	f:block(function(done)
		f:loop(function(loop)
			f:load(t)
			f:load(i)
			f:load(k)
			f:add()
			f:call(itembytes)
			f:tee(vb)
			f:refisnull()
			f:iff(function()
				alloc.lnil(f)
				f:call(tmppush)
				f:load(i)
				f:load(k)
				f:add()
				f:call(newi64)
				f:call(tmppush)
				f:ret()
			end)
			f:load(total)
			f:load(vb)
			f:arraylen()
			f:add()
			f:store(total)
			toobig()
			f:load(k)
			f:load(n)
			f:eq()
			f:brif(done)
			f:load(total)
			f:load(slen)
			f:add()
			f:store(total)
			toobig()
			f:load(k)
			f:i64(1)
			f:add()
			f:store(k)
			f:br(loop)
		end)
	end)

	f:load(total)
	f:arraynewdefault(bytes)
	f:store(nb)
	f:i64(0)
	f:store(k)
	f:block(function(done)
		f:loop(function(loop)
			f:load(t)
			f:load(i)
			f:load(k)
			f:add()
			f:call(itembytes)
			f:store(vb)
			f:load(nb)
			f:load(pos)
			f:load(vb)
			f:i32(0)
			f:load(vb)
			f:arraylen()
			f:arraycopy(bytes, bytes)
			f:load(pos)
			f:load(vb)
			f:arraylen()
			f:add()
			f:store(pos)
			f:load(k)
			f:load(n)
			f:eq()
			f:brif(done)
			f:load(nb)
			f:load(pos)
			f:load(sb)
			f:i32(0)
			f:load(slen)
			f:arraycopy(bytes, bytes)
			f:load(pos)
			f:load(slen)
			f:add()
			f:store(pos)
			f:load(k)
			f:i64(1)
			f:add()
			f:store(k)
			f:br(loop)
		end)
	end)
	f:load(nb)
	f:call(alloc.strfrombytes)
	f:call(tmppush)
end)

local function inc(f, l, n)
	f:load(l)
	f:i32(n or 1)
	f:add()
	f:store(l)
end
-- pattern byte at local idx (+ off)
local function patat(f, idx, off)
	f:loadg(mpat)
	f:load(idx)
	if off then
		f:i32(off)
		f:add()
	end
	f:arrayget(bytes, false)
end
local function srcat(f, idx)
	f:loadg(msrc)
	f:load(idx)
	f:arrayget(bytes, false)
end
local function raise(f, code)
	f:i32(code)
	f:storeg(merr)
	f:i32(-1)
	f:ret()
end
-- if the i32 on the stack is set, return -1
local function failif(f)
	f:iff(function()
		f:i32(-1)
		f:ret()
	end)
end
-- capture l's start (field 0) or length (field 1)
local function capget(f, l, field)
	f:loadg(mcaps)
	f:load(l)
	f:i32(1)
	f:shl()
	if field == 1 then
		f:i32(1)
		f:add()
	end
	f:arrayget(alloc.i32s)
end
local function capset(f, l, field, val)
	f:loadg(mcaps)
	f:load(l)
	f:i32(1)
	f:shl()
	if field == 1 then
		f:i32(1)
		f:add()
	end
	val()
	f:arrayset(alloc.i32s)
end

-- The index just past the single class at p, or an error
local mclassend = func(i32, i32, function(f, p)
	local c = f:locals(i32)
	patat(f, p)
	f:store(c)
	inc(f, p)
	f:load(c)
	f:i32(37) -- %
	f:eq()
	f:iff(function()
		f:load(p)
		f:loadg(mplen)
		f:geu()
		f:iff(function()
			raise(f, ERR_ENDPCT)
		end)
		f:load(p)
		f:i32(1)
		f:add()
		f:ret()
	end)
	f:load(c)
	f:i32(91) -- [
	f:eq()
	f:iff(function()
		f:load(p)
		f:loadg(mplen)
		f:ltu()
		f:iff(function()
			patat(f, p)
			f:i32(94) -- ^
			f:eq()
			f:load(p)
			f:add()
			f:store(p)
		end)
		-- like lstrlib: the first byte is in the set even when it's ']'
		f:loop(function(loop)
			f:load(p)
			f:loadg(mplen)
			f:geu()
			f:iff(function()
				raise(f, ERR_BRACKET)
			end)
			patat(f, p)
			f:store(c)
			inc(f, p)
			-- a % skips the byte after it
			f:load(c)
			f:i32(37)
			f:eq()
			f:load(p)
			f:loadg(mplen)
			f:ltu()
			f:band()
			f:iff(function()
				inc(f, p)
			end)
			f:load(p)
			f:loadg(mplen)
			f:ltu()
			f:iff(function()
				patat(f, p)
				f:i32(93) -- ]
				f:eq()
				f:iff(function()
					f:load(p)
					f:i32(1)
					f:add()
					f:ret()
				end)
			end)
			f:br(loop)
		end)
	end)
	f:load(p)
end)

-- Does byte s of the source match the class p..ep
local msingle = func(i32, i32, i32, i32, function(f, s, p, ep)
	f:load(s)
	f:loadg(mslen)
	f:ltu()
	f:iff(i32, function()
		srcat(f, s)
		f:loadg(mpat)
		f:load(p)
		f:load(ep)
		f:call(single1)
	end, function()
		f:i32(0)
	end)
end)

