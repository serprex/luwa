	initclasses = initclasses,
	strmap = std_strmap,
	strrep = std_strrep,
	concat = std_concat,
	match = std_match,
	capture = std_capture,
	captures = std_captures,
	findplain = std_findplain,
	fltdigits = std_fltdigits,
	fmtint = std_fmtint,
}
