	f:i32(1)
	f:add()
	f:loadg(mplen)
	f:geu()
	f:iff(function()
		raise(f, ERR_BALANCE)
	end)
	f:load(s)
	f:loadg(mslen)
	f:geu()
	failif(f)
	patat(f, p)
	f:store(b)
	patat(f, p, 1)
	f:store(e)
	srcat(f, s)
	f:load(b)
	f:ne()
	failif(f)
	f:i32(1)
	f:store(cont)
	f:loop(function(loop)
		inc(f, s)
		f:load(s)
		f:loadg(mslen)
		f:geu()
		failif(f)
		srcat(f, s)
		f:tee(c)
		f:load(e)
		f:eq()
		f:iff(function()
			f:load(cont)
			f:i32(1)
			f:sub()
			f:tee(cont)
			f:eqz()
			f:iff(function()
				f:load(s)
				f:i32(1)
				f:add()
				f:ret()
			end)
		end, function()
			f:load(c)
			f:load(b)
			f:eq()
			f:iff(function()
				inc(f, cont)
			end)
		end)
		f:br(loop)
	end)
	f:unreachable()
end)

-- Greedy repeat of the class p..ep from s, then the rest of the pattern at ep+1
local maxexpand = func(i32, i32, i32, i32, function(f, s, p, ep)
	local i, r = f:locals(i32, 2)
	f:block(function(done)
		f:loop(function(loop)
			f:load(s)
			f:load(i)
			f:add()
			f:load(p)
			f:load(ep)
			f:call(msingle)
			f:eqz()
			f:brif(done)
			inc(f, i)
			f:br(loop)
		end)
	end)
	f:loop(function(loop)
		f:load(s)
		f:load(i)
		f:add()
		f:load(ep)
		f:i32(1)
		f:add()
		f:call(match)
		f:tee(r)
		f:i32(-1)
		f:ne()
		f:iff(function()
			f:load(r)
			f:ret()
		end)
		f:loadg(merr)
		failif(f)
		f:load(i)
		f:i32(1)
		f:sub()
		f:tee(i)
		f:i32(0)
		f:ges()
		f:brif(loop)
	end)
	f:i32(-1)
end)

-- Lazy repeat of the class p..ep from s
local minexpand = func(i32, i32, i32, i32, function(f, s, p, ep)
	local r = f:locals(i32)
	f:loop(function(loop)
		f:load(s)
		f:load(ep)
		f:i32(1)
		f:add()
		f:call(match)
		f:tee(r)
		f:i32(-1)
		f:ne()
		f:iff(function()
			f:load(r)
			f:ret()
		end)
		f:loadg(merr)
		failif(f)
		f:load(s)
		f:load(p)
		f:load(ep)
		f:call(msingle)
		f:eqz()
		failif(f)
		inc(f, s)
		f:br(loop)
	end)
	f:unreachable()
end)

local startcapture = func(i32, i32, i32, i32, function(f, s, p, what)
	local l, r = f:locals(i32, 2)
	f:loadg(mlevel)
	f:tee(l)
	f:i32(MAXCAPTURES)
	f:geu()
	f:iff(function()
		raise(f, ERR_MANYCAPS)
	end)
	capset(f, l, 0, function() f:load(s) end)
	capset(f, l, 1, function() f:load(what) end)
	f:load(l)
	f:i32(1)
	f:add()
	f:storeg(mlevel)
	f:load(s)
	f:load(p)
	f:call(match)
	f:tee(r)
	f:i32(-1)
	f:eq()
	f:iff(function()
		f:load(l)
		f:storeg(mlevel)
	end)
	f:load(r)
end)

local endcapture = func(i32, i32, i32, function(f, s, p)
	local l, r = f:locals(i32, 2)
	-- the last unfinished capture
	f:loadg(mlevel)
	f:store(l)
	f:block(function(found)
		f:loop(function(loop)
			f:load(l)
			f:i32(1)
			f:sub()
			f:tee(l)
			f:i32(0)
			f:lts()
			f:iff(function()
				raise(f, ERR_CAPTURE)
			end)
			capget(f, l, 1)
			f:i32(CAP_UNF)
			f:eq()
			f:brif(found)
			f:br(loop)
		end)
	end)
	capset(f, l, 1, function()
		f:load(s)
		capget(f, l, 0)
		f:sub()
	end)
	f:load(s)
	f:load(p)
	f:call(match)
	f:tee(r)
	f:i32(-1)
	f:eq()
	f:iff(function()
		capset(f, l, 1, function() f:i32(CAP_UNF) end)
	end)
	f:load(r)
end)

-- %1-9 back reference, d is the digit byte
local mbackref = func(i32, i32, i32, function(f, s, d)
	local l, len, init, k = f:locals(i32, 4)
	f:load(d)
	f:i32(49) -- 1
	f:sub()
	f:tee(l)
	f:i32(0)
	f:lts()
	f:load(l)
	f:loadg(mlevel)
	f:ges()
	f:bor()
	f:iff(i32, function()
		f:i32(1)
	end, function()
		capget(f, l, 1)
		f:i32(CAP_UNF)
		f:eq()
	end)
	f:iff(function()
		f:load(d)
		f:i32(ERR_CAPIDX - 48)
		f:add()
		f:storeg(merr)
		f:i32(-1)
		f:ret()
	end)
	capget(f, l, 1)
	f:store(len)
	-- a position capture never matches, like C's size_t cast
	f:load(len)
	f:i32(0)
	f:lts()
	failif(f)
	f:loadg(mslen)
	f:load(s)
	f:sub()
	f:load(len)
	f:lts()
	failif(f)
	capget(f, l, 0)
	f:store(init)
	f:block(function(done)
		f:loop(function(loop)
			f:load(k)
			f:load(len)
			f:geu()
			f:brif(done)
			f:loadg(msrc)
			f:load(init)
			f:load(k)
			f:add()
			f:arrayget(bytes, false)
			f:loadg(msrc)
			f:load(s)
			f:load(k)
			f:add()
			f:arrayget(bytes, false)
			f:ne()
			failif(f)
			inc(f, k)
			f:br(loop)
		end)
	end)
	f:load(s)
	f:load(len)
	f:add()
end)

-- Match from s with the pattern at p
match = func(i32, i32, i32, function(f, s, p)
	local pc, nc, ep, epc, r, prev, cur = f:locals(i32, 7)
	f:loadg(mdepth)
	f:eqz()
	f:iff(function()
		raise(f, ERR_COMPLEX)
	end)
	f:loadg(mdepth)
	f:i32(1)
	f:sub()
	f:storeg(mdepth)
	f:block(function(done)
		f:loop(function(init)
			f:load(p)
			f:loadg(mplen)
			f:geu()
			f:brif(done)
			patat(f, p)
			f:store(pc)
			-- the byte after pc, 0 past the end
			f:load(p)
			f:i32(1)
			f:add()
			f:loadg(mplen)
			f:ltu()
			f:iff(i32, function()
				patat(f, p, 1)
			end, function()
				f:i32(0)
			end)
			f:store(nc)
			f:load(pc)
			f:i32(40) -- (
			f:eq()
			f:iff(function()
				-- () is a position capture
				f:load(s)
				f:load(p)
				f:i32(2)
				f:add()
				f:load(p)
				f:i32(1)
				f:add()
				f:load(nc)
				f:i32(41) -- )
				f:eq()
				f:select()
				f:i32(CAP_POS)
				f:i32(CAP_UNF)
				f:load(nc)
				f:i32(41)
				f:eq()
				f:select()
				f:call(startcapture)
				f:store(s)
				f:br(done)
			end)
			f:load(pc)
			f:i32(41) -- )
			f:eq()
			f:iff(function()
				f:load(s)
				f:load(p)
				f:i32(1)
				f:add()
				f:call(endcapture)
				f:store(s)
				f:br(done)
			end)
			-- $ at the end
			f:load(pc)
			f:i32(36)
			f:eq()
			f:load(p)
			f:i32(1)
			f:add()
			f:loadg(mplen)
			f:eq()
			f:band()
			f:iff(function()
				f:load(s)
				f:loadg(mslen)
				f:ne()
				f:iff(function()
					f:i32(-1)
					f:store(s)
				end)
				f:br(done)
			end)
			f:load(pc)
			f:i32(37) -- %
			f:eq()
			f:iff(function()
				f:load(nc)
				f:i32(98) -- b
				f:eq()
				f:iff(function()
					f:load(s)
					f:load(p)
					f:i32(2)
					f:add()
					f:call(mbalance)
					f:tee(s)
					f:i32(-1)
					f:eq()
					f:brif(done)
					inc(f, p, 4)
					f:br(init)
				end)
				f:load(nc)
				f:i32(102) -- f
				f:eq()
				f:iff(function()
					inc(f, p, 2)
					f:load(p)
					f:loadg(mplen)
					f:geu()
					f:iff(i32, function()
						f:i32(1)
					end, function()
						patat(f, p)
						f:i32(91) -- [
						f:ne()
					end)
					f:iff(function()
						raise(f, ERR_FRONTIER)
					end)
					f:load(p)
					f:call(mclassend)
					f:tee(ep)
					f:i32(-1)
					f:eq()
					failif(f)
					-- before the start & past the end count as byte 0
					f:load(s)
					f:iff(i32, function()
						f:loadg(msrc)
						f:load(s)
						f:i32(1)
						f:sub()
						f:arrayget(bytes, false)
					end, function()
						f:i32(0)
					end)
					f:store(prev)
					f:load(s)
					f:loadg(mslen)
					f:ltu()
					f:iff(i32, function()
						srcat(f, s)
					end, function()
						f:i32(0)
					end)
					f:store(cur)
					f:load(prev)
					f:loadg(mpat)
					f:load(p)
					f:load(ep)
					f:i32(1)
					f:sub()
					f:call(bracket)
					f:eqz()
					f:load(cur)
					f:loadg(mpat)
					f:load(p)
					f:load(ep)
					f:i32(1)
					f:sub()
					f:call(bracket)
					f:band()
					f:iff(function()
						f:load(ep)
						f:store(p)
						f:br(init)
					end)
					f:i32(-1)
					f:store(s)
					f:br(done)
				end)
				f:load(nc)
				f:i32(48)
				f:sub()
				f:i32(10)
				f:ltu()
				f:iff(function()
					f:load(s)
					f:load(nc)
					f:call(mbackref)
					f:tee(s)
					f:i32(-1)
					f:eq()
					f:brif(done)
					inc(f, p, 2)
					f:br(init)
				end)
			end)
			-- a single class & maybe *, +, ? or -
			f:load(p)
			f:call(mclassend)
			f:tee(ep)
			f:i32(-1)
			f:eq()
			failif(f)
			f:load(ep)
			f:loadg(mplen)
			f:ltu()
			f:iff(i32, function()
				patat(f, ep)
			end, function()
				f:i32(0)
			end)
			f:store(epc)
			f:load(s)
			f:load(p)
			f:load(ep)
			f:call(msingle)
			f:eqz()
			f:iff(function()
				f:load(epc)
				f:i32(42) -- *
				f:eq()
				f:load(epc)
				f:i32(63) -- ?
				f:eq()
				f:bor()
				f:load(epc)
				f:i32(45) -- -
				f:eq()
				f:bor()
				f:iff(function()
					f:load(ep)
					f:i32(1)
					f:add()
					f:store(p)
					f:br(init)
				end)
				f:i32(-1)
				f:store(s)
				f:br(done)
			end)
			f:load(epc)
			f:i32(63) -- ?
			f:eq()
			f:iff(function()
				f:load(s)
				f:i32(1)
				f:add()
				f:load(ep)
				f:i32(1)
				f:add()
				f:call(match)
				f:tee(r)
				f:i32(-1)
				f:ne()
				f:iff(function()
					f:load(r)
					f:store(s)
					f:br(done)
				end)
				f:loadg(merr)
				failif(f)
				f:load(ep)
				f:i32(1)
				f:add()
				f:store(p)
				f:br(init)
			end)
			f:load(epc)
			f:i32(43) -- +
			f:eq()
			f:iff(function()
				f:load(s)
				f:i32(1)
				f:add()
				f:load(p)
				f:load(ep)
				f:call(maxexpand)
				f:store(s)
				f:br(done)
			end)
			f:load(epc)
			f:i32(42) -- *
			f:eq()
			f:iff(function()
				f:load(s)
				f:load(p)
				f:load(ep)
				f:call(maxexpand)
				f:store(s)
				f:br(done)
			end)
			f:load(epc)
			f:i32(45) -- -
			f:eq()
			f:iff(function()
				f:load(s)
				f:load(p)
				f:load(ep)
				f:call(minexpand)
				f:store(s)
				f:br(done)
			end)
			inc(f, s)
			f:load(ep)
			f:store(p)
			f:br(init)
		end)
	end)
	f:loadg(mdepth)
	f:i32(1)
	f:add()
	f:storeg(mdepth)
	f:load(s)
end)

-- _luwa.match(s, p, si, pi, anchor, lastmatch): the first match of p from pi, trying starts si, si+1, ..
-- (only si when anchor is 1), skipping matches that end at lastmatch (0 for none).
-- Gives start, end (just past the match) & capture count, start 0 for no match, -code for an error
local std_match = func(function(f)
	local si, last, r = f:locals(i32, 3)
	local function push3(a, b, c)
		a()
		pushint(f)
		b()
		pushint(f)
		c()
		pushint(f)
	end
	strparam(f, 0)
	f:storeg(msrc)
	f:loadg(msrc)
	f:arraylen()
	f:storeg(mslen)
	strparam(f, 1)
	f:storeg(mpat)
	f:loadg(mpat)
	f:arraylen()
	f:storeg(mplen)
	i32param(f, 2)
	f:i32(1)
	f:sub()
	f:store(si)
	i32param(f, 5)
	f:i32(1)
	f:sub()
	f:store(last)
	f:loop(function(loop)
		f:i32(0)
		f:storeg(mlevel)
		f:i32(0)
		f:storeg(merr)
		f:i32(MAXCCALLS)
		f:storeg(mdepth)
		f:load(si)
		i32param(f, 3)
		f:i32(1)
		f:sub()
		f:call(match)
		f:store(r)
		f:loadg(merr)
		f:iff(function()
			push3(function()
				f:i32(0)
				f:loadg(merr)
				f:sub()
			end, function() f:i32(0) end, function() f:i32(0) end)
			f:ret()
		end)
		f:load(r)
		f:i32(-1)
		f:ne()
		f:load(r)
		f:load(last)
		f:ne()
		f:band()
		f:iff(function()
			push3(function()
				f:load(si)
				f:i32(1)
				f:add()
			end, function()
				f:load(r)
				f:i32(1)
				f:add()
			end, function()
				f:loadg(mlevel)
			end)
			f:ret()
		end)
		i32param(f, 4)
		f:eqz()
		f:load(si)
		f:loadg(mslen)
		f:ltu()
		f:band()
		f:iff(function()
			inc(f, si)
			f:br(loop)
		end)
	end)
	push3(function() f:i32(0) end, function() f:i32(0) end, function() f:i32(0) end)
end)

-- Pushes source bytes [start, start+len) as a string
local function pushsub(f, start, len)
	local nb = f:locals(R.bytes)
	len()
	f:arraynewdefault(bytes)
	f:tee(nb)
	f:i32(0)
	f:loadg(msrc)
	start()
	len()
	f:arraycopy(bytes, bytes)
	f:load(nb)
	f:call(alloc.strfrombytes)
	f:call(tmppush)
end

-- Pushes capture l (0 based): a string, or an integer for a position capture.
-- Gives 0, or 1 when it's unfinished
local pushcap = func(i32, i32, function(f, l)
	local len = f:locals(i32)
	capget(f, l, 1)
	f:tee(len)
	f:i32(CAP_UNF)
	f:eq()
	f:iff(function()
		f:i32(1)
		f:ret()
	end)
	f:load(len)
	f:i32(CAP_POS)
	f:eq()
	f:iff(function()
		capget(f, l, 0)
		f:i32(1)
		f:add()
		pushint(f)
	end, function()
		pushsub(f, function() capget(f, l, 0) end, function() f:load(len) end)
	end)
	f:i32(0)
end)

-- _luwa.capture(i, si, e): capture i of the last match si..e, the whole match when i is 1 & there are none.
-- nil for a bad index, false when it's unfinished
local std_capture = func(function(f)
	local i, si, e = f:locals(i32, 3)
	i32param(f, 0)
	f:i32(1)
	f:sub()
	f:tee(i)
	f:loadg(mlevel)
	f:ges()
	f:iff(function()
		f:load(i)
		f:iff(function()
			alloc.lnil(f)
			f:call(tmppush)
		end, function()
			i32param(f, 1)
			f:i32(1)
			f:sub()
			f:store(si)
			i32param(f, 2)
			f:i32(1)
			f:sub()
			f:store(e)
			pushsub(f, function() f:load(si) end, function()
				f:load(e)
				f:load(si)
				f:sub()
			end)
		end)
		f:ret()
	end)
	f:load(i)
	f:call(pushcap)
	f:iff(function()
		alloc.lfalse(f)
		f:call(tmppush)
	end)
end)

-- _luwa.captures(): all captures of the last match, which has at least 1. Just false when one is unfinished
local std_captures = func(function(f)
	local l = f:locals(i32)
	f:block(function(done)
		f:loop(function(loop)
			f:load(l)
			f:loadg(mlevel)
			f:geu()
			f:brif(done)
			capget(f, l, 1)
			f:i32(CAP_UNF)
			f:eq()
			f:iff(function()
				alloc.lfalse(f)
				f:call(tmppush)
				f:ret()
			end)
			inc(f, l)
			f:br(loop)
		end)
	end)
	f:i32(0)
	f:store(l)
	f:block(function(done)
		f:loop(function(loop)
			f:load(l)
			f:loadg(mlevel)
			f:geu()
			f:brif(done)
			f:load(l)
			f:call(pushcap)
			f:drop()
			inc(f, l)
			f:br(loop)
		end)
	end)
end)

-- _luwa.findplain(s, p, init): the first position from init where p is in s, or 0. init <= #s + 1
local std_findplain = func(function(f)
	local s, p = f:locals(R.bytes, 2)
	local plen, i, last, first, j = f:locals(i32, 5)
	strparam(f, 0)
	f:store(s)
	strparam(f, 1)
	f:tee(p)
	f:arraylen()
	f:tee(plen)
	f:eqz()
	f:iff(function()
		loadparam(f, 2)
		f:call(tmppush)
		f:ret()
	end)
	f:load(s)
	f:arraylen()
	f:load(plen)
	f:sub()
	f:store(last)
	byteat(f, p, j)
	f:store(first)
	i32param(f, 2)
	f:i32(1)
	f:sub()
	f:store(i)
	f:block(function(done)
		f:loop(function(loop)
			f:load(i)
			f:load(last)
			f:gts()
			f:brif(done)
			byteat(f, s, i)
			f:load(first)
			f:eq()
			f:iff(function()
				f:i32(1)
				f:store(j)
				f:block(function(nomatch)
					f:loop(function(inner)
						f:load(j)
						f:load(plen)
						f:geu()
						f:iff(function()
							f:load(i)
							f:i32(1)
							f:add()
							pushint(f)
							f:ret()
						end)
						f:load(s)
						f:load(i)
						f:load(j)
						f:add()
						f:arrayget(bytes, false)
						byteat(f, p, j)
						f:ne()
						f:brif(nomatch)
						f:load(j)
						f:i32(1)
						f:add()
						f:store(j)
						f:br(inner)
					end)
				end)
			end)
			f:load(i)
			f:i32(1)
			f:add()
			f:store(i)
			f:br(loop)
		end)
	end)
	f:i32(0)
	pushint(f)
end)

-- _luwa.fltdigits(x, k): the decimal digits of |x| * 10^k rounded to an integer, half to even.
-- x is a finite float, -330 <= k <= 430. The prelude lays out %f, %e & %g from these
local std_fltdigits = func(function(f)
	loadparam(f, 0)
	f:refcast(M.ref(alloc.float))
	f:structget(alloc.float, 'val')
	f:abs()
	i32param(f, 1)
	f:call(_float.decdigits)
	f:call(tmppush)
end)

-- _luwa.fmtint(x, base, upper): digits of integer x read as unsigned, in base 8, 10 or 16.
-- upper is 1 for A-F, 0 for a-f
local std_fmtint = func(function(f)
	local buf, outb = f:locals(R.bytes, 2)
	local x, base = f:locals(i64, 2)
	local pos, d, alpha = f:locals(i32, 3)
	i64param(f, 0)
	f:store(x)
	i64param(f, 1)
	f:store(base)
	-- byte of digit 10 minus 10
	i32param(f, 2)
	f:iff(i32, function()
		f:i32(55) -- A
	end, function()
		f:i32(87) -- a
	end)
	f:store(alpha)
	f:i32(24)
	f:arraynewdefault(bytes)
	f:store(buf)
	f:i32(24)
	f:store(pos)
	f:loop(function(loop)
		f:load(pos)
		f:i32(1)
		f:sub()
		f:store(pos)
		f:load(buf)
		f:load(pos)
		f:load(x)
		f:load(base)
		f:remu()
		f:i32wrap()
		f:tee(d)
		f:i32(48)
		f:add()
		f:load(d)
		f:load(alpha)
		f:add()
		f:load(d)
		f:i32(10)
		f:ltu()
		f:select()
		f:arrayset(bytes)
		f:load(x)
		f:load(base)
		f:divu()
		f:tee(x)
		f:i64(0)
		f:ne()
		f:brif(loop)
	end)
	f:i32(24)
	f:load(pos)
	f:sub()
	f:arraynewdefault(bytes)
	f:tee(outb)
	f:i32(0)
	f:load(buf)
	f:load(pos)
	f:i32(24)
	f:load(pos)
	f:sub()
	f:arraycopy(bytes, bytes)
	f:load(outb)
	f:call(alloc.strfrombytes)
	f:call(tmppush)
end)

