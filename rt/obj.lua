local M = require 'make'
local func = M.func

local alloc = require 'alloc'
local types, R, typeof = alloc.types, alloc.R, alloc.typeof
local int, float, str, bytes, idobj = alloc.int, alloc.float, alloc.str, alloc.bytes, alloc.idobj
local util = require 'util'

-- nil & false are the only falsy values
local truthy = func(V, i32, function(f, o)
	f:load(o)
	f:refisnull()
	f:iff(function()
		f:i32(0)
		f:ret()
	end)
	f:load(o)
	alloc.lfalse(f)
	f:refeq()
	f:eqz()
end)

local intval = alloc.intval
local function fltval(f, o)
	f:load(o)
	f:refcast(M.ref(float))
	f:structget(float, 'val')
end

-- Same bytes
local streq = func(R.str, R.str, i32, function(f, a, b)
	local ab, bb = f:locals(R.bytes, 2)
	local i, n = f:locals(i32, 2)
	f:load(a)
	f:structget(str, 'bytes')
	f:tee(ab)
	f:arraylen()
	f:tee(n)
	f:load(b)
	f:structget(str, 'bytes')
	f:tee(bb)
	f:arraylen()
	f:ne()
	f:iff(function()
		f:i32(0)
		f:ret()
	end)
	f:loop(function(loop)
		f:load(i)
		f:load(n)
		f:ltu()
		f:iff(function()
			f:load(ab)
			f:load(i)
			f:arrayget(bytes, false)
			f:load(bb)
			f:load(i)
			f:arrayget(bytes, false)
			f:ne()
			f:iff(function()
				f:i32(0)
				f:ret()
			end)
			f:load(i)
			f:i32(1)
			f:add()
			f:store(i)
			f:br(loop)
		end)
	end)
	f:i32(1)
end)

-- Raw equality, no metamethods. Ints equal floats of the same value
local eq = func(V, V, i32, function(f, a, b)
	local ta, tb = f:locals(i32, 2)
	f:load(a)
	f:load(b)
	f:refeq()
	f:iff(function()
		-- the same object is equal to itself, unless it's a NaN, which the float case below checks
		f:load(a)
		f:call(typeof)
		f:i32(types.float)
		f:ne()
		f:iff(function()
			f:i32(1)
			f:ret()
		end)
	end)
	f:load(a)
	f:call(typeof)
	f:tee(ta)
	f:load(b)
	f:call(typeof)
	f:tee(tb)
	f:ne()
	f:iff(function()
		-- int & float: compare as floats
		f:load(ta)
		f:load(tb)
		f:bor()
		f:i32(1)
		f:ne()
		f:iff(function()
			f:i32(0)
			f:ret()
		end)
		f:load(ta)
		f:iff(function()
			-- a is the float, swap so b is
			f:load(a)
			f:load(b)
			f:store(a)
			f:store(b)
		end)
		fltval(f, b)
		intval(f, a)
		f:f64converts()
		f:eq()
		f:ret()
	end)
	f:switch(function()
		f:load(ta)
	end, types.int, function()
		intval(f, a)
		intval(f, b)
		f:eq()
		f:ret()
	end, types.float, function()
		fltval(f, a)
		fltval(f, b)
		f:eq()
		f:ret()
	end, types.str, function()
		f:load(a)
		f:refcast(R.str)
		f:load(b)
		f:refcast(R.str)
		f:call(streq)
		f:ret()
	end, -1)
	f:i32(0)
end)

-- Hash of the int value x
local function hashi64(f, x)
	f:load(x)
	f:i32wrap()
	f:load(x)
	f:i64(32)
	f:shru()
	f:i32wrap()
	f:xor()
end

local hash = func(V, i32, function(f, o)
	local h, n, i = f:locals(i32, 3)
	local x = f:locals(i64)
	local fl = f:locals(f64)
	local s = f:locals(R.str)
	local b = f:locals(R.bytes)
	f:switch(function()
		f:load(o)
		f:call(typeof)
	end, types.int, function()
		intval(f, o)
		f:store(x)
		hashi64(f, x)
		f:ret()
	end, types.float, function()
		fltval(f, o)
		f:store(fl)
		f:load(fl)
		f:call(util.fltisint)
		f:iff(function()
			-- integral floats hash like the int they equal
			f:load(fl)
			f:i64truncs()
			f:store(x)
		end, function()
			f:load(fl)
			f:i64reinterpret()
			f:store(x)
		end)
		hashi64(f, x)
		f:ret()
	end, types.single, function()
		-- nil 0, false 1, true 2
		f:load(o)
		f:refisnull()
		f:iff(function()
			f:i32(0)
			f:ret()
		end)
		f:load(o)
		alloc.ltrue(f)
		f:refeq()
		f:i32(1)
		f:add()
		f:ret()
	end, types.tbl, types.functy, types.coro, function()
		f:load(o)
		f:refcast(M.ref(idobj))
		f:structget(idobj, 'id')
		f:ret()
	end, types.str, function()
		f:load(o)
		f:refcast(R.str)
		f:tee(s)
		f:structget(str, 'hash')
		f:tee(h)
		f:iff(function()
			f:load(h)
			f:ret()
		end)
		-- FNV-1a
		f:i32(-2128831035)
		f:store(h)
		f:load(s)
		f:structget(str, 'bytes')
		f:tee(b)
		f:arraylen()
		f:store(n)
		f:loop(function(loop)
			f:load(i)
			f:load(n)
			f:ltu()
			f:iff(function()
				f:load(h)
				f:load(b)
				f:load(i)
				f:arrayget(bytes, false)
				f:xor()
				f:i32(16777619)
				f:mul()
				f:store(h)
				f:load(i)
				f:i32(1)
				f:add()
				f:store(i)
				f:br(loop)
			end)
		end)
		-- 0 means not worked out yet
		f:load(s)
		f:load(h)
		f:i32(113)
		f:load(h)
		f:select()
		f:tee(h)
		f:structset(str, 'hash')
		f:load(h)
		f:ret()
	end, -1)
	f:i32(0)
end)

return {
	truthy = truthy,
	streq = streq,
	eq = eq,
	hash = hash,
	hashi64 = hashi64,
}
