local M = require 'make'

local alloc = require 'alloc'
local str, bytes, R = alloc.str, alloc.bytes, alloc.R

-- -1, 0 or 1 as a is before, same as or after b, by bytes
local strcmp = M.func(R.str, R.str, i32, function(f, a, b)
	local ab, bb = f:locals(R.bytes, 2)
	local idx, len, alen, blen, c = f:locals(i32, 5)
	f:load(a)
	f:structget(str, 'bytes')
	f:tee(ab)
	f:arraylen()
	f:store(alen)
	f:load(b)
	f:structget(str, 'bytes')
	f:tee(bb)
	f:arraylen()
	f:store(blen)
	-- len = min(alen, blen)
	f:load(alen)
	f:load(blen)
	f:load(alen)
	f:load(blen)
	f:ltu()
	f:select()
	f:store(len)

	f:loop(function(loop)
		f:load(idx)
		f:load(len)
		f:ltu()
		f:iff(function()
			f:load(ab)
			f:load(idx)
			f:arrayget(bytes, false)
			f:load(bb)
			f:load(idx)
			f:arrayget(bytes, false)
			f:sub()
			f:tee(c)
			f:iff(function()
				f:i32(1)
				f:i32(-1)
				f:load(c)
				f:i32(0)
				f:gts()
				f:select()
				f:ret()
			end)
			f:load(idx)
			f:i32(1)
			f:add()
			f:store(idx)
			f:br(loop)
		end)
	end)
	-- shorter one comes first
	f:load(alen)
	f:load(blen)
	f:gtu()
	f:load(alen)
	f:load(blen)
	f:ltu()
	f:sub()
end)

-- New string a..b
local strconcat = M.func(R.str, R.str, M.ref(str), function(f, a, b)
	local ab, bb, nb = f:locals(R.bytes, 3)
	local alen = f:locals(i32)
	f:load(a)
	f:structget(str, 'bytes')
	f:tee(ab)
	f:arraylen()
	f:tee(alen)
	f:load(b)
	f:structget(str, 'bytes')
	f:tee(bb)
	f:arraylen()
	f:add()
	f:arraynewdefault(bytes)
	f:tee(nb)
	f:i32(0)
	f:load(ab)
	f:i32(0)
	f:load(alen)
	f:arraycopy(bytes, bytes)
	f:load(nb)
	f:load(alen)
	f:load(bb)
	f:i32(0)
	f:load(bb)
	f:arraylen()
	f:arraycopy(bytes, bytes)
	f:load(nb)
	f:call(alloc.strfrombytes)
end)

return {
	strcmp = strcmp,
	strconcat = strconcat,
}
