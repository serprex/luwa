-- Lua compiler in wasm, like lparser.c: source to bytecode in one go, no tree.
-- The grammar at the bottom is turned into wasm funcs by pgen.lua, its actions emit code with lcode.lua.
-- Two passes over the source: the first finds what the second needs to know before it gets there
-- (captured locals, & where the parts of assignments & tables are, as bcgen emitted those out of order)
local M = require 'make'
local func = M.func
local LV = M.eqref -- a Lua value. V below is a grammar rule
local P = require 'pgen'
local seq, m, p, o, V, val, kw, act, when, close, prec =
	P.seq, P.m, P.p, P.o, P.V, P.val, P.kw, P.act, P.when, P.close, P.prec

local lex = require 'lex'
local bc = require 'bc'
local alloc = require 'alloc'
local _lex = require '_lex'
local _table = require '_table'
local C = require 'lcode'
local R, str, bytes, stack = alloc.R, alloc.str, alloc.bytes, alloc.stack
local tblget, tblset = _table.tblget, _table.tblset
local streq = require('obj').streq
local strconcat = require('_string').strconcat
local G, EK, K, E, S, op, fget, fset, pc, ifpass2 = C.G, C.EK, C.K, C.E, C.S, C.op, C.fget, C.fset, C.pc, C.ifpass2
local Rvl, Ril, var, fs, ilist = R.stack, C.Ril, C.var, C.fs, C.ilist
local errs = C.errs

-- Token stream. The current token & one token of lookahead, each with what it takes to go back to
-- it: its byte, value & line, where it starts & ends in the source, & the lexer's line count there
local tokfields = { { 'tok', i32 }, { 'val', LV }, { 'line', i32 }, { 'start', i32 }, { 'pos', i32 }, { 'lnline', i32 }, { 'lnpos', i32 } }
local cur, ahead = {}, {}
for _, fd in ipairs(tokfields) do
	cur[fd[1]] = M.global(fd[2], true)
	ahead[fd[1]] = M.global(fd[2], true)
end
local ahas = M.global(i32, true)
local lexfields = { tok = _lex.tok, val = _lex.val, line = _lex.line, start = _lex.ts, pos = _lex.pos, lnline = _lex.lnline, lnpos = _lex.lnpos }
-- equal string literals of a chunk are one string, like C Lua's
local strs = M.global(R.tbl, true)
local function lexinto(f, t)
	f:call(_lex.next)
	f:loadg(_lex.tok)
	f:i32(lex._string)
	f:eq()
	f:iff(function()
		local v = f:locals(LV)
		f:loadg(strs)
		f:loadg(_lex.val)
		f:call(tblget)
		f:tee(v)
		f:refisnull()
		f:iff(function()
			f:loadg(strs)
			f:loadg(_lex.val)
			f:loadg(_lex.val)
			f:call(tblset)
		end, function()
			f:load(v)
			f:storeg(_lex.val)
		end)
	end)
	for _, fd in ipairs(tokfields) do
		f:loadg(lexfields[fd[1]])
		f:storeg(t[fd[1]])
	end
end
local tnext = func(function(f)
	f:loadg(ahas)
	f:iff(function()
		for _, fd in ipairs(tokfields) do
			f:loadg(ahead[fd[1]])
			f:storeg(cur[fd[1]])
		end
		f:i32(0)
		f:storeg(ahas)
	end, function()
		lexinto(f, cur)
	end)
end)
tnext.name = 'parse.next'
-- The token after the current one
local tlook = func(i32, function(f)
	f:loadg(ahas)
	f:eqz()
	f:iff(function()
		lexinto(f, ahead)
		f:i32(1)
		f:storeg(ahas)
	end)
	f:loadg(ahead.tok)
end)
tlook.name = 'parse.lookahead'
local function tok(f)
	f:loadg(cur.tok)
end
local function curline(f)
	f:loadg(cur.line)
end
-- the current token, as a key for pass 1's notes: where it ends in the source
local function tkey(f)
	f:loadg(cur.pos)
end

-- A saved spot in the token stream, to come back to it
local spot = M.struct((function()
	local fl = {}
	for i, fd in ipairs(tokfields) do
		fl[i] = { fd[2], name = fd[1] }
	end
	return fl
end)(), { name = 'spot' })
local savespot = func(M.ref(spot), function(f)
	for _, fd in ipairs(tokfields) do
		f:loadg(cur[fd[1]])
	end
	f:structnew(spot)
end)
local gotospot = func(LV, void, function(f, s)
	local sp = f:locals(M.ref(spot))
	f:load(s)
	f:refcast(M.ref(spot))
	f:store(sp)
	for _, fd in ipairs(tokfields) do
		f:load(sp)
		f:structget(spot, fd[1])
		f:storeg(cur[fd[1]])
	end
	f:i32(0)
	f:storeg(ahas)
	f:loadg(cur.pos)
	f:storeg(_lex.pos)
	f:loadg(cur.lnline)
	f:storeg(_lex.lnline)
	f:loadg(cur.lnpos)
	f:storeg(_lex.lnpos)
end)

-- Errors at the current token. A lexing error wins, it's what made the token wrong
local raise = func(i32, void, function(f, code)
	f:load(code)
	f:storeg(errs.code)
	f:loadg(cur.line)
	f:storeg(errs.line)
	f:loadg(cur.start)
	f:storeg(errs.s)
	f:loadg(cur.pos)
	f:storeg(errs.e)
	f:loadg(cur.tok)
	f:eqz()
	f:iff(function()
		f:i32(-1)
		f:storeg(errs.e)
	end)
	f:loadg(cur.tok)
	f:i32(255)
	f:eq()
	f:iff(function()
		f:i32(E.lex)
		f:storeg(errs.code)
		f:loadg(_lex.err)
		f:storeg(errs.n)
		f:loadg(_lex.errs)
		f:storeg(errs.s)
		f:loadg(_lex.erre)
		f:storeg(errs.e)
	end)
	f:throw(C.errtag)
end)
raise.name = 'parse.raise'
local hooks = {
	tok = tok,
	line = curline,
	next = tnext,
	expected = function(f, L, t)
		f:i32(t)
		f:storeg(errs.tok)
		f:i32(E.expected)
		f:call(raise)
	end,
	unexpected = function(f, L)
		f:i32(E.unexpected)
		f:call(raise)
	end,
	closeerr = function(f, L, t, open, line)
		f:i32(t)
		f:storeg(errs.tok)
		f:i32(open)
		f:storeg(errs.n2)
		line(f, L)
		f:storeg(errs.n)
		f:i32(E.close)
		f:call(raise)
	end,
}
local function syntaxerr(f)
	f:i32(E.syntax)
	f:call(raise)
end

-- Tests for the few places one token of lookahead isn't enough
-- , name in a parameter list, not , ...
local function commaname(f)
	tok(f)
	f:i32(lex._comma)
	f:eq()
	f:iff(i32, function()
		f:call(tlook)
		f:i32(lex._ident)
		f:eq()
	end, function()
		f:i32(0)
	end)
end
-- a , or ; with another field after it
local function sepfield(f)
	tok(f)
	f:i32(lex._comma)
	f:eq()
	tok(f)
	f:i32(lex._semi)
	f:eq()
	f:bor()
	f:iff(i32, function()
		f:call(tlook)
		f:i32(lex._cr)
		f:ne()
	end, function()
		f:i32(0)
	end)
end
-- name = in a table
local function namefield(f)
	tok(f)
	f:i32(lex._ident)
	f:eq()
	f:iff(i32, function()
		f:call(tlook)
		f:i32(lex._set)
		f:eq()
	end, function()
		f:i32(0)
	end)
end
-- 'global' lexes as a name, so it still works as one where it can't start a declaration
local isglobal = func(i32, function(f)
	local t = f:locals(i32)
	tok(f)
	f:i32(lex._ident)
	f:ne()
	f:iff(function()
		f:i32(0)
		f:ret()
	end)
	f:call(tlook)
	f:tee(t)
	f:i32(lex._ident)
	f:eq()
	f:load(t)
	f:i32(lex._function)
	f:eq()
	f:bor()
	f:load(t)
	f:i32(lex._lt)
	f:eq()
	f:bor()
	f:load(t)
	f:i32(lex._mul)
	f:eq()
	f:bor()
	f:iff(i32, function()
		f:loadg(cur.val)
		f:refcast(R.str)
		f:call(S'global')
		f:call(streq)
	end, function()
		f:i32(0)
	end)
end)
isglobal.name = 'parse.isglobal'

-- Small builder helpers
local function inc(f, l, by)
	f:load(l)
	f:i32(by or 1)
	f:add()
	f:store(l)
end
local function nth(f, l, i)
	-- i is a local, or { n } for the number n
	f:load(l)
	if type(i) == 'table' then
		f:i32(i[1])
	else
		f:load(i)
	end
	C.vlget(f)
end
local function ilnth(f, l, i)
	-- i is a local, or { n } for the number n
	f:load(l)
	if type(i) == 'table' then
		f:i32(i[1])
	else
		f:load(i)
	end
	C.ilget(f)
end
-- for i = from, to (exclusive), step: from & to are pushers, body(i)
local function forloop(f, from, to, step, body)
	local i = f:locals(i32)
	from(f)
	f:store(i)
	f:block(function(done)
		f:loop(function(loop)
			f:load(i)
			to(f)
			if step > 0 then f:ges() else f:lts() end
			f:brif(done)
			body(i)
			inc(f, i, step)
			f:br(loop)
		end)
	end)
end
-- for i = n-1 down to 0
local function fordown(f, n, body)
	forloop(f, function()
		n(f)
		f:i32(1)
		f:sub()
	end, function() f:i32(0) end, -1, body)
end

-- Scopes, for names, gotos & labels. Like bcgen's scope(): do, while, repeat, each if block, for & functions
local scope = M.struct(nil, { name = 'scope' })
local Rsc = M.refnull(scope)
scope:define{
	{ Rsc, name = 'prev' },
	-- scopevars' length at the start
	{ i32, name = 'base' },
	-- names declared in it when its block started, for labels at the block's end
	{ i32, mut = true, name = 'bstart' },
	{ Rvl, name = 'labels' },
	-- gotos not matched to a label yet
	{ Rvl, name = 'gotos' },
	-- labels at the end of the block so far
	{ i32, mut = true, name = 'ntrail' },
	{ i32, name = 'isfunc' },
}
local label = M.struct({
	{ R.str, name = 'name' },
	{ i32, mut = true, name = 'count' },
	{ i32, name = 'pc' },
	{ i32, name = 'tbcn' },
}, { name = 'label' })
local gotos = M.struct({
	{ R.str, name = 'name' },
	{ i32, name = 'line' },
	-- where its jump's target is, & its <close> count's const index (-1 for none)
	{ i32, name = 'pc' },
	{ i32, name = 'kpc' },
	{ i32, name = 'tbcn' },
	-- names declared in the scope it's waiting in, where it is
	{ i32, mut = true, name = 'count' },
	{ M.refnull(label), mut = true, name = 'label' },
}, { name = 'goto' })
local cursc = M.global(Rsc, true)
local function scount(f)
	f:loadg(G.scopevars)
	C.vllen(f)
	f:loadg(cursc)
	f:structget(scope, 'base')
	f:sub()
end
local scopen = func(i32, void, function(f, isfunc)
	f:loadg(cursc)
	f:loadg(G.scopevars)
	C.vllen(f)
	f:i32(0)
	f:call(C.newvl)
	f:call(C.newvl)
	f:i32(0)
	f:load(isfunc)
	f:structnew(scope)
	f:storeg(cursc)
end)
-- Leave the scope. Its gotos find their labels, or wait in the scope around it
local scclose = func(function(f)
	local sc = f:locals(M.ref(scope))
	local gl, ll = f:locals(Rvl, 2)
	local g = f:locals(M.ref(gotos))
	local l = f:locals(M.refnull(label))
	f:loadg(cursc)
	f:refasnonnull()
	f:tee(sc)
	f:structget(scope, 'gotos')
	f:store(gl)
	f:load(sc)
	f:structget(scope, 'labels')
	f:store(ll)
	forloop(f, function() f:i32(0) end, function()
		f:load(gl)
		C.vllen(f)
	end, 1, function(i)
		nth(f, gl, i)
		f:refcast(M.ref(gotos))
		f:store(g)
		f:refnull(label)
		f:store(l)
		f:block(function(found)
			forloop(f, function() f:i32(0) end, function()
				f:load(ll)
				C.vllen(f)
			end, 1, function(j)
				nth(f, ll, j)
				f:refcast(M.ref(label))
				f:tee(l)
				f:structget(label, 'name')
				f:load(g)
				f:structget(gotos, 'name')
				f:call(streq)
				f:brif(found)
				f:refnull(label)
				f:store(l)
			end)
		end)
		f:load(l)
		f:refisnull()
		f:iff(function()
			f:load(sc)
			f:structget(scope, 'isfunc')
			f:iff(function()
				C.semerr(f, E.nolabel, function()
					f:load(g)
					f:structget(gotos, 'line')
				end, function()
					f:load(g)
					f:structget(gotos, 'name')
				end)
			end)
		end, function()
			-- the label can't see a name the goto doesn't
			f:load(l)
			f:structget(label, 'count')
			f:load(g)
			f:structget(gotos, 'count')
			f:gts()
			f:iff(function()
				f:loadg(G.scopevars)
				f:load(sc)
				f:structget(scope, 'base')
				f:load(g)
				f:structget(gotos, 'count')
				f:add()
				C.vlget(f)
				f:refcast(M.ref(var))
				f:structget(var, 'name')
				f:storeg(errs.arg2)
				C.semerr(f, E.intoscope, function()
					f:load(g)
					f:structget(gotos, 'line')
				end, function()
					f:load(g)
					f:structget(gotos, 'name')
				end, function()
					f:load(g)
					f:structget(gotos, 'line')
				end)
			end)
			f:load(g)
			f:load(l)
			f:structset(gotos, 'label')
			fget(f, 'gotos')
			f:load(g)
			f:call(C.vlpush)
		end)
	end)
	f:load(sc)
	f:structget(scope, 'base')
	f:call(C.popnames)
	f:load(sc)
	f:structget(scope, 'prev')
	f:storeg(cursc)
	-- the rest wait in the scope around, where they are now
	forloop(f, function() f:i32(0) end, function()
		f:load(gl)
		C.vllen(f)
	end, 1, function(i)
		nth(f, gl, i)
		f:refcast(M.ref(gotos))
		f:tee(g)
		f:structget(gotos, 'label')
		f:refisnull()
		f:iff(function()
			f:load(g)
			scount(f)
			f:structset(gotos, 'count')
			f:loadg(cursc)
			f:structget(scope, 'gotos')
			f:load(g)
			f:call(C.vlpush)
		end)
	end)
end)

-- break scopes
local brkopen = func(function(f)
	fset(f, 'brk', function()
		fget(f, 'brk')
		fget(f, 'tbcn')
		f:call(C.newil)
		f:structnew(C.brk)
	end)
end)
local brkclose = func(function(f)
	local l = f:locals(Ril)
	fget(f, 'brk')
	f:structget(C.brk, 'pcs')
	f:store(l)
	forloop(f, function() f:i32(0) end, function()
		f:load(l)
		f:structget(ilist, 'len')
	end, 1, function(i)
		ilnth(f, l, i)
		pc(f)
		f:call(C.patch)
	end)
	fset(f, 'brk', function()
		fget(f, 'brk')
		f:structget(C.brk, 'prev')
	end)
end)

-- Make the function object, & its info table for errors & debug, like the prelude's asm2fn did
local mkproto = func(function(f)
	local fn = f:locals(M.ref(alloc.functy))
	local b = f:locals(R.bytes)
	local a = f:locals(R.vals)
	local t, lt, ft = f:locals(R.tbl, 3)
	local n, j, ismain = f:locals(i32, 3)
	local v = f:locals(M.ref(var))
	local lv = f:locals(M.ref(C.lvar))
	local d = f:locals(Rvl)
	f:call(alloc.newfunc)
	f:tee(fn)
	fget(f, 'isvararg')
	f:structset(alloc.functy, 'isdotdotdot')
	pc(f)
	f:arraynewdefault(bytes)
	f:tee(b)
	f:i32(0)
	fget(f, 'bc')
	f:structget(_lex.bbuf, 'arr')
	f:i32(0)
	pc(f)
	f:arraycopy(bytes, bytes)
	f:load(fn)
	f:load(b)
	f:structset(alloc.functy, 'bc')
	fget(f, 'consts')
	C.vllen(f)
	f:tee(n)
	f:arraynewdefault(alloc.vals)
	f:tee(a)
	f:i32(0)
	fget(f, 'consts')
	f:structget(stack, 'arr')
	f:i32(0)
	f:load(n)
	f:arraycopy(alloc.vals, alloc.vals)
	f:load(fn)
	f:load(a)
	f:structset(alloc.functy, 'consts')
	f:load(fn)
	fget(f, 'nlocals')
	f:structset(alloc.functy, 'localc')
	f:load(fn)
	fget(f, 'nparams')
	f:structset(alloc.functy, 'paramc')
	fset(f, 'proto', function() f:load(fn) end)
	f:loadg(G.noinfo)
	f:iff(function()
		f:ret()
	end)
	fget(f, 'main')
	f:store(ismain)
	f:call(alloc.newtbl)
	f:store(t)
	local function setk(key, v)
		C.tsets(f, function() f:load(t) end, key, v)
	end
	local function int(fn)
		return function()
			fn(f)
			f:refi31()
		end
	end
	local function bymain(m, other)
		return function()
			f:load(ismain)
			f:iff(LV, m, other)
		end
	end
	setk('source', function() f:loadg(G.source) end)
	setk('short_src', function() f:loadg(G.short) end)
	setk('what', bymain(function() f:call(S'main') end, function() f:call(S'Lua') end))
	setk('linedefined', bymain(int(function() f:i32(0) end), int(function() fget(f, 'linedef') end)))
	setk('lastlinedefined', bymain(int(function() f:i32(0) end), int(function() fget(f, 'lastlinedef') end)))
	-- pc, line pairs
	f:call(alloc.newtbl)
	f:store(lt)
	forloop(f, function() f:i32(0) end, function()
		fget(f, 'lineinfo')
		f:structget(ilist, 'len')
	end, 1, function(i)
		C.tseti(f, function() f:load(lt) end, function()
			f:load(i)
			f:i32(1)
			f:add()
		end, function()
			fget(f, 'lineinfo')
			f:load(i)
			C.ilget(f)
			f:refi31()
		end)
	end)
	setk('lines', function() f:load(lt) end)
	setk('names', function() fget(f, 'opnames') end)
	setk('name', function() fget(f, 'fname') end)
	setk('nparams', bymain(int(function() f:i32(0) end), int(function() fget(f, 'nparams') end)))
	setk('isvararg', function()
		fget(f, 'isvararg')
		alloc.lbool(f)
	end)
	setk('nups', bymain(int(function() f:i32(1) end), int(function()
		fget(f, 'frees')
		C.vllen(f)
	end)))
	-- names of the frees
	f:call(alloc.newtbl)
	f:store(ft)
	f:load(ismain)
	f:iff(function()
		C.tseti(f, function() f:load(ft) end, 1, function() f:call(S'_ENV') end)
	end, function()
		forloop(f, function() f:i32(0) end, function()
			fget(f, 'frees')
			C.vllen(f)
		end, 1, function(i)
			C.tseti(f, function() f:load(ft) end, function()
				f:load(i)
				f:i32(1)
				f:add()
			end, function()
				fget(f, 'frees')
				f:load(i)
				C.vlget(f)
				f:refcast(M.ref(var))
				f:structget(var, 'name')
			end)
		end)
	end)
	setk('upnames', function() f:load(ft) end)
	-- locals for debug.getlocal: { name, isparam, slot index, startpc, endpc }, params first.
	-- The main chunk's _ENV param is an upvalue in C Lua, so it's left out
	f:call(alloc.newtbl)
	f:store(lt)
	f:i32(1)
	f:store(j)
	local function lventry(name, isparam, slot, s, e)
		C.tseti(f, function() f:load(lt) end, function() f:load(j) end, function()
			local e1 = f:locals(R.tbl)
			f:call(alloc.newtbl)
			f:store(e1)
			C.tseti(f, function() f:load(e1) end, 1, name)
			C.tseti(f, function() f:load(e1) end, 2, function()
				if isparam then alloc.ltrue(f) else alloc.lfalse(f) end
			end)
			C.tseti(f, function() f:load(e1) end, 3, int(slot))
			C.tseti(f, function() f:load(e1) end, 4, int(s))
