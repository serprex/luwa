-- After a return's explist: xn & xr from it, see bcgen's Block
local function emitreturn(f, L)
	local function close()
		fget(f, 'tbcn')
		f:i32(0)
		f:call(C.tbcclose)
		f:drop()
	end
	f:load(L.xr)
	f:i32(-1)
	f:ne()
	f:iff(function()
		close()
		op(f, bc.Return)
	end, function()
		f:loadg(G.ccounts)
		f:structget(ilist, 'len')
		f:iff(function()
			f:loadg(G.cline)
			f:storeg(G.curline)
			f:load(L.xn)
			f:eqz()
			fget(f, 'tbcn')
			f:eqz()
			f:band()
			f:loadg(G.tailcalls)
			f:band()
			f:iff(function()
				-- return f(args): a tail call. The Return after it returns the results
				-- when f isn't a Lua function & gets a normal call
				C.emitchain(f, bc.ReturnCall, bc.ReturnCallVarg, function() f:i32(0xffff) end)
			end, function()
				-- call keeping all results (retc 0xffff), then return them
				C.emitchain(f, bc.Call, bc.CallVarg, function() f:i32(0xffff) end)
				close()
			end)
			op(f, bc.Return)
		end, function()
			close()
			op(f, bc.ReturnVarg)
		end)
	end)
end

