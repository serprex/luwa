					emitappend(f, L)
					-- pass 1: a keyed field after a positional one, so pass 2 has to reorder
					f:load(L.seen)
					f:iff(function()
						f:load(L.rec)
						f:refcast(M.ref(tabrec))
						f:structget(tabrec, 'spots')
						f:call(savespot)
						f:call(C.vlpush)
						C.tseti(f, function() f:loadg(G.tabs) end, function() f:load(L.key) end, function()
							f:load(L.rec)
						end)
					end)
				end),
			},
		},
		close('}', '{', line),
		act(leave),
	}},
	-- a field: 1 for a keyed one, emitted, 0 for a positional one, left held for Table
	Field = P.rule{ results = { i32 }, locals = locs(I'line', I'kind'), body = seq{
		act(function(f, L)
			enter(f, L)
			f:i32(1)
			f:store(L.kind)
		end),
		o{
			seq{'[', ExpOr, act(function(f) discharge(f, 1) f:drop() end), ']', '=', ExpOr, act(function(f)
				discharge(f, 1)
				f:drop()
				op(f, bc.TblAdd)
			end)},
			when(namefield, seq{val(lex._ident, function(f)
				C.loadk(f, function() f:loadg(cur.val) end)
			end), '=', ExpOr, act(function(f)
				discharge(f, 1)
				f:drop()
				op(f, bc.TblAdd)
			end)}),
			seq{ExpOr, act(function(f, L)
				f:i32(0)
				f:store(L.kind)
			end)},
		},
		act(leave),
	}, result = function(f, L) f:load(L.kind) end },
}

-- The operator actions
do
	local unops = { [lex._minus] = bc.Neg, [lex._not] = bc.Not, [lex._hash] = bc.Len, [lex._bnot] = bc.BNot }
	local binops = {
		[lex._plus] = bc.Add, [lex._minus] = bc.Sub, [lex._mul] = bc.Mul, [lex._div] = bc.Div, [lex._idiv] = bc.IDiv,
		[lex._pow] = bc.Pow, [lex._mod] = bc.Mod, [lex._band] = bc.BAnd, [lex._bnot] = bc.BXor, [lex._bor] = bc.BOr,
		[lex._rsh] = bc.Shr, [lex._lsh] = bc.Shl, [lex._dotdot] = bc.Concat,
		[lex._lt] = bc.CmpLt, [lex._lte] = bc.CmpLe, [lex._gt] = bc.CmpGt, [lex._gte] = bc.CmpGe, [lex._eq] = bc.CmpEq,
	}
	-- what made the value just emitted, for the op's error message: a chain's desc
	local function operanddesc(f)
		f:loadg(G.echain)
		f:loadg(G.eisop)
		f:eqz()
		f:band()
		f:iff(LV, function()
			f:loadg(G.desc)
			C.orfalse(f)
		end, function()
			alloc.lfalse(f)
		end)
	end
	local function opdone(f, L)
		setek(f, EK.stack)
		f:i32(0)
		f:storeg(G.echain)
		f:i32(1)
		f:storeg(G.eisop)
		f:refnull(M.heap.eq)
		f:storeg(G.desc)
		f:load(L.pl)
		f:storeg(G.curline)
	end
	local function emitop(f, L, map, extra)
		f:loadg(G.curline)
		f:store(L.pl)
		f:load(L.opline)
		f:storeg(G.curline)
		local ts = {}
		for t in pairs(map) do
			ts[#ts+1] = t
		end
		table.sort(ts)
		for _, t in ipairs(ts) do
			local o = map[t]
			f:load(L.op)
			f:i32(t)
			f:eq()
			f:iff(function()
				op(f, o)
			end)
		end
		if extra then
			extra()
		end
	end
	local e = G_.Exp.body
	e.onunop = function(f, L)
		local d = f:locals(LV)
		discharge(f, 1)
		f:drop()
		operanddesc(f)
		f:store(d)
		emitop(f, L, unops)
		C.opname(f, function()
			C.list(f, { function() f:load(d) end })
		end)
		opdone(f, L)
	end
	e.onleft = function(f, L)
		discharge(f, 1)
		f:drop()
		operanddesc(f)
		f:store(L.d1)
	end
	e.onbinop = function(f, L)
		local d = f:locals(LV)
		discharge(f, 1)
		f:drop()
		operanddesc(f)
		f:store(d)
		emitop(f, L, binops, function()
			f:load(L.op)
			f:i32(lex._neq)
			f:eq()
			f:iff(function()
				op(f, bc.CmpEq)
				op(f, bc.Not)
			end)
		end)
		C.opname(f, function()
			C.list(f, { function() f:load(L.d1) end, function() f:load(d) end })
		end)
		opdone(f, L)
	end
end

Rules = P.gen(G_, hooks)
for k, fn in pairs{ scopen = scopen, scclose = scclose, brkopen = brkopen, brkclose = brkclose, mkproto = mkproto,
		closefunc = closefunc, savespot = savespot, gotospot = gotospot } do
	fn.name = 'parse.' .. k
end

-- Compile src. Gives the main function, or null with the error in errs.
-- flags: 1 tail calls, 2 no debug info. h1, h2, h3: the prelude's tbcpush, tbcclose & vargunpack
local compile = func(R.str, LV, LV, i32, LV, LV, LV, LV, function(f, src, source, short, flags, h1, h2, h3)
	f:i32(0)
	f:storeg(errs.code)
	f:load(flags)
	f:i32(1)
	f:band()
	f:storeg(G.tailcalls)
	f:load(flags)
	f:i32(2)
	f:band()
	f:storeg(G.noinfo)
	f:load(h1)
	f:storeg(G.htbcpush)
	f:load(h2)
	f:storeg(G.htbcclose)
	f:load(h3)
	f:storeg(G.hvargunpack)
	f:load(source)
	f:storeg(G.source)
	f:load(short)
	f:storeg(G.short)
	for _, t in ipairs{ G.capt, G.fcapt, G.asgn, G.tabs, strs } do
		f:call(alloc.newtbl)
		f:storeg(t)
	end
	f:call(C.newil)
	f:storeg(G.ccounts)
	f:call(C.newvl)
	f:storeg(G.cdescs)
	f:block(function(caught)
		f:trytable(caught, function()
			for pass = 1, 2 do
				f:i32(pass)
				f:storeg(G.pass)
				f:call(alloc.newtbl)
				f:storeg(G.names)
				f:call(C.newvl)
				f:storeg(G.scopevars)
				f:refnull(fs)
				f:storeg(G.cfs)
				f:refnull(scope)
				f:storeg(cursc)
				f:i32(0)
				f:storeg(G.curline)
				f:refnull(M.heap.eq)
				f:storeg(G.desc)
				f:i32(0)
				f:storeg(ahas)
				f:load(src)
				f:call(_lex.init)
				f:call(tnext)
				call(f, 'Main')
			end
		end)
		f:loadg(lastproto)
		f:ret()
	end)
	f:refnull(M.heap.eq)
end)
compile.name = 'parse.compile'

return {
	compile = compile,
	errs = errs,
	E = E,
}
