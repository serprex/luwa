-- and & or: jump past the rest, leaving the value, when it decides. jop is the jump
local function shortcircuit(sub, word, jop)
	return P.rule{ locals = locs(I'line', I'j'), body = seq{
		act(function(f, L)
			enter(f, L)
			saveline(f, L)
			f:i32(-1)
			f:store(L.j)
		end),
		sub,
		m(seq{
			act(function(f, L)
				local at = f:locals(i32)
				discharge(f, 1)
				f:drop()
				-- the jumps are a list through their args till patched
				C.jump(f, jop)
				f:tee(at)
				f:load(L.j)
				f:call(C.setarg)
				f:load(at)
				f:store(L.j)
			end),
			word,
			sub,
		}),
		act(function(f, L)
			local nx = f:locals(i32)
			f:load(L.j)
			f:i32(-1)
			f:ne()
			f:iff(function()
				discharge(f, 1)
				f:drop()
				f:loop(function(loop)
					f:load(L.j)
					f:i32(-1)
					f:ne()
					f:iff(function()
						f:load(L.j)
						f:call(C.readarg)
						f:store(nx)
						f:load(L.j)
						pc(f)
						f:call(C.patch)
						f:load(nx)
						f:store(L.j)
						f:br(loop)
					end)
				end)
				f:i32(0)
				f:storeg(G.echain)
			end)
			if word == 'or' then
				f:load(L.line)
				f:storeg(G.epad)
			end
			leave(f, L)
		end),
	}}
end

