			f:iff(function()
				f:loadg(G.cline)
				f:storeg(G.curline)
				C.emitchain(f, bc.AppendCall, bc.AppendCallVarg, nm1)
			end, function()
				op(f, bc.AppendVarg, nm1)
			end)
		end)
	end)
end

