#!/usr/bin/env lua
-- Builds a small module that uses WasmGC features, to test make.lua on its own.
-- Run from the repo root: lua scripts/maketest.lua out.wasm (scripts/maketest.js does this & runs it)
package.path = 'rt/?.lua;' .. package.path
local M = require 'make'
local i32, i64, f64 = M.i32, M.i64, M.f64

-- linked list of i64. A lone type can refer to itself
local node = M.struct(nil, { name = 'node' })
node:define{ { i64, name = 'val' }, { M.refnull(node), mut = true, name = 'next' } }

-- open box type with a float box under it
local box = M.struct({}, { final = false, name = 'box' })
local fbox = M.struct({ { f64, name = 'val' } }, { super = box, name = 'fbox' })

-- table with an array part, in an explicit rec group
local tbl = M.struct(nil, { name = 'tbl' })
local vals = M.array(M.mut(M.anyref), { name = 'vals' })
tbl:define{ { M.ref(vals), mut = true, name = 'arr' }, { M.refnull(tbl), mut = true, name = 'meta' } }
M.rec(tbl, vals)

local bytes = M.array(M.mut(M.i8), { name = 'bytes' })
local hellodata = M.passivedata({ 104, 101, 108, 108, 111 })

local gtbl = M.global(M.refnull(tbl), true)
local gvals = M.global(M.ref(vals), false, function(f)
	f:i32(2)
	f:arraynewdefault(vals)
end)

-- build list n..1, then sum it
local sumlist = M.func(i32, i64, function(f, n)
	local l = f:locals(M.refnull(node))
	local s = f:locals(i64)
	f:loop(function(loop)
		f:load(n)
		f:iff(function()
			f:load(n)
			f:i64extendu()
			f:load(l)
			f:structnew(node)
			f:store(l)
			f:load(n)
			f:i32(1)
			f:sub()
			f:store(n)
			f:br(loop)
		end)
	end)
	f:block(function(done)
		f:loop(function(loop)
			f:load(l)
			f:bronnull(done)
			f:structget(node, 'val')
			f:load(s)
			f:add()
			f:store(s)
			f:load(l)
			f:structget(node, 'next')
			f:store(l)
			f:br(loop)
		end)
	end)
	f:load(s)
end)

-- two results
local divmod = M.func(i32, i32, { i32, i32 }, function(f, a, b)
	f:load(a)
	f:load(b)
	f:divs()
	f:load(a)
	f:load(b)
	f:rems()
end)

-- multi value block: swap two values
local swapsub = M.func(i32, i32, i32, function(f, a, b)
	f:load(a)
	f:load(b)
	f:block(M.functype({ i32, i32 }, { i32, i32 }), function()
		local t = f:locals(i32)
		f:store(t)
		f:store(a)
		f:load(t)
		f:load(a)
	end)
	f:sub()
end)

local mkfbox = M.func(f64, M.anyref, function(f, x)
	f:load(x)
	f:structnew(fbox)
end)

-- 0 null, 1 i31, 2 fbox, 3 anything else
local classify = M.func(M.anyref, i32, function(f, x)
	f:load(x)
	f:refisnull()
	f:iff(function()
		f:i32(0)
		f:ret()
	end)
	f:block(M.ref(fbox), function(isf)
		f:load(x)
		f:broncast(isf, M.anyref, M.ref(fbox))
		f:reftest(M.ref(M.heap.i31))
		f:iff(function()
			f:i32(1)
			f:ret()
		end)
		f:i32(3)
		f:ret()
	end)
	f:structget(fbox, 'val')
	f:drop()
	f:i32(2)
end)

-- len * 1000 + 2nd byte of "hello"
local hello = M.func(i32, function(f)
	local a = f:locals(M.refnull(bytes))
	f:i32(0)
	f:i32(5)
	f:arraynewdata(bytes, hellodata)
	f:store(a)
	f:load(a)
	f:arraylen()
	f:i32(1000)
	f:mul()
	f:load(a)
	f:i32(1)
	f:arrayget(bytes, false)
	f:add()
end)

local twice = M.func(i32, i32, function(f, x)
	f:load(x)
	f:i32(2)
	f:mul()
end)
local apply = M.func(i32, i32, function(f, x)
	f:load(x)
	f:reffunc(twice)
	f:callref(M.functype({ i32 }, i32))
end)

local fact = M.func(i64, i64, i64, function(f, n, acc)
	f:load(n)
	f:eqz()
	f:iff(function()
		f:load(acc)
		f:ret()
	end)
	f:load(n)
	f:i64(1)
	f:sub()
	f:load(acc)
	f:load(n)
	f:mul()
end)
-- fact's body needs itself, so finish it after it exists
local factbody = fact.bgen
fact.bgen = function(f, n, acc)
	factbody(f, n, acc)
	f:retcall(fact)
end

local tblset = M.func(i32, M.anyref, M.void, function(f, i, v)
	f:loadg(gtbl)
	f:refisnull()
	f:iff(function()
		f:i32(4)
		f:arraynewdefault(vals)
		f:refnull(tbl)
		f:structnew(tbl)
		f:storeg(gtbl)
	end)
	f:loadg(gtbl)
	f:structget(tbl, 'arr')
	f:load(i)
	f:load(v)
	f:arrayset(vals)
end)
local tblget = M.func(i32, M.anyref, function(f, i)
	f:loadg(gtbl)
	f:structget(tbl, 'arr')
	f:load(i)
	f:arrayget(vals)
end)

local glen = M.func(i32, function(f)
	f:loadg(gvals)
	f:arraylen()
end)

local pick = M.func(i32, M.anyref, M.anyref, M.anyref, function(f, c, a, b)
	f:load(a)
	f:load(b)
	f:load(c)
	f:select()
end)

local mod = M.mod()
mod:export('sumlist', sumlist)
mod:export('divmod', divmod)
mod:export('swapsub', swapsub)
mod:export('mkfbox', mkfbox)
mod:export('classify', classify)
mod:export('hello', hello)
mod:export('apply', apply)
mod:export('fact', fact)
mod:export('tblset', tblset)
mod:export('tblget', tblget)
mod:export('glen', glen)
mod:export('pick', pick)
local chunks = mod:compile()
io.open(assert(arg[1], 'usage: maketest.lua out.wasm'), 'wb'):write(table.unpack(chunks)):close()